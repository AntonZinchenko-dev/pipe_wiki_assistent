import type { Dataset } from '@/shared/api/contracts'

/**
 * Таблица сервиса — в файл, который откроется в Excel с первого раза.
 *
 * Здесь три решения, и каждое из них — про русский Excel, а не про
 * «правильный CSV»:
 *
 * РАЗДЕЛИТЕЛЬ — ТОЧКА С ЗАПЯТОЙ. В русской локали десятичный знак —
 * запятая, поэтому запятая же в роли разделителя полей рвёт каждое дробное
 * число на два столбца. Excel это не чинит, он честно показывает кашу.
 *
 * ЧИСЛА С ЗАПЯТОЙ. Иначе «97.7» приезжает текстом, и по столбцу нельзя ни
 * отсортировать, ни посчитать среднее — то есть файл открывается, но не
 * работает.
 *
 * BOM В НАЧАЛЕ. Без него Excel читает UTF-8 как однобайтную кодировку, и
 * весь русский текст превращается в «ÐÑÑÐ±Ð°». Три байта, которые
 * отделяют работающий файл от жалобы «у вас кракозябры».
 *
 * Выгружаем РОВНО ТО, ЧТО НА ЭКРАНЕ: те же колонки и те же строки. В
 * ответе сервиса полей больше, но человек их не видел, и файл, в котором
 * столбцов вдвое больше таблицы, читается как чужой.
 */

const SEPARATOR = ';'
const BOM = '﻿'

function field(value: unknown): string {
  if (value === null || value === undefined) return ''
  const text =
    typeof value === 'number' ? String(value).replace('.', ',') : String(value)
  // Кавычки, разделитель и перенос внутри значения ломают разбор, если их
  // не закрыть. Внутренняя кавычка удваивается — так велит RFC 4180, и так
  // ждёт Excel.
  return /["\n\r;]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text
}

export function datasetToCsv(data: Dataset): string {
  const header = data.columns.map((column) =>
    // Единица измерения в шапке, а не в каждой ячейке: «Выработка, %» —
    // это столбец чисел, «97,7 %» — это столбец текста.
    field(column.unit ? `${column.title}, ${column.unit}` : column.title),
  )
  const rows = data.rows.map((row) =>
    data.columns.map((column) => field(row[column.key])).join(SEPARATOR),
  )
  return BOM + [header.join(SEPARATOR), ...rows].join('\r\n') + '\r\n'
}

/**
 * Имя файла: что за таблица, когда снята и её метка.
 *
 * Метка нужна затем, что «топ-5 труб» человек выгрузит трижды за утро, и
 * три файла с одинаковым именем в папке «Загрузки» — это три файла, про
 * которые непонятно, какой свежий.
 */
export function datasetFileName(data: Dataset): string {
  const name = `${data.title} ${data.handle}`
    .replace(/[\\/:*?"<>|]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  return `${name}.csv`
}

import { readFileSync } from 'node:fs'
import path from 'node:path'
import { describe, expect, it } from 'vitest'

/**
 * Маркировка «отвечает ИИ» обязана быть постоянной.
 *
 * Требование из чек-листа готовности к проду, и оно там не ради
 * формальности: человек имеет право знать, с кем разговаривает, особенно
 * когда собеседник ссылается на документы и звучит уверенно.
 *
 * Проверяем исходником, а не рендером, по той же причине, по которой так
 * проверяется запрет `dangerouslySetInnerHTML`: нас интересует не то, что
 * компонент показал в одном сценарии, а то, что маркировку нельзя убрать
 * незаметно. Абзац на пустом экране этому требованию не отвечает — он
 * исчезает ровно тогда, когда человек начинает верить ответам.
 */
describe('маркировка «отвечает ИИ»', () => {
  const source = readFileSync(
    path.resolve(__dirname, 'ChatThread.tsx'),
    'utf-8',
  )

  it('стоит вне ветки пустого экрана', () => {
    // Ветка пустого экрана — от проверки на ноль обменов до `) : (`,
    // где начинается ветка «диалог уже идёт». Маркировка обязана быть
    // снаружи: внутри она исчезнет после первого же вопроса.
    const start = source.indexOf('exchanges.length === 0')
    const end = source.indexOf(') : (', start)
    const emptyBranch = source.slice(start, end)

    expect(source).toContain('Отвечает языковая модель')
    expect(emptyBranch).not.toContain('Отвечает языковая модель')
  })

  it('называет вещи своими именами', () => {
    expect(source).toMatch(/языковая модель/)
    expect(source).toMatch(/сверяйтесь|проверяйте/)
  })
})

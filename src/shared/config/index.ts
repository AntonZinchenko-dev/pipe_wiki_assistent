/** Настройки интерфейса. Всё, что не про адрес бэкенда, живёт здесь. */

export const config = {
  /**
   * Как часто перерисовывать поток. Модель отдаёт десятки токенов в секунду;
   * без батчинга каждый токен вызывал бы отдельный ререндер, и страница
   * тормозила бы ровно в тот момент, когда человек читает.
   *
   * Ноль означает «раз в кадр анимации» — см. features/ask-assistant.
   */
  streamFlushMs: 0,

  /** Сколько последних вопросов держим в истории диалога на экране. */
  maxThreadItems: 20,

  /**
   * Сколько последних пар «вопрос — ответ» отправляем как память диалога.
   *
   * Сервер режет историю по бюджету токенов сам — клиенту верить нельзя, —
   * а здесь предел нужен для другого: чтобы не гонять по сети то, что на
   * той стороне всё равно выбросят. Шесть пар — это примерно один экран
   * разговора, дальше ссылки вроде «а сколько их?» встречаются редко.
   */
  historyTurns: 6,
} as const

/**
 * Диалог — это то, что помнит ассистент.
 *
 * Границы памяти совпадают с границами диалога, и это не техническая
 * деталь, а обещание пользователю: «новый диалог» означает «забудь всё
 * предыдущее». Если бы память тянулась поверх диалогов, кнопка «новый»
 * ничего бы не значила, а объяснить, почему ассистент вспомнил вопрос
 * недельной давности, было бы нечем.
 */
export type Thread = {
  id: string
  /** Заголовок = первый вопрос. Отдельного поля для имени человек не просил. */
  title: string
  createdAt: number
  updatedAt: number
  /**
   * Памятка по свёрнутой части разговора.
   *
   * Считает её сервер (у него модель), хранит браузер (у него диалоги), и
   * с каждым запросом она уезжает обратно вместо десятка свёрнутых реплик.
   * Сервер при этом остаётся без состояния.
   *
   * Зачем она, если есть бюджет токенов: бюджет отвечает, сколько влезет,
   * а не что важно. Когда разговор перерастает бюджет, отрезается хвост —
   * и первый вопрос, в котором обычно задан предмет всего разговора,
   * исчезает первым. Со стороны это выглядит как «ассистент вдруг
   * поглупел».
   */
  summary: string
  /**
   * До какого момента разговор уже свёрнут.
   *
   * Обмены не старше этой отметки в переписку больше не отправляются: они
   * учтены в памятке. Хранится время, а не число реплик, потому что
   * обмены удаляются по переполнению — счётчик разъехался бы молча.
   */
  foldedAt: number
}

export const NEW_TITLE = 'Новый диалог'
export const TITLE_CHARS = 60

export function newThread(title: string): Thread {
  const now = Date.now()
  return {
    id: `t-${now}-${Math.random().toString(36).slice(2, 8)}`,
    title: title.trim().slice(0, TITLE_CHARS) || NEW_TITLE,
    createdAt: now,
    updatedAt: now,
    summary: '',
    foldedAt: 0,
  }
}

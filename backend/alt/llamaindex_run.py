def row_for(
    *,
    question: Question,
    answer_text: str,
    retrieved_docs: list[str],
    chunk_texts: list[str],
    context_text: str,
    latency_ms: float,
) -> RowResult:
    """Строка прогона в НАШЕМ формате — чтобы работали все наши команды.

    Ключевое решение здесь — что оставить НЕИЗМЕРЕННЫМ.

    У образца нет нашей схемы ответа: он отдаёт свободный текст, без ярлыка
    статуса и без ссылок на фрагменты. Значит `status_ok` и проверка цитат к
    нему неприменимы, и в эти графы идёт «не измерено», а не ноль.

    Разница принципиальная. Ноль непрошедших цитат читается как безупречная
    работа, а означает «мы не проверяли». Это ровно та ошибка, которую мы уже
    ловили у себя: `get(ключ, 0)` превращал невыставленную метрику в отличный
    результат. Повторить её в сравнении с чужой системой значило бы подтасовать
    сравнение в свою пользу — и подтасовать незаметно.
    """
    score = score_retrieval(
        retrieved_docs=retrieved_docs,
        relevant_docs=set(question.docs),
        context_text=context_text,
        must_contain=question.must_contain,
        best_cosine=0.0,        # образец не отдаёт косинус наружу
        passed_floor=True,      # абсолютного порога у него нет вообще
        chunk_texts=chunk_texts,
        cosines=[],
    )

    return RowResult(
        question_id=question.id,
        question=question.question,
        type=question.type,
        difficulty=question.difficulty,
        answerable=question.answerable,
        critical=question.critical,
        split=question.split,
        retrieved_docs=retrieved_docs[:10],
        retrieval=score.as_dict(),
        # Статус НЕ ИЗМЕРЕН: у образца нет схемы ответа.
        status="",
        status_ok=None,
        answer=answer_text[:2000],
        # Цитаты НЕ ИЗМЕРЕНЫ по той же причине. Нули здесь — не результат.
        citations_total=0,
        citations_failed=0,
        schema_valid=None,
        answer_contains=(
            answer_contains(answer_text, question.answer_needles)
            if question.answerable
            else None
        ),
        # Язык ответа — измеряется, в отличие от статуса и цитат.
        #
        # Разница принципиальная и стоит одной строки объяснения. Статус и
        # цитаты у образца мерить НЕЧЕМ: своей схемы ответа у него нет, и
        # выставлять туда что-нибудь было бы выдумкой. А язык есть у любого
        # текста, чьей бы схемой он ни был порождён, — значит здесь прочерк
        # был бы не честностью, а пропуском.
        #
        # Именно эта графа и вскрыла главное различие стеков: встроенный
        # промпт фреймворка английский, языка ответа не задаёт, и на коротких
        # вопросах да/нет модель уходит в свой родной.
        answer_language=answer_language(answer_text),
        latency_ms=round(latency_ms, 1),
    )



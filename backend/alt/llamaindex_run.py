"""Тот же ассистент на LlamaIndex — как измерительный образец.

Зачем это нужно, если своя реализация работает и измерена.

Три причины, и первая самая важная.

ПЕРВАЯ: проверка нас самих. Все наши цифры получены нашим же стендом на нашей
же системе. Если готовый фреймворк «из коробки» окажется лучше — это надо
знать, и это самое полезное, что может выясниться. Сравнение со стороной,
которую мы не писали, — единственный способ отличить «мы сделали хорошо» от
«мы измерили по-своему».

ВТОРАЯ: честный ответ на вопрос «зачем руками». Руками мы писали затем, что
почти каждый найденный дефект жил ВНУТРИ слоя, который фреймворк закрывает:
порядок полей в схеме, константа слияния при нашей глубине списков, карта
позиций для вырезания цитаты. Утверждение «фреймворк это спрятал бы» стоит
ровно столько же, сколько его проверка. Здесь оно проверяется.

ТРЕТЬЯ, прикладная: требования вакансий содержат эти названия прямым текстом,
и «я читал про LlamaIndex» — не то же самое, что «я сравнил его со своей
реализацией на 113 размеченных вопросах».

--------------------------------------------------------------------------
ЧТО СРАВНИВАЕТСЯ, А ЧТО НЕТ — читать до того, как смотреть цифры

Образец собран ИЗ КОРОБКИ: стандартный чтец документов, стандартная нарезка,
стандартное слияние двух выдач, стандартный сборщик ответа. Это сознательно:
вопрос стоит «нужен ли фреймворк», а не «можно ли на фреймворке написать то же
самое» (можно, разумеется).

Отсюда главное ограничение, и его нельзя забывать при чтении таблицы:
сравниваются ЦЕЛЫЕ СТЕКИ. Разница в цифрах не говорит, какой слой её создал —
извлечение из PDF, нарезка, поиск или промпт. Чтобы это узнать, нужен разбор
по слоям, а у нас он есть только для своей системы (scripts/eval.py why).

Что уравнено намеренно:
  - тот же корпус, те же документы;
  - тот же золотой набор и та же разметка;
  - те же модели: qwen2.5:7b для ответа, bge-m3 для эмбеддингов;
  - температура ноль;
  - та же глубина выдачи и то же число фрагментов в контексте.

Что НЕ измеряется у образца и потому честно помечается как неизмеренное:
  - статус ответа (ответил / не найдено / нужно уточнение) — у образца нет
    нашей схемы ответа, он отдаёт свободный текст;
  - проверка цитат — по той же причине.
  Написать ноль в эти графы было бы ложью в нашу пользу: ноль непрошедших
  цитат читается как безупречность, а означает «мы не проверяли».

--------------------------------------------------------------------------
ПРЕДСКАЗАНИЕ, СДЕЛАННОЕ ДО ПЕРВОГО ПРОГОНА

Записываю заранее, чтобы потом не подгонять объяснение под результат.

`QueryFusionRetriever` сливает выдачи тем же RRF и с той же константой по
умолчанию — k = 60. Мы измерили, что при глубине списков 24 это гарантирует
победу «нашлось в обоих списках» над любым местом: 2/(60+24) больше, чем
1/(60+1). Значит у образца ожидается ТА ЖЕ слабость: нужный фрагмент доезжает
до модели, но стоит не первым. Конкретно: `context_hit` близкий к нашему,
`chunk_top1` ниже наших 0.866 и ближе к нашим прежним 0.821.

Если так и выйдет — это лучший возможный аргумент в пользу того, что читать
константы чужой библиотеки надо. Если не выйдет — значит у них есть что-то,
чего мы не поняли, и это надо найти и забрать.
"""


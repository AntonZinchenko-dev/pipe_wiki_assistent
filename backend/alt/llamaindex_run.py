# Сколько запросов делает слияние. Один — значит переписывания запроса нет.
#
# Важная деталь про «из коробки»: по умолчанию QueryFusionRetriever делает
# ЧЕТЫРЕ запроса — он просит модель переформулировать вопрос и ищет по всем
# вариантам. Это переписывание запроса, которого у нас нет и которое стоит у
# нас в чек-листе как несделанное.
#
# Поэтому значение вынесено в параметр, а не зашито:
#   1 — сравнение поиска честное, стек против стека без лишней функции;
#   4 — поведение по умолчанию, и заодно БЕСПЛАТНЫЙ ЗАМЕР того, сколько даёт
#       переписывание запроса, — чужой реализацией, на нашем наборе.
# Второе интересно само по себе: q034 («какие методы есть на апихе папасса»)
# не доходит до контекста именно из-за разговорных слов, и если четыре
# варианта запроса его вытащат, мы узнаем цену этой функции, не написав её.
DEFAULT_FUSION_QUERIES = 1


def corpus_files(corpus_dir: Path) -> list[Path]:
    """Файлы корпуса в устойчивом порядке.

    Отдельная функция — чтобы её можно было проверить тестом БЕЗ установленного
    LlamaIndex: «нашлись все шестнадцать документов и все они есть в карте
    doc_id» проверяется обычным тестом стенда, а не первым двадцатиминутным
    прогоном через модель.

    Сортировка не косметика. Порядок документов влияет на нумерацию узлов в
    индексе, а `glob` порядок не гарантирует — то есть без сортировки два
    прогона на одной машине могли бы разойтись по причине, не имеющей
    отношения к предмету измерения.
    """
    files = sorted(path for path in corpus_dir.glob("*.md") if path.is_file())
    if not files:
        raise RuntimeError(f"в {corpus_dir} не нашлось документов .md")
    return files


def build_engine(
    *,
    settings: Settings,
    corpus_dir: Path,
    fusion_queries: int = DEFAULT_FUSION_QUERIES,
):
    """Собирает образец. Тяжёлые импорты внутри — чтобы стенд работал без них.

    Модуль обязан импортироваться на машине, где LlamaIndex не установлен:
    иначе тесты нашего стенда упадут из-за зависимости, которая нужна одному
    вспомогательному сценарию. Это то же правило, что и с зависимостями в
    requirements: чужое дерево не должно становиться обязательным.
    """
    from llama_index.core import Document
    from llama_index.core import Settings as LlamaSettings
    from llama_index.core import VectorStoreIndex
    from llama_index.core.node_parser import SentenceSplitter
    from llama_index.core.query_engine import RetrieverQueryEngine
    from llama_index.core.retrievers import QueryFusionRetriever
    from llama_index.embeddings.ollama import OllamaEmbedding
    from llama_index.llms.ollama import Ollama
    from llama_index.retrievers.bm25 import BM25Retriever

    # Модели — ТЕ ЖЕ, что у нас, и температура тот же ноль. Без этого
    # сравнение измеряло бы разницу моделей, а не разницу стеков.
    LlamaSettings.llm = Ollama(
        model=settings.ollama_chat_model,
        base_url=settings.ollama_url,
        temperature=settings.temperature,
        request_timeout=settings.request_timeout_s,
    )
    LlamaSettings.embed_model = OllamaEmbedding(
        model_name=settings.ollama_embed_model,
        base_url=settings.ollama_url,
    )
    # Нарезка по умолчанию — предложениями с перекрытием. Наша структурная
    # нарезка по заголовкам здесь сознательно НЕ повторяется: смысл образца в
    # том, что он собран из готовых частей.
    splitter = SentenceSplitter(chunk_size=700, chunk_overlap=80)
    LlamaSettings.node_parser = splitter

    # Файлы читаем САМИ, а не через SimpleDirectoryReader. Две причины, и обе
    # выяснились на первом же запуске.
    #
    # ПЕРВАЯ, практическая: SimpleDirectoryReader живёт в llama-index-core, но
    # без пакета llama-index-readers-file падает на первом же файле
    # («`llama-index-readers-file` package not found»). Этот пакет тянет за
    # собой pypdf, beautifulsoup, striprtf и ещё десяток библиотек — ради того,
    # чтобы прочитать текстовый файл в кодировке UTF-8. Для образца, который
    # существует ради одного сравнения, это плохая сделка.
    #
    # ВТОРАЯ, и она важнее: читалка markdown у них НЕ нейтральна. Она вырезает
    # ссылки и картинки и режет документ по заголовкам. То есть добавила бы к
    # сравнению ещё один слой преобразования текста — и мы бы не знали, чья
    # разница видна в цифрах: поиска или читалки.
    #
    # Аналогия: сравниваем две мясорубки. Мясо в обе надо положить одинаковое.
    # Если одна идёт в комплекте с тёркой, мясо через тёрку прогонять не надо —
    # иначе меряется тёрка.
    #
    # Поэтому: plain text как есть, имя файла в метаданных (по нему считается
    # doc_id), а нарезку делает SentenceSplitter — то есть ровно тот слой
    # образца, который мы и хотели измерить.
    paths = corpus_files(corpus_dir)
    documents = [
        Document(
            text=path.read_text(encoding="utf-8"),
            metadata={"file_name": path.name},
        )
        for path in paths
    ]

    # Сначала РЕЖЕМ, потом строим индекс из готовых узлов — а не наоборот.
    #
    # Так оба поиска гарантированно работают по ОДНОМУ И ТОМУ ЖЕ списку узлов.
    # Если индекс собирать из документов, узлы придётся потом достать у него из
    # хранилища, и список для BM25 получится «тем же самым» только по нашей
    # вере в то, как устроено хранилище внутри. А вся арифметика слияния по
    # рангам держится на том, что оба списка про одни и те же куски текста:
    # разойдись они — и RRF сливал бы несравнимое, а мы бы увидели просто
    # «цифры похуже» и никогда не поняли причину.
    nodes = splitter.get_nodes_from_documents(documents)
    index = VectorStoreIndex(nodes)

    vector_retriever = index.as_retriever(similarity_top_k=settings.search_top_k)
    keyword_retriever = BM25Retriever.from_defaults(
        nodes=nodes, similarity_top_k=settings.search_top_k
    )

    fusion = QueryFusionRetriever(
        [vector_retriever, keyword_retriever],
        similarity_top_k=settings.context_max_fragments,
        num_queries=fusion_queries,
        mode="reciprocal_rerank",
        use_async=False,
    )
    return RetrieverQueryEngine.from_args(fusion), len(nodes)


def doc_id_of(node) -> str:
    """Идентификатор документа из метаданных узла.

    У нас `doc_id` стоит в шапке markdown-файла (`doc_id: PP-FE`), а чтец
    LlamaIndex такие поля не разбирает — он кладёт имя файла. Поэтому берём
    имя файла и достаём из него идентификатор по той же карте, что в корпусе.

    Иначе метрики поиска считались бы по разным ключам и всегда давали бы
    ноль — то есть образец выглядел бы катастрофически плохим по причине,
    к нему не относящейся. Такую ошибку легко не заметить: цифра «recall 0.0»
    выглядит как результат, а является поломкой сравнения.
    """
    name = (node.metadata or {}).get("file_name", "")
    return FILE_TO_DOC.get(name, name)



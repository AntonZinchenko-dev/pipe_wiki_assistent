"""Тесты мутатора: порча обязана быть ЗАВЕДОМО неверной.

Весь метод держится на этом условии. Если мутант окажется верным ответом,
прибор, не поднявший тревогу, будет наказан за правильную работу — и я запишу
это ему в слепоту. Такой «замер» хуже отсутствующего: он уверенно указывает не
туда.
"""

from eval.mutate import FALSE_CLAIM, mutants_for
from eval.metrics import answer_contains


def kinds(**kwargs) -> dict[str, str]:
    return {m.kind: m.answer for m in mutants_for(**kwargs)}


def test_truncation_is_not_used_as_a_mutant():
    """Обрезка ответа убрана, потому что она не всегда ошибка.

    Первая версия мутатора резала ответ до первого предложения. На первом же
    примере получилось: «Новичкам токены к боевому контуру не выдаются» —
    факт сохранён целиком, отброшено лишь пояснение. То есть ПОЛНЫЙ И ВЕРНЫЙ
    ответ, выданный за порчу.
    """
    made = kinds(
        question="дают ли новичку токен к боевому контуру",
        answer="Новичкам токены не выдаются. Он нужен только для эксплуатации.",
        needles=["не выдаются"],
    )
    assert "обрезка" not in made


def test_number_is_changed_only_when_the_number_is_the_fact():
    """Портим число, только если оно входит в разметку.

    Иначе «РЛ-9.2» превращается в «РЛ-8.2», ответ остаётся верным по
    существу, и прибор наказывается за отсутствие ложной тревоги.
    """
    made = kinds(
        question="обязателен ли постмортем",
        answer="Да, постмортем обязателен для S1 и S2 по регламенту РЛ-9.2.",
        needles=["обязателен"],  # чисел в разметке нет
    )
    assert "число" not in made

    made = kinds(
        question="какой порог по усталости считается аварийным",
        answer="Аварийный порог по усталости составляет 80 %.",
        needles=["80"],
    )
    assert made["число"] == "Аварийный порог по усталости составляет 8 %."


def test_appended_lie_is_invisible_to_the_substring_check():
    """Приписка — главный вид порчи: подстрока к ней слепа ПО ПОСТРОЕНИЮ.

    Верный ответ остаётся на месте целиком, все ожидаемые слова в нём есть,
    проверка довольна. А рядом дописано утверждение, которого в документах
    нет и которое противоречит регламенту. Так выглядит самая опасная ошибка
    справочной системы: правильный ответ плюс уверенная отсебятина.

    Именно на этом виде и решается, окупает ли судья свои вызовы.
    """
    needles = ["80"]
    answer = "Аварийный порог по усталости составляет 80 %."
    made = kinds(
        question="какой порог по усталости считается аварийным",
        answer=answer,
        needles=needles,
    )
    assert FALSE_CLAIM in made["приписка"]
    # Верный ответ проходит проверку — и испорченный тоже. В этом и суть.
    assert answer_contains(answer, needles) is True
    assert answer_contains(made["приписка"], needles) is True


def test_refusal_and_echo_are_caught_by_the_substring_check():
    """А эти две порчи бесплатная проверка обязана ловить сама.

    Если она перестанет их ловить, значит разметка снова стала слепой — ровно
    те два дефекта, которые мы сегодня чинили: разметка, срабатывающая на
    отказе, и разметка, проходящая повтором вопроса.
    """
    needles = ["80"]
    made = kinds(
        question="какой порог по усталости считается аварийным",
        answer="Аварийный порог по усталости составляет 80 %.",
        needles=needles,
    )
    assert answer_contains(made["отказ"], needles) is False
    assert answer_contains(made["эхо"], needles) is False


def test_negation_flip_inverts_the_meaning():
    """Переворот отрицания — самая опасная ошибка по смыслу и самая незаметная по форме.

    «Токен новичку не выдаётся» против «выдаётся» — это разница между
    соблюдённым регламентом и инцидентом безопасности, а отличаются ответы
    двумя буквами.
    """
    made = kinds(
        question="можно ли выкладывать в пятницу",
        answer="Выкладка в пятницу запрещена, кроме исправления действующей аварии.",
        needles=["запрещ"],
    )
    assert made["отрицание"].startswith("Выкладка в пятницу разрешена")
    assert answer_contains(made["отрицание"], ["запрещ"]) is False

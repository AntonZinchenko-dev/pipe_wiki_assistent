"""Тесты вокруг нумерации в промпте судьи.

Один дефект, но показательный: прибор выбросил четыре ВЕРНЫХ измерения из-за
нашей собственной путаницы, и в отчёте это выглядело как неисправность судьи.
"""

import re


def test_citation_marks_are_stripped_before_judging():
    """Ссылки из ответа нельзя показывать судье: они путают нумерацию.

    Ответ системы размечен ссылками на фрагменты её КОНТЕКСТА: «...не более 14
    дней [4]». Выдержки судье мы нумеруем заново, своим счётом — их две или
    три. Судья видит «[4]» в ответе, принимает за номер выдержки и ссылается
    на выдержку [4], которой не существует.

    Так и вышло: четыре вердикта из 96 отброшены с причиной «судья сослался
    на выдержку [4], которой нет (их 2)». Все четыре были верны, а их
    обоснования дословно цитировали настоящий текст документа.

    Аналогия: дать эксперту документ, где абзацы пронумерованы дважды —
    типографски и от руки на полях, — и требовать ссылок «по номеру абзаца».
    Эксперт не виноват.
    """
    from eval.judge import _CITATION_MARK

    answer = "Роль data-admin выдаётся на срок не более 14 дней [4] и только под задачу [12]."
    cleaned = _CITATION_MARK.sub("", answer)
    assert "[4]" not in cleaned
    assert "[12]" not in cleaned
    assert "не более 14 дней" in cleaned
    # Смысл не тронут: убираем только разметку ссылок.
    assert cleaned == "Роль data-admin выдаётся на срок не более 14 дней и только под задачу."


def test_only_citation_marks_are_stripped():
    """Числа в квадратных скобках внутри текста документа тоже уйдут.

    Это осознанная плата: отличить «[4]» — нашу ссылку от «[4]» в тексте
    документа невозможно, а цена ошибки несимметрична. Лишняя ссылка ломает
    измерение целиком, потерянные скобки в редком документе — нет.
    """
    from eval.judge import _CITATION_MARK

    assert _CITATION_MARK.sub("", "порог [0.62] и предел") == "порог [0.62] и предел"
    assert _CITATION_MARK.sub("", "шаг [1] готов") == "шаг готов"


def test_judge_prompt_has_no_citation_marks():
    """Проверка на уровне кода: в промпт идёт очищенный ответ.

    Тест смотрит исходник, потому что вызвать судью без модели нельзя. Он
    слабый и честнее отсутствующего: ломается, если очистку уберут.
    """
    from pathlib import Path

    source = (Path(__file__).resolve().parent.parent / "eval" / "judge.py").read_text(
        encoding="utf-8"
    )
    verdict = source[source.index("async def verdict("):]
    assert "_CITATION_MARK.sub" in verdict
    assert re.search(r"Ответ системы:\\n\{cleaned", verdict), (
        "в промпт судьи должен идти очищенный ответ, а не исходный"
    )


def test_labeller_sees_the_source_but_not_the_verdict():
    """Человеку показываем ДОКУМЕНТ и скрываем мнение судьи.

    Разница принципиальная, и я её сначала не разделил. Вердикт судьи —
    мнение: увидев его до решения, человек соглашается чаще, и каппа измерит
    силу подсказки вместо качества судьи. Выдержка из документа — источник,
    по которому и надо судить; скрывать его значит требовать оценки по
    памяти.

    Цена ошибки измерена. Из восьми расхождений два оказались промахами
    человека по документу: он отметил неверными ответы «аварийный порог 80 %»
    и «пороги 40 / 70 %», тогда как в регламенте стоит «50 % внимание и 80 %
    авария», а в постмортеме — «40 %» и «70 %». Оба ответа были верны.
    Разметка — точка отсчёта для всех приборов, и ошибки в ней дороже
    ошибок в самих приборах.

    Аналогия: проверять контрольную по памяти, без задачника под рукой.
    Проверяющий добросовестен, а часть верных решений зачёркнута.
    """
    from pathlib import Path

    source = (Path(__file__).resolve().parent.parent / "scripts" / "eval.py").read_text(
        encoding="utf-8"
    )
    block = source[source.index("def cmd_label("):]
    block = block[: block.index("\ndef ")]

    assert "что написано в документах" in block, "человеку не показывают источник"
    assert "args.show_judge" in block, "вердикт судьи обязан быть скрыт по умолчанию"
    # И скрыт именно по умолчанию, а не «если попросят показать».
    assert 'action="store_true"' in source[source.index('"--show-judge"'):][:200]

def test_gate_watches_questions_by_name_not_only_averages():
    """Гейт обязан ловить ОБМЕН: один вопрос сломался, другой починился.

    Главный урок прогонов: непрошедших цитат было 7 и стало 7, а состав
    сменился наполовину. Среднее не шевельнулось, и по нему всё выглядело
    стабильным. То же может пройти и через гейт по средним: вопрос A потерял
    нужный фрагмент, вопрос B приобрёл, дельта ноль, проверка зелёная.

    Тест проверяет сам код гейта на наличие поимённого сравнения — не средних.
    Проверять текстом приходится потому, что гейт устроен как команда: он сам
    делает прогон, и вызвать его в тесте без модели и индекса нельзя. Это
    слабый тест, и он честнее отсутствующего: он ломается, если поимённую
    проверку уберут.
    """
    from pathlib import Path

    source = (Path(__file__).resolve().parent.parent / "scripts" / "eval.py").read_text(
        encoding="utf-8"
    )
    gate = source[source.index("async def _gate("):]
    gate = gate[: gate.index("\ndef ", 1) if "\ndef " in gate else len(gate)]

    assert "потеряли контекст" in gate, "гейт не сравнивает вопросы поимённо"
    assert "chunk_top1" in gate, "гейт не следит за метрикой, у которой есть запас"
    assert "на потолке" in gate, "гейт молчит о том, что насыщенная метрика не сторожит"


def test_fusion_settings_are_part_of_the_run_fingerprint():
    """Вес ключевого списка обязан попадать в отпечаток конфигурации.

    Иначе два прогона с разным весом выглядят как одна конфигурация, и рост
    метрики читается как улучшение системы, хотя изменилась настройка. Мы уже
    дважды на этом попадались: сначала не было отпечатка кода, потом настроек
    судьи. Каждый раз `compare` уверенно писал «конфигурации совпадают».
    """
    from eval.runner import RunConfig

    fields = RunConfig.__dataclass_fields__
    assert "keyword_weight" in fields, "вес слияния не входит в отпечаток прогона"
    assert "rrf_k" in fields


def test_default_fusion_is_the_measured_plateau_not_the_library_default():
    """Настройки слияния обязаны быть теми, что выбраны перебором.

    k = 60 — значение из статьи про списки длиной в тысячи. На наших списках
    по 24 оно гарантировало, что присутствие в обоих списках сильнее любого
    места: 2/(60+24) больше, чем 1/(60+1). Перебор 42 вариантов дал плато при
    весе 0.3 и k от 8 до 16 — одинаковый результат на трёх соседних значениях,
    то есть свойство системы, а не удачная точка.

    Тест сторожит откат к «библиотечному» значению: с ним метрика падает с
    0.866 до 0.821, а выглядит это как невинная правка конфига.
    """
    from app.config import Settings
    from app.rag.search import single_list_can_win

    settings = Settings()
    assert settings.keyword_weight < 1.0, "вес ключевого списка вернулся к единице"
    assert single_list_can_win(settings.rrf_k, settings.search_top_k), (
        "при таком k присутствие в обоих списках снова сильнее любого места"
    )


def test_env_override_is_detected():
    """Настройка, переопределённая окружением, обязана быть видна.

    Я поменял в коде константу слияния с 60 на 12, прогнал стенд и получил
    прежние цифры. Полчаса искал ошибку в логике — её не было: значение
    переопределено в `.env`, код его не применял, и нигде не печаталось ни то,
    ни другое. Настройка выглядела изменённой и не была.

    Аналогия: крутишь термостат на стене, а в комнате обогреватель со своим
    регулятором. Термостат исправен, цифра меняется, тепла не прибавляется.
    """
    from app.config import Settings, overridden_from_env

    assert overridden_from_env(Settings()) == {}, (
        "в тестовом окружении настройки должны совпадать с кодом"
    )

    changed = overridden_from_env(Settings(rrf_k=60))
    assert "rrf_k" in changed
    current, default = changed["rrf_k"]
    assert (current, default) == (60, 10)


def test_gate_waiver_requires_a_written_reason():
    """Уступку можно принять, но только назвав метрику и причину.

    Разница между исключением и поднятым допуском принципиальная. Поднятый
    допуск прощает любую просадку любой метрики во всех будущих проверках —
    это храповик: планка опускается по щелчку за раз, и каждый шаг законен.
    Исключение названо по имени, требует письменной причины и действует
    только на один запуск.
    """
    from pathlib import Path

    source = (Path(__file__).resolve().parent.parent / "scripts" / "eval.py").read_text(
        encoding="utf-8"
    )
    gate = source[source.index("async def _gate("):]

    assert "исключение без причины" in gate, "уступка без причины обязана отвергаться"
    assert "Действует только на этот запуск" in gate
    # И допуск по-прежнему нельзя поднимать молча.
    assert "прячет регрессию" in gate

"""Тесты разбора поиска: один диагноз из четырёх, а не список наблюдений.

Смысл этих тестов в том, что диагноз — это ВЫВОД, и выводы можно проверить.
Метрика `chunk_top1` под одной цифрой прячет четыре разные болезни с четырьмя
разными лекарствами, и главная ценность разбора — не печать таблиц, а то, что
он называет ровно одну из них. Значит и проверять надо именно выбор.
"""

from eval.explain import diagnose


def verdict(**kwargs) -> str:
    base = dict(
        needle_chunks=[7],
        vector_ranks={},
        keyword_ranks={},
        fused_ranks={},
        context_chunks=set(),
    )
    base.update(kwargs)
    return diagnose(**base).code


def test_needle_absent_from_index_is_not_a_search_problem():
    """Если ожидаемого текста нет ни в одном фрагменте, поиск ни при чём.

    Это первый вопрос, который надо задавать, и его легко пропустить: «не
    нашлось» и «нечего находить» выглядят в отчёте одинаково, а лечатся
    противоположным — первое ранжированием, второе разбиением текста или
    разметкой. Мы уже попадались на этом с разметкой, которая требовала
    подстроку «3»: она встречалась сотни раз и не различала ничего.
    """
    assert verdict(needle_chunks=[]) == "нет в индексе"


def test_context_hit_is_split_by_position():
    """«Дошёл» и «дошёл первым» — разные исходы, и их нельзя сливать.

    Первая версия разбора отвечала «поиск справился» на оба, и сводка
    показала 66 успехов из 67 при chunk_top1 = 0.821. Обе цифры верны и
    говорят о разном: нужный фрагмент доезжает почти всегда, но в каждом
    пятом вопросе он не первый. Слив этих случаев прячет ровно ту разницу,
    ради которой ставят реранкер.
    """
    assert verdict(context_chunks={7}, fused_ranks={7: 1}) == "дошёл первым"
    assert verdict(context_chunks={7}, fused_ranks={7: 6}) == "дошёл не первым"


def test_needle_in_neither_list_points_at_the_query_not_the_ranking():
    """Ни в векторном, ни в ключевом — значит вопрос задан другими словами.

    Настоящий случай: «какие методы есть на апихе папасса?». Реранкер здесь
    бесполезен по определению — он переставляет то, что нашлось, а нашлось не
    то. Лечится переписыванием запроса в лексику документов.
    """
    assert verdict(vector_ranks={1: 1}, keyword_ranks={2: 1}) == "запрос другими словами"


def test_keyword_only_is_a_fusion_trust_question():
    assert verdict(keyword_ranks={7: 2}) == "смысл не поймался"


def test_vector_only_is_normal_for_paraphrase():
    assert verdict(vector_ranks={7: 9}) == "слова не совпали"


def test_in_both_lists_but_below_context_is_the_reranker_case():
    """И только этот случай — работа для реранкера.

    Состав выдачи правильный, порядок неправильный. Если таких вопросов в
    сводке мало, дорогой реранкер починит малую долю проблемы, и вечер уйдёт
    не туда.
    """
    assert (
        verdict(vector_ranks={7: 12}, keyword_ranks={7: 8}, fused_ranks={7: 11})
        == "порядок"
    )


def test_dropped_by_fusion_is_named_separately():
    """Есть в обоих списках, а после слияния исчез — это про RRF, не про порядок.

    RRF складывает МЕСТА, а не баллы: фрагмент, стоящий низко в обоих списках,
    проигрывает тому, кто стоит средне в обоих. Отдельное имя нужно затем, что
    смотреть надо на константу k и глубину списков.
    """
    assert (
        verdict(vector_ranks={7: 20}, keyword_ranks={7: 22}, fused_ranks={1: 1})
        == "срезано слиянием"
    )


def test_verdict_carries_a_remedy_not_only_a_label():
    """У каждого диагноза обязано быть написано, ЧТО с ним делать.

    Диагноз без лечения — это просто ещё одно наблюдение, а таких у нас и так
    хватает. Отчёт, который называет болезнь и молчит про лекарство,
    заставляет каждый раз вспоминать логику заново.
    """
    for kwargs in (
        {"needle_chunks": []},
        {"context_chunks": {7}},
        {"vector_ranks": {1: 1}, "keyword_ranks": {2: 1}},
        {"keyword_ranks": {7: 2}},
        {"vector_ranks": {7: 9}},
        {"vector_ranks": {7: 12}, "keyword_ranks": {7: 8}, "fused_ranks": {7: 11}},
    ):
        base = dict(
            needle_chunks=[7], vector_ranks={}, keyword_ranks={},
            fused_ranks={}, context_chunks=set(),
        )
        base.update(kwargs)
        result = diagnose(**base)
        assert result.remedy.strip(), f"{result.code}: нет лекарства"
        assert len(result.remedy) > 40, f"{result.code}: лекарство слишком общее"



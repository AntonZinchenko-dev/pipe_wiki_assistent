"""Ответ отрицает таблицу, которая у человека перед глазами. Починка.

Все примеры ниже — дословно из живых прогонов, не выдуманы. Это важно:
правила про таблицы УЖЕ запрещают такие ответы, прямым текстом и с тремя
образцами «так не надо», один из которых почти совпадает с первым случаем.
То есть промпт написан, прочитан и не сработал.
"""

from __future__ import annotations

import pytest

from app.rag.table_answer import ENOUGH, repair, surviving_refs

FROM_RUNS = [
    "Во фрагментах нет информации о топ-5 труб по выработке ресурса. "
    "В таблице T18D0 показаны только три трубы: PP-0035, PP-0007 и PP-0013 [1].",
    "Во фрагментах нет информации о топ-10 труб по выработке ресурса. "
    "В таблице T18D0 показаны только первые записи, а не весь список из 38 труб [1].",
    "Во фрагменте нет данных о следующих пяти трубах по выработке ресурса. "
    "Показана только первая строка таблицы: Труба PP-0035, выработка 97.7 % [1].",
]


@pytest.mark.parametrize("answer", FROM_RUNS)
def test_a_denial_over_a_table_becomes_the_honest_line(answer: str) -> None:
    """Когда все предложения вредные, остаётся канонический ответ.

    «Данные в таблице выше» — не отписка: правила про таблицы прямо
    называют это полноценным ответом. Таблица у человека перед глазами, и
    добавить к ней действительно нечего.
    """
    fixed, removed = repair(answer, tables=1)

    assert fixed == ENOUGH
    assert removed == 2


def test_a_useful_sentence_survives_the_repair() -> None:
    """Чинится форма, а не смысл: полезное остаётся.

    Выбросить весь ответ значило бы наказать человека за нашу проблему.
    """
    answer = (
        "Во фрагментах нет информации о списке труб. "
        "Порог аварии по выработке составляет 80 % [3]."
    )

    fixed, removed = repair(answer, tables=1)

    assert removed == 1
    assert fixed == "Порог аварии по выработке составляет 80 % [3]."


@pytest.mark.parametrize(
    "answer",
    [
        "Выработка ресурса у трубы PP-0035 составляет 97.7 % [1].",
        "В таблице T7951 инспекция просрочена у трубы PP-0036 [4].",
        # Честный отказ сервиса трогать нельзя: он верен.
        "Запрос «Паспорт трубы PP-0007» не удался. Код E-1042: расчёт устарел [1].",
        "В таблице T18D0 есть только текущие значения. Самая изношенная — PP-0035 [1].",
    ],
)
def test_a_real_answer_is_left_alone(answer: str) -> None:
    assert repair(answer, tables=1) == (answer, 0)


def test_without_a_table_a_refusal_is_honest() -> None:
    """Отрицание в ответе по документам — правда, и подменять её нельзя.

    Починка здесь была бы враньём в другую сторону: «во фрагментах нет
    тайм-аута очереди» — это верный отказ, если тайм-аута там правда нет.
    """
    honest = "Во фрагментах нет информации о тайм-ауте очереди."

    assert repair(honest, tables=0) == (honest, 0)


def test_orphaned_citations_are_findable_after_the_repair() -> None:
    """Ссылка на фрагмент, номера которого в тексте не осталось, — ссылка в никуда.

    Проверка цитат у нас строгая. Оставить осиротевшую ссылку значило бы
    своими руками создать ровно то, что она ловит.
    """
    fixed, removed = repair(
        "Во фрагментах нет списка труб [1]. Порог аварии — 80 % [3].", tables=1
    )

    assert removed == 1
    assert surviving_refs(fixed) == {3}



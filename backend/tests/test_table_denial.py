def test_a_dropped_invention_still_counts_against_the_run() -> None:
    """САМАЯ ВАЖНАЯ ПРОВЕРКА ЗДЕСЬ: починка не должна чистить метрику.

    Если убранные обозначения не считать, `live_clean` станет 1.000 ровно в
    тот момент, когда мы научились прятать выдумку от человека, — то есть
    замер наградит сокрытие. Поэтому убранное роняет прогон наравне с
    показанным, и разница только в том, видит ли это человек.
    """
    from eval.runner import RowResult

    common = dict(question="?", type="live", difficulty="easy", answerable=True,
                  critical=False, retrieved_docs=[], retrieval={}, split="tune")
    shown = RowResult(question_id="x", invented_refs=["PP-0035"], **common)
    hidden = RowResult(question_id="y", invented_dropped=["PP-0035"], **common)

    # Поле существует и заполняется — иначе прогон о починке не узнает вовсе.
    assert hidden.invented_dropped == ["PP-0035"]
    assert shown.invented_refs == ["PP-0035"]

    # И то и другое считается нечистым ответом.
    for row in (shown, hidden):
        assert bool(row.invented_refs or row.invented_dropped)


def test_the_kitchen_rule_is_a_sign_not_a_word_list() -> None:
    """Список оборотов пропустил вот это — и поэтому стал признаком.

    Из прогона, вопрос «следующие 5», таблица с ними пришла и стоит у человека
    перед глазами:

        «Во фрагменте приведена только одна строка таблицы: Труба PP-0035,
         выработка 97.7 %. Следующие пять труб не показаны и не перечислены.»

    Оба предложения — про нашу кухню, и оба список пропустил. Дописать в него
    ещё один оборот значило бы играть в догонялки: формулировок у модели
    бесконечно, и каждая новая приходит отдельным прогоном на полтора часа.

    Признак вместо списка: слово «фрагмент» служебное. Человек его не знает,
    в интерфейсе оно не показывается, в корпусе его нет. Предложение про
    фрагмент — предложение про кухню по определению.
    """
    from app.rag.table_answer import ENOUGH, repair

    fixed, removed = repair(
        "Во фрагменте приведена только одна строка таблицы: Труба PP-0035, "
        "выработка 97.7 % [1]. Следующие пять труб не показаны и не перечислены.",
        tables=1,
    )

    assert removed == 2
    assert fixed == ENOUGH


def test_an_honest_refusal_over_documents_is_untouched() -> None:
    """Признак широкий, поэтому условие «только при таблице» несущее.

    «Во фрагментах нет данных» без таблицы — честный отказ, и тронуть его
    значило бы соврать в другую сторону. Ровно поэтому проверка живёт внутри
    `repair`, который без таблиц не делает ничего.
    """
    from app.rag.table_answer import repair

    text = "Во фрагментах нет данных о стоимости лицензии."
    assert repair(text, tables=0) == (text, 0)


def test_a_good_answer_over_a_table_survives() -> None:
    """Обобщение не должно съедать нормальные ответы.

    Проверка на то, что признак не стал всеядным: в обоих ответах ниже нет ни
    слова про кухню, и трогать их нельзя.
    """
    from app.rag.table_answer import repair

    for text in (
        "Выработка ресурса у трубы PP-0035 составляет 97.7 % [1].",
        "Самая тяжёлая скважина — W-122, Приобское, максимум выработки 97.7 % [1].",
    ):
        assert repair(text, tables=1) == (text, 0)

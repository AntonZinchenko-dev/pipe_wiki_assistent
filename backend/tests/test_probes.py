"""Готовность и живость — разные вопросы, и путать их дорого.

Правило из чек-листа готовности к проду: проверка готовности учитывает
доступность модели, проверка живости — нет.

Почему это не формальность. По ЖИВОСТИ оркестратор перезапускает, по
ГОТОВНОСТИ балансировщик снимает нагрузку. Если проверка живости спросит
модель, то падение чужого сервиса — облака, локального рантайма, сети —
будет выглядеть как смерть нашего процесса. Нас начнут перезапускать по
кругу ровно тогда, когда мы исправно работаем и отдаём понятные ошибки, а
перезапуск при этом ничего не чинит: модель от него не поднимется.
"""

from __future__ import annotations

import inspect

from app.api import routes


def source_of(name: str) -> str:
    return inspect.getsource(getattr(routes, name))


def test_liveness_does_not_ask_the_model() -> None:
    """В живости не должно быть ни провайдеров, ни индекса."""
    body = source_of("live")

    assert "providers" not in body
    assert "store" not in body


def test_readiness_asks_the_model_and_the_index() -> None:
    """Готовность обязана спросить и модель, и индекс.

    Сервис с живой моделью и пустым индексом отвечать не может — значит
    он не готов, даже если процесс здоров.
    """
    body = source_of("ready")

    assert "providers" in body
    assert "stats" in body


def test_readiness_answers_with_a_status_code_not_a_field() -> None:
    """503, а не 200 с `ok: false`.

    Балансировщики читают код ответа, а не тело. Двухсотка с честным телом
    внутри означает для них «всё хорошо, шлите людей» — то есть проверка
    есть, а толку от неё нет.
    """
    assert "503" in source_of("ready")

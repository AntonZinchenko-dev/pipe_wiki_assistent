"""Ответ отрицает данные, которые сам же и получил.

Прибор понадобился после дня, потраченного на `tools_ok`. Я довёл его до
1.000 — агент во всех девяти живых вопросах зовёт нужный инструмент и
приносит таблицу, — и только потом прочитал сами ответы. Три из них
начинались со слов «во фрагментах нет информации», при том что таблица была
у человека на экране.

То есть метрика, которую я полдня оптимизировал, слепа к тому, ради чего всё
делалось. `answer_contains` в том же прогоне ВЫРОС до 0.982: живые вопросы
освобождены от проверок по документам, и провал в них не виден вовсе.
"""

from __future__ import annotations

import pytest

from eval.metrics import table_answered


@pytest.mark.parametrize(
    "answer",
    [
        "Во фрагментах нет информации о топ-5 труб по выработке ресурса.",
        "Во фрагментах нет сведений о выработке ресурса трубы PP-0035.",
        "Во фрагменте нет данных о следующих пяти трубах.",
        "Данных конкретно по трубе PP-0035 не указано.",
    ],
)
def test_a_denial_over_a_delivered_table_is_caught(answer: str) -> None:
    """Все четыре формулировки взяты из живых прогонов, не выдуманы."""
    assert table_answered(answer, tables=1) is False


@pytest.mark.parametrize(
    "answer",
    [
        "Выработка ресурса у трубы PP-0035 составляет 97.7 %.",
        "В таблице T7951 инспекция просрочена у трубы PP-0036.",
        # ЧЕСТНЫЙ ОТКАЗ СЕРВИСА — не дефект ответа.
        #
        # Сервис действительно вернул ошибку, и сказать об этом прямо
        # правильно. Проверка, ругающаяся на такой ответ, заставила бы
        # прятать отказы сервиса — то есть чинила бы метрику за счёт
        # правдивости.
        "Запрос «Паспорт трубы PP-0007» не удался. Код E-1042: расчёт устарел.",
    ],
)
def test_a_real_answer_is_not_flagged(answer: str) -> None:
    assert table_answered(answer, tables=1) is True


def test_without_a_table_there_is_nothing_to_check() -> None:
    """`None`, а не `True`: неизмеренное нельзя складывать с измеренным.

    Ноль или True здесь означал бы, что 120 вопросов по документам
    «прошли проверку», которую им не проводили, и метрика показывала бы
    благополучие вместо молчания.
    """
    assert table_answered("во фрагментах нет информации", tables=0) is None


def test_the_check_does_not_grade_quality() -> None:
    """Проверка грубая нарочно, и её границы надо знать.

    Ответ про НЕ ТОТ предмет — «на какой скважине трубы хуже всего» ->
    «самая изношенная труба парка PP-0035» — слов отрицания не содержит и
    здесь не ловится. Это работа судьи, и делать вид, что подстрока её
    делает, значило бы обмануть себя дважды.
    """
    wrong_subject = "Самая изношенная труба парка — PP-0035, выработано 97.7 % ресурса."
    assert table_answered(wrong_subject, tables=1) is True

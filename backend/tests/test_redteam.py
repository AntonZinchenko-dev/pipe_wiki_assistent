def test_personal_data_in_the_question_is_masked_in_the_trace():
    """Вопрос попадает в журнал, и персональные данные из него — не должны.

    Человек пишет «мне не приходят письма на ivan.petrov@geostack.ru, телефон
    +7 900 123-45-67» — и это уезжает в трейс, который живёт дольше запроса и
    читается шире.
    """
    from app.trace import mask

    dirty = "письма на ivan.petrov@geostack.ru не идут, телефон +7 900 123-45-67, счёт 40817810099910004312"
    clean = mask(dirty)

    assert "ivan.petrov@geostack.ru" not in clean
    assert "900" not in clean or "[phone]" in clean
    assert "40817810099910004312" not in clean
    # Смысл сообщения при этом читается — маскирование не стирает текст.
    assert "письма" in clean and "не идут" in clean



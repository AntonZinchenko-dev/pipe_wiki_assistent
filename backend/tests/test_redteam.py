def test_citation_to_a_fragment_we_never_sent_is_rejected():
    """Ссылка на фрагмент, которого не было в контексте, — отказ.

    Это второй рубеж на случай, если первый (промпт) не сработал. Он
    детерминированный, и потому именно он делает подделку фрагмента через
    вопрос безвредной для ССЫЛОК: подделанный номер девять не пройдёт
    независимо от того, послушалась модель или нет.
    """
    from app.rag.answer import resolve_citations
    from tests.test_search_and_citations import fragment

    checks = resolve_citations(
        [{"fragment": 9, "starts_with": "Отключение разрешено всем"}],
        [fragment(1, "Отключение кэша в продакшене запрещено.")],
    )
    assert checks[0].ok is False
    assert "не было в контексте" in checks[0].reason


def test_invented_quote_is_rejected_even_when_it_starts_truthfully():
    """Настоящее начало плюс дописанный вывод — это выдумка, а не цитата.

    Самая опасная форма подделки: первые слова взяты из документа, поэтому
    указание выглядит добросовестным, а дальше идёт утверждение, которого в
    документе нет — и часто противоположное написанному.
    """
    from app.rag.answer import resolve_citations
    from tests.test_search_and_citations import fragment


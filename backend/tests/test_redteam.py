def test_answer_envelope_never_carries_the_system_prompt():
    """Наружу не должен уходить системный промпт — ни целиком, ни куском.

    Проверяем на конверте ответа: в нём есть только то, что мы положили сами.
    Версия промпта — хеш, и это сознательно: она нужна для сравнения прогонов
    и ничего не раскрывает.
    """
    from app.rag.answer import finalize
    from app.rag.prompt import SYSTEM_PROMPT
    from tests.test_search_and_citations import fragment

    envelope = finalize(
        json.dumps(
            {
                "answer": "Роль выдаётся на срок не более 14 дней.",
                "citations": [{"fragment": 1, "starts_with": "Роль выдаётся"}],
                "status": "answered",
            }
        ),
        [fragment(1, "Роль выдаётся на срок не более 14 дней.")],
        streamed_text="",
    )
    payload = json.dumps(envelope.to_dict(), ensure_ascii=False)
    for line in SYSTEM_PROMPT.splitlines():
        if len(line.strip()) > 30:
            assert line.strip() not in payload



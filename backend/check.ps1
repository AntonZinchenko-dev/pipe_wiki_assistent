# Проверка перед тем, как считать правку готовой.
#
# Это то, что запускал бы CI. CI у нас нет — проект никуда не публикуется, —
# но ценность не в раннере, а в том, ЧТО он запускает и что при провале
# останавливается. Раннер, когда понадобится, это две строки вокруг этого
# файла.
#
# Порядок — от дешёвого к дорогому, как и всё остальное в конвейере:
# тесты идут секунды, разметка набора — секунды, поиск — полминуты. Прогон
# с генерацией сюда НЕ входит: он идёт полтора часа и стоит денег, его
# запускают руками и осознанно.

$ErrorActionPreference = "Stop"
$failed = @()

function Step($name, $script) {
    Write-Host ""
    Write-Host "=== $name" -ForegroundColor Cyan
    & $script
    if ($LASTEXITCODE -ne 0) {
        $script:failed += $name
        Write-Host "    ПРОВАЛ: $name" -ForegroundColor Red
    }
}

Step "тесты" { python -m pytest -q }

# Разметка набора: доехали ли ожидаемые подстроки до чанков. Ловит
# рассинхронизацию набора с корпусом — самую тихую из возможных, потому
# что прогон при ней просто молча меряет не то.
Step "разметка набора" { python scripts\eval.py validate }

# Поиск без генерации. Отвечает на вопрос, который надо задавать первым:
# доехал ли нужный текст до контекста. Если нет — крутить промпт
# бессмысленно, и дорогой прогон запускать незачем.
Step "поиск против базовой линии" { python scripts\eval.py gate }

Write-Host ""
if ($failed.Count -gt 0) {
    Write-Host "НЕ ГОТОВО. Провалено: $($failed -join ', ')" -ForegroundColor Red
    exit 1
}
Write-Host "Готово: тесты, разметка и поиск в порядке." -ForegroundColor Green
Write-Host "Прогон с генерацией сюда не входит — запускайте .\run.ps1 отдельно." -ForegroundColor DarkGray
exit 0

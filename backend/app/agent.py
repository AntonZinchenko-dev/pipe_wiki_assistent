# Пункт 2 добавлен по факту. Без него модель на вопрос «какая труба самая
# изношенная» находила в вики определение изношенности, считала, что этого
# хватает, и выдавала рассказ о том, что такое изношенность, со статусом
# «ответ найден». Формально она права: фрагменты про трубы нашлись. Ошибка
# была в постановке задачи — её спрашивали «хватает ли найденного», а надо
# спрашивать «чем закрывать вопрос»: для вопроса о сегодняшнем значении
# ответ «в документах достаточно» неверен всегда, сколько бы там ни нашлось.
#
# ВТОРАЯ ПРАВКА ПУНКТА 2, И ВОТ ПОЧЕМУ. Первая версия перечисляла обороты со
# словом «сейчас»: «какая труба сейчас», «сколько сейчас». На вопросе «найди
# самую изношенную трубу в парке» слова «сейчас» нет — и GigaChat честно
# отнёс вопрос к пункту 1, потому что определение изношенности во фрагментах
# действительно нашлось.
#
# Ошибка была в том, ЧТО именно перечислялось. Перечислять надо не обороты
# речи, а ПРЕДМЕТ вопроса: правило или конкретный объект с числом. Список
# оборотов модель сопоставляет буквально, и любой синоним мимо списка
# отправляет её не туда. Это общее свойство инструкций по образцам: образец
# ловит форму, а решение принимается по смыслу.

# Для родного механизма — одна добавка сверху.
#
# Модель, у которой есть и инструменты, и возможность написать текст,
# выбирает текст: это дешевле и всегда «работает». В логах это выглядело
# как рассуждение «здесь нужно обратиться к сервису» — верное по смыслу и
# бесполезное по результату, потому что вызова не было. Инструкция говорит
# прямо: решение выражается вызовом, а не его описанием.
AGENT_PROMPT_NATIVE = AGENT_PROMPT + """

Решение выражай ВЫЗОВОМ инструмента, а не рассказом о нём. Фраза «нужно \
обратиться к сервису» инструмент не вызывает и шага не стоит. Либо вызов, \
либо слово ХВАТИТ — третьего варианта ответа здесь нет."""


def agent_version() -> str:
    """Отпечаток ВСЕГО, чем агент принимает решение.

    Промпты ответа у нас живут в реестре версий: у каждой имя, отпечаток
    содержимого и запись в журнале каждого запроса. У агента этого не было
    — и это стоило мне прогона. Я поменял бланк решения и список
    инструментов, а в шапке прогона поменялась одна строка: `код`. По ней
    видно, что код другой, и не видно, ЧТО в нём другое: правка агента,
    правка поиска и опечатка в комментарии выглядят одинаково.

    Считается от трёх вещей вместе, потому что решение принимают они втроём:
    текст промпта, бланк решения целиком и описания инструментов. Имена
    инструментов в бланк подставляются по правам человека, поэтому в
    отпечаток идёт полный набор — отпечаток описывает КОД, а не отдельный
    запрос.

    БЛАНК БЕРЁТСЯ ЦЕЛИКОМ, А НЕ СПИСКОМ ИМЁН ПОЛЕЙ. Первая версия считала
    отпечаток от `sorted(properties)` — то есть от одних названий. Я снял с
    поля `why` границу длины, которая стоила двух живых вопросов, пересчитал
    отпечаток и получил прежний: названия-то не изменились. Сторож, который
    не замечает правку, ради обнаружения которой поставлен, — это не сторож,
    а успокоительное. Ровно та же ошибка, что с отпечатком промпта,
    вычисленным из самого себя (см. `prompt.py`), и оба раза она выглядела
    как работающая проверка.
    """
    from .rag.tools import LIVE_SPECS, tool_specs

    tools = tool_specs() + list(LIVE_SPECS)
    material = "".join([
        AGENT_PROMPT,
        AGENT_PROMPT_NATIVE,
        # ТЕКСТ СОСТОЯНИЯ — ТОЖЕ ЧАСТЬ ТОГО, ЧЕМ РЕШАЕТ МОДЕЛЬ.
        #
        # Забыл его при первой сборке, и сторож промолчал на правке, которая
        # меняла поведение агента сильнее всех предыдущих. Это третий раз,
        # когда этот отпечаток оказывался слеп в новом месте: сначала считал
        # от одних имён полей, потом не видел содержимого схемы, теперь не
        # видел постоянного блока состояния.
        #
        # Правило, чтобы не было четвёртого: в отпечаток идёт ВСЁ, что
        # уезжает модели и живёт в коде. Не «промпт», а весь текст запроса.
        #
        # ГРАНИЦА ЭТОГО ОТПЕЧАТКА, чтобы он не обещал лишнего. Он покрывает
        # МАТЕРИАЛ — тексты, схемы, описания инструментов, правило
        # маршрутизации. Он НЕ покрывает логику цикла: например, с какого
        # шага модели снова разрешают сказать «хватит». Такая правка меняет
        # поведение и отпечаток агента не двигает — её видно только по
        # `code_version`. Обещать здесь «всё, что решает» было бы неправдой,
        # а неправда в шапке прогона хуже отсутствия строки.
        LIVE_AVAILABLE,
        # ПРАВИЛО МАРШРУТИЗАЦИИ — тоже часть решения, хоть и не текст.
        # Оно решает, останется ли у модели вариант «ХВАТИТ», то есть
        # меняет её поведение сильнее любой строки промпта. Два прогона
        # с разными правилами обязаны различаться в шапке.
        Path(route.__file__).read_text(encoding='utf-8'),
        # `sort_keys` обязателен: иначе отпечаток поедет от случайного
        # порядка вставки в словарь, и «изменилось» будет означать «мы
        # перечитали тот же код».
        json.dumps(decision_schema(tools), ensure_ascii=False, sort_keys=True),
        json.dumps(tools, ensure_ascii=False, sort_keys=True),
    ])
    return f"agent-1.0+{hashlib.sha256(material.encode()).hexdigest()[:8]}"



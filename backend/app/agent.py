# СТРОКА, КОТОРАЯ СТОИЛА ШЕСТИ ПРОГОНОВ. Почему она здесь, а не в промпте.
#
# Разбор 45 наблюдений (шесть прогонов на девяти живых вопросах) дал
# разделение БЕЗ ЕДИНОГО ИСКЛЮЧЕНИЯ:
#
#                          позвал живой инструмент   не позвал
#     FATIGUE-API нашёлся             20                  0
#     FATIGUE-API не нашёлся           0                 25
#
# То есть агент шёл в сервис тогда и только тогда, когда описание сервиса
# случайно попало в найденные фрагменты. Не вопрос решал, а поиск.
#
# Механика понятна по словам самой модели: «В найденных фрагментах есть
# только правила и категории, но нет списка труб или их номеров» — и
# ХВАТИТ. Она судит о наличии данных по контексту, а контекст про сервис
# молчит. В промпте написано «значения живут в сервисе», но написанное в
# промпте абстрактно, а фрагмент с эндпоинтами — вещественная улика. При
# конфликте выигрывает улика.
#
# Поэтому строка стоит В СОСТОЯНИИ, рядом с фрагментами, а не в промпте:
# она должна оказаться там, где модель ищет доказательства, и она обязана
# появляться ТОЛЬКО когда сервис реально доступен этому человеку.
#
# И главное отличие от предыдущей попытки (поле `verdict`, откат выше):
# новых ветвей решения эта строка не открывает. Она не добавляет исходов, а
# убирает ложный вывод из отсутствия данных в документах.
LIVE_AVAILABLE = """СЕРВИС ЖИВЫХ ДАННЫХ ПОДКЛЮЧЁН И РАБОТАЕТ ПРЯМО СЕЙЧАС.

Сегодняшние значения — парк, паспорт трубы, осмотры, скважины — берутся из \
него, а не из документов. Поэтому то, что во фрагментах нет списка труб, \
номеров, процентов выработки и статусов инспекций, — ЭТО НОРМА, а не признак, \
что их негде взять. В документах их и не должно быть.

Фраза «в найденных фрагментах этого нет» решения НЕ закрывает: если \
спрашивают про конкретные объекты и их числа, данные берутся из сервиса."""


def decision_schema(tools: list[dict], *, allow_enough: bool = True) -> dict:
    """Бланк решения для моделей, которые не умеют вызывать функции.

    `allow_enough=False` убирает из списка действий вариант «ХВАТИТ». Так
    задаётся ВТОРОЙ из двух вопросов: к нему приходят только после того, как
    модель сама сказала, что найденного мало, и увернуться от выбора
    источника ей уже нечем. Именно здесь она шесть прогонов подряд и
    уворачивалась, дописав перед этим верный вывод.

    Запасной путь, и нужен он не для красоты. Вызов функций поддерживают не
    все модели: у нас на облачной `GigaChat-3-Lightning` за пять запросов не
    пришло ни одного вызова, включая прямую просьбу пользователя сходить в
    сервис. А структурированный ответ по схеме на той же модели работает —
    им отдаётся весь основной ответ. Значит агент может принимать решение
    тем же механизмом, которым система уже пользуется.

    Поле `why` идёт ПЕРВЫМ, а `action` после. Это то же правило, что в схеме
    ответа: генерация авторегрессивная, и ярлык, выданный первым, тянет за
    собой обоснование под себя. Схема, начинавшаяся со `status`, стоила нам
    60 отказов из 67 отвечаемых вопросов.
    """
    names = [spec["function"]["name"] for spec in tools]
    return {
        "type": "object",
        "properties": {
            # ЖЁСТКОЙ ГРАНИЦЫ ДЛИНЫ ЗДЕСЬ БЫТЬ НЕ ДОЛЖНО. ЭТО ПОЛЕ ДЛЯ
            # РАССУЖДЕНИЯ, А ГРАНИЦА ДЛИНЫ РАССУЖДЕНИЯ — ЭТО ГРАНИЦА МЫСЛИ.
            #
            # Здесь стояло `maxLength: 200`, и поставил я его, чтобы модель не
            # тратила бюджет ответа на обоснование раньше, чем дойдёт до
            # `action`. Довод верный, лекарство — нет.
            #
            # Что вышло на замере. Провайдер строит из схемы грамматику и
            # соблюдает границу буквально: на двухсотом символе поле
            # закрывается, где бы модель ни находилась. В прогоне это
            # выглядело так (`why` ровно 200 символов, оба раза):
            #
            #   «...это про конкретные трубы и их состояние. В найденных
            #    фрагментах есть только правила и категории, но нет списка с»
            #   «...В найденных фрагментах есть только правила и категории
            #    инспекции, но нет данных о реальных трубах или их инсп»
            #
            # Обе мысли шли к ВЕРНОМУ выводу — «списка самих труб тут нет,
            # значит надо в сервис» — и обе отрублены за полслова до него.
            # Дальше грамматика закрывает поле и требует `action`, а решение
            # принимается по оборванной фразе, которая кончается союзом «но».
            # Модель дописывает то, что согласуется с обрывком.
            #
            # Правильное лекарство от «обоснование съело бюджет» — бюджет
            # (`agent_max_tokens`) и просьба в описании, а не нож в грамматике.
            # Плюс обрыв по токенам теперь ВИДЕН: `_blank_reason` называет его
            # «(обрыв)», и молчаливой потери, ради которой ставилась граница,
            # больше не бывает.
            #
            # Правило общее: перечисления и ярлыки ограничивать схемой можно и
            # нужно, поля для рассуждения — нельзя.
            "why": {
                "type": "string",
                "description": (
                    "Коротко: к какому пункту относится вопрос и почему. "
                    "Одна-две фразы, договори мысль до конца."
                ),
            },
            # ПОРЯДОК ЗНАЧЕНИЙ В СПИСКЕ — ТОЖЕ ПОРЯДОК РАССУЖДЕНИЯ.
            #
            # Здесь стояло `["ХВАТИТ", *names]`, и это тот же дефект, что
            # ярлык впереди содержания, только спрятанный на уровень глубже:
            # провайдер строит из перечисления грамматику, и первое значение
            # — самый дешёвый путь. Слабая модель сползает в него.
            #
            # ЗАМЕР ЭТУ ГИПОТЕЗУ НЕ ПОДТВЕРДИЛ, и порядок всё равно такой.
            #
            # Прогон с перестановкой дал `tools_ok` 0.444 против 0.444 — те
            # же пять промахов, те же четыре решения ХВАТИТ, и поля `why`
            # совпали с прошлым прогоном до символа. Значит сползания в
            # первое значение здесь не было: решение принимается раньше и
            # по другой причине, которую ищем отдельно.
            #
            # Порядок оставлен новым по независимому доводу — по цене
            # ошибки. Расплата за «позвал лишнего» — один лишний запрос к
            # сервису; расплата за «не позвал» — ответ про устройство
            # системы вместо запрошенных чисел. Наклон списка пусть смотрит
            # в сторону дешёвой ошибки, даже если на этой модели он ничего
            # не решает.
            #
            # Запись оставлена целиком нарочно: «проверено, не сработало» —
            # такой же результат, как «сработало», и стоит он прогона. Без
            # этой записи следующий человек (или я через месяц) потратит
            # прогон на ту же перестановку.
            "action": {
                "type": "string",
                "enum": [*names, *(["ХВАТИТ"] if allow_enough else [])],
                "description": (
                    "Имя инструмента, если вопрос о конкретных объектах и их "
                    "числах. ХВАТИТ — только если найденного действительно "
                    "достаточно. Заполнять обязательно."
                ),
            },
            # ПОЛЯ ПАРАМЕТРОВ БЕРУТСЯ ИЗ САМИХ ИНСТРУМЕНТОВ, А НЕ ПЕРЕПИСАНЫ
            # РУКАМИ.
            #
            # Здесь лежал список из семи полей, скопированный с описаний
            # инструментов, — и скопированный без описаний. То есть каждый
            # параметр был описан для модели в одном месте и пуст в другом,
            # причём пуст именно там, где работает облачная модель: она
            # ходит бланком, а не родным вызовом. Описания писались и не
            # доезжали до единственного живого механизма.
            #
            # Копия всегда отстаёт от оригинала — вопрос только в том,
            # сколько времени пройдёт. Здесь прошло два инструмента:
            # `live_inspections` и `live_wells` добавились с параметрами,
            # которых в этом списке не появилось вовсе, и модель физически
            # не могла попросить фильтр по категории через бланк.
            **_parameter_fields(tools),
        },
        "required": ["why", "action"],
    }


def _parameter_fields(tools: list[dict]) -> dict:
    """Объединение параметров всех инструментов — с их описаниями.

    Бланк один на все инструменты сразу, поэтому поля складываются в один
    плоский объект. Лишнее, заполненное по инерции, отсекается при разборе
    (`_call_from_json` отбирает аргументы по схеме ВЫБРАННОГО инструмента),
    так что цена объединения — только размер схемы.

    Одноимённые параметры разных инструментов обязаны совпадать по типу:
    `top_n` у парка и у скважин — одно и то же поле бланка, и разными
    типами оно быть не может. Несовпадение здесь означало бы, что бланк
    молча навязывает одному из инструментов чужой тип, — поэтому оно
    ловится тестом, а не примиряется втихую.
    """
    fields: dict[str, dict] = {}
    for spec in tools:
        properties = (spec["function"].get("parameters") or {}).get("properties") or {}
        for name, schema in properties.items():
            fields.setdefault(name, dict(schema))
    return fields


@dataclass(slots=True)
class AgentProgress:
    """Чем агент занят прямо сейчас. Уходит пользователю по мере работы."""

    text: str


# Человеческие названия действий. Технические имена инструментов
# пользователю не говорят ничего, а ждёт он именно их.
_DOING = {
    "search_wiki": "ищу в вики ещё раз",
    "read_section": "дочитываю раздел",
    "live_pipe": "иду в базу за паспортом трубы",
    "live_fleet": "иду в базу за данными парка",
    "live_inspections": "иду в базу за инспекциями",
    "live_wells": "иду в базу за скважинами",
}


def _what_now(call: ToolCall) -> str:
    what = _DOING.get(call.name, f"вызываю {call.name}")
    pipe = str(call.arguments.get("pipe_id") or "").strip()
    return f"{what} {pipe}".strip() if pipe else what


@dataclass(slots=True)
class AgentStep:
    """Один шаг: что попросила модель и что из этого вышло."""

    number: int
    tool: str
    arguments: dict
    result: str
    added: int
    ok: bool


@dataclass(slots=True)
class AgentOutcome:
    hits: list[Hit]
    steps: list[AgentStep] = field(default_factory=list)
    # Потолок шагов исчерпан: цикл кончился не потому, что модель сказала
    # «хватит», а потому, что кончились шаги. Признак отдельный, потому что
    # означает «ответ собран из возможно неполного», и в отчёте это надо
    # видеть сразу, а не высчитывать по числу шагов.
    hit_limit: bool = False
    used_tools: bool = False
    # Чем принято решение: «инструменты», «схема» или «не спрашивали».
    #
    # Раньше здесь стояло только `used_tools`, а в комментарии — что
    # «модель отказалась» и «модель не умеет инструменты» снаружи
    # неразличимы и притворяться не надо. Это была ошибка. Различить их
    # дёшево, а без различия агент, который молчит, выглядит одинаково при
    # двух совершенно разных причинах — и чинишь не то. Так и вышло: пять
    # запросов подряд без единого вызова, и по отчёту нельзя было понять,
    # решала модель или не умела.
    mechanism: str = "не спрашивали"
    # Что модель ответила вместо вызова. Пусто, если вызвала.
    #
    # Это и есть недостающая улика: «ХВАТИТ» означает решение, а связный
    # текст ответа на вопрос — что модель не поняла задачу или не умеет
    # инструменты и просто ответила.
    declined_with: str = ""
    # Таблицы, добытые инструментами за все шаги. Уходят в браузер
    # отдельными событиями, минуя модель.
    datasets: list = field(default_factory=list)
    # Шаги кончились, когда след был ЖИВОЙ: последний вызов принёс новые
    # фрагменты, значит следующий мог принести ещё.
    #
    # Это не то же самое, что `hit_limit`. Предел исчерпан и тогда, когда
    # модель последним шагом сходила впустую, — а такой обрыв ничего не
    # стоил, и пугать им пользователя незачем. Ровно это и было в логе:
    # «кончились разрешённые шаги» стояло под полным, правильным ответом,
    # потому что второй шаг не принёс ничего. Предупреждение, которое
    # срабатывает не по делу, через неделю перестают читать вовсе — и
    # тогда оно не сработает и по делу.
    trail_cut: bool = False


class Agent:
    def __init__(
        self,
        *,
        settings: Settings,
        toolbox: Toolbox,
        providers,
    ) -> None:
        self._s = settings
        self._toolbox = toolbox
        self._providers = providers
        # Сколько раз пара «провайдер + модель» промолчала в ответ на
        # показанные инструменты.
        #
        # РАНЬШЕ ЗДЕСЬ БЫЛО МНОЖЕСТВО, И ОДНОГО ПРОМАХА ХВАТАЛО НАВСЕГДА.
        # Это неверно: болтливый ответ вместо вызова бывает и у модели,
        # которая вызовы умеет, — достаточно неудачной формулировки
        # вопроса. Одно наблюдение объявлялось свойством модели, и дальше
        # весь процесс жил со схемой, хотя родной механизм работал.
        #
        # Порог в два промаха стоит один лишний вызов на модель, которая
        # правда не умеет, — и возвращает родной механизм всем, кто просто
        # оступился. Обратная ошибка дороже: она тихая и на весь процесс.
        self._native_misses: dict[tuple[str, str], int] = {}

    # Столько промахов подряд считаем свойством модели, а не случайностью.
    NATIVE_MISS_LIMIT = 2

    async def gather(
        self,
        question: str,
        first: SearchResult,
        *,
        trace: Trace,
        provider: str = "",
        model: str = "",
        live_allowed: bool = False,
        open_tables: list[OpenTable] | None = None,
    ) -> AgentOutcome:
        """Итог работы агента. Тонкая обёртка над `stream` для тех, кому
        промежуточные шаги не нужны."""
        outcome = AgentOutcome(hits=list(first.hits))
        async for item in self.stream(
            question, first, trace=trace, provider=provider, model=model,
            live_allowed=live_allowed, open_tables=open_tables,
        ):
            if isinstance(item, AgentOutcome):
                outcome = item
        return outcome

    async def stream(
        self,
        question: str,
        first: SearchResult,
        *,
        trace: Trace,
        provider: str = "",
        model: str = "",
        live_allowed: bool = False,
        open_tables: list[OpenTable] | None = None,
    ):
        """Добирает фрагменты, сообщая по дороге, чем занят.

        ГЕНЕРАТОР, А НЕ ФУНКЦИЯ, и это не стилистика. Агент работает
        секунды: решает, идёт в сервис, решает снова. Всё это время
        человек смотрит в пустой экран и не знает, думает система или
        зависла. Промежуточные сообщения — единственное лекарство, и
        отдать их можно только по мере появления.

        Последним элементом идёт `AgentOutcome`, до него — `AgentProgress`.

        На вход идёт результат ПЕРВОГО поиска — он уже сделан цепочкой, и
        повторять его было бы просто тратой.
        """
        found: list[Hit] = list(first.hits)
        steps: list[AgentStep] = []
        datasets: list = []
        history: list[dict] = []
        done: set[tuple[str, str]] = set()
        # Метки страниц, которые вернул БРАУЗЕР: только их разрешено листать.
        allowed_pages = {
            table.next_cursor for table in (open_tables or []) if table.next_cursor
        }
        hit_limit = False
        mechanism = "не спрашивали"
        declined_with = ""

        for number in range(1, self._s.agent_max_steps + 1):
            call, how, said = await self._decide(
                question, found, history,
                provider=provider, model=model, live_allowed=live_allowed,
                open_tables=open_tables,
                # ДАННЫЕ УЖЕ ВЗЯТЫ — значит модели снова можно сказать «хватит».
                #
                # Забыл я это ровно один раз, и замер показал последствие:
                # каждый живой вопрос звал инструмент ДВАЖДЫ
                # (`live_fleet, live_fleet`), потому что на втором шаге отказа
                # в списке действий по-прежнему не было. Модель не упрямилась
                # — ей нечем было остановиться. `tables_ok` 1.000 -> 0.750,
                # `live_clean` 1.000 -> 0.917: вторая таблица на экране,
                # которую никто не просил.
                #
                # Запрет на отказ осмысленен РОВНО до первой удачной выборки:
                # он существует, чтобы модель не увернулась от похода за
                # данными, а не чтобы ходила за ними бесконечно.
                live_done=any(
                    step.tool in LIVE_TOOL_NAMES and step.ok for step in steps
                ),
            )
            mechanism = how
            if call is None:
                declined_with = said
                break

            # Труба, названная в вопросе, подставляется в вызов КОДОМ.
            # Подсказка в состоянии этого не обеспечила — см. `_with_pipe_id`.
            call = _with_pipe_id(call, question)

            key = (call.name, repr(sorted(call.arguments.items())))
            if key in done:
                # Тот же вызов второй раз. Продолжать бессмысленно: ответ
                # будет тот же самый, а шаг и токены потрачены. Модели
                # застревают на этом регулярно — особенно когда первый
                # результат им не понравился.
                steps.append(
                    AgentStep(number, call.name, call.arguments, "повтор того же вызова", 0, False)
                )
                break
            done.add(key)

            # ЛИСТАЕТ ЧЕЛОВЕК, А НЕ АГЕНТ.
            #
            # Метку следующей страницы агент получает двумя путями: её
            # вернул браузер вместе с вопросом (значит человек смотрит на
            # эту таблицу и попросил ещё) — или её выдал инструмент минуту
            # назад, на прошлом шаге этого же вопроса. Первое разрешено,
            # второе нет, и разница не формальная.
            #
            # Из живого прогона: на «дай топ 10 труб» агент брал десять
            # строк, видел в ответе метку и тут же шёл за одиннадцатой-
            # двадцатой. На «как дела?» он притащил строки с 21-й по 38-ю.
            # Никто этого не просил: он просто увидел, что дальше есть ещё.
            #
            # Запретом в промпте это не лечится — мы пробовали, абзац
            # «сам за следующей страницей не ходи» модель игнорирует через
            # раз. Правило простое и проверяемое кодом, значит его место в
            # коде: подкачка страницы — действие человека, а не решение
            # модели.
            page = str(call.arguments.get("cursor") or "").strip()
            if page and page not in allowed_pages:
                steps.append(
                    AgentStep(
                        number, call.name, call.arguments,
                        "эта страница ещё не показана человеку — листать за него не надо",
                        0, False,
                    )
                )
                history.append({
                    "role": "assistant", "content": "",
                    "tool_calls": [
                        {"function": {"name": call.name, "arguments": call.arguments}}
                    ],
                })
                history.append({
                    "role": "tool", "name": call.name,
                    "content": (
                        "Страницу не показал. Следующую страницу запрашивают, только "
                        "когда человек сам попросил её в этом вопросе. Нужные строки "
                        "у тебя уже есть — отвечай."
                    ),
                })
                continue

            # Говорим ДО вызова, а не после: сообщение «иду в сервис»,
            # приходящее вместе с результатом, не сообщает ничего.
            yield AgentProgress(_what_now(call))

            with trace.span("agent_tool", tool=call.name) as span:
                outcome = await self._toolbox.run(
                    call.name, call.arguments, live_allowed=live_allowed
                )
                fresh = _without_known(outcome.hits, found)
                found.extend(fresh)
                if outcome.dataset is not None:
                    datasets.append(outcome.dataset)
                span.attributes.update(added=len(fresh), ok=outcome.ok)

            steps.append(
                AgentStep(
                    number=number,
                    tool=call.name,
                    arguments=call.arguments,
                    result=outcome.text[:400],
                    added=len(fresh),
                    ok=outcome.ok,
                )
            )

            # Диалог продолжаем полностью: и чем просили, и что получили.
            # Без ответа инструмента модель на следующем шаге не знает, что
            # уже спрашивала, и просит то же самое другими словами.
            history.append({
                "role": "assistant",
                "content": "",
                "tool_calls": [{"function": {"name": call.name, "arguments": call.arguments}}],
            })
            history.append({"role": "tool", "name": call.name, "content": outcome.text})
        else:
            hit_limit = self._s.agent_max_steps > 0

        yield AgentOutcome(
            hits=_ordered(found),
            steps=steps,
            datasets=datasets,
            hit_limit=hit_limit,
            # След оборвали, только если последний шаг ЧТО-ТО принёс.
            # Упёрлись в предел после пустого шага — ничего не потеряли.
            trail_cut=hit_limit and bool(steps) and steps[-1].added > 0,
            used_tools=bool(steps),
            mechanism=mechanism,
            declined_with=declined_with,
        )

    async def _decide(
        self, question, found, history, *, provider: str, model: str, live_allowed: bool,
        open_tables: list[OpenTable] | None = None,
        live_done: bool = False,
    ) -> tuple[ToolCall | None, str, str]:
        """Решение модели: (вызов или None, каким механизмом, что сказала).

        Два механизма, и второй не запасной парашют, а рабочий путь для
        моделей, которые не умеют вызывать функции. Таких больше, чем
        кажется: на облачной `GigaChat-3-Lightning` за пять запросов подряд
        не пришло ни одного вызова, включая прямую просьбу пользователя
        сходить в сервис. Тот же бланк ответа по схеме на той же модели
        работает — им отдаётся весь основной ответ системы.

        Способ определяется ОДИН РАЗ на пару «провайдер + модель» и
        запоминается. Выяснять это заново на каждом шаге значило бы платить
        лишним вызовом за уже известное.
        """
        tools = self._toolbox.specs(live_allowed=live_allowed)
        key = (provider or self._providers.chain[0], model)
        mode = self._s.agent_decision
        gave_up = self._native_misses.get(key, 0) >= self.NATIVE_MISS_LIMIT

        if mode != "schema" and not gave_up:
            call, said = await self._ask_native(question, found, history, provider, model, tools, open_tables)
            if call is not None:
                # Вызов пришёл — значит прошлые промахи были случайностью.
                # Счётчик обнуляем, иначе редкие осечки накопятся и
                # отключат работающий механизм на ровном месте.
                self._native_misses.pop(key, None)
                return call, "инструменты", ""
            if _is_decision(said):
                # Модель ответила «ХВАТИТ» — она поняла задачу и приняла
                # решение. Это не промах механизма: счётчик не трогаем и
                # на схему не переходим.
                return None, "инструменты", said
            if mode == "tools":
                return None, "инструменты", said
            # Ни вызова, ни внятного отказа: модель ответила текстом.
            # Засчитываем промах и пробуем схему — на этом шаге.
            self._native_misses[key] = self._native_misses.get(key, 0) + 1

        call, said = await self._ask_schema(
            question, found, history, provider, model, tools, open_tables, live_done
        )
        return call, f"схема{_blank_reason(said, tools) if call is None else ''}", said

    async def _ask_native(self, question, found, history, provider, model, tools, open_tables):
        """Решение через вызов функции — родной механизм провайдера."""
        request = ChatRequest(
            system=AGENT_PROMPT_NATIVE,
            # Родной механизм получает ту же подсказку по тому же правилу:
            # различие между механизмами должно быть в том, КАК модель
            # отвечает, а не в том, что она видит.
            user=_state(
                question, found, open_tables, tools=tools,
                live=live_tool(question, has_open_table=bool(open_tables)) is not None,
            ),
            temperature=self._s.temperature,
            max_tokens=self._s.agent_max_tokens,
            seed=self._s.seed,
            model=model,
            # Инструменты показываем по правам ЭТОГО человека. Показать
            # недоступный означало бы: модель попробует, получит отказ,
            # попробует ещё раз — и потратит шаги на то, чего всё равно
            # нельзя. Отсутствующий инструмент честнее запрещённого.
            tools=tools,
            history=history,
            think=False,
        )
        return await self._run(request, native=True)

    async def _ask_schema(
        self, question, found, history, provider, model, tools, open_tables, live_done=False
    ):
        """Решение через бланк — ДВУМЯ вопросами вместо одного.

        ПОЧЕМУ ДВА, А НЕ ОДИН. Один бланк просил модель сделать четыре дела
        сразу: разобрать вопрос, решить, хватает ли найденного, выбрать
        инструмент и заполнить его параметры. Шесть прогонов подряд она
        делала первые два верно и спотыкалась на третьем. В последнем
        замере её собственные слова были такие:

            «Такие данные есть только в сервисе живых данных.»  -> ХВАТИТ
            «Данные о статусах инспекций берутся из сервиса, а не из
             документов.»                                      -> ХВАТИТ

        То есть вывод правильный и действие ему противоречит — в одной и
        той же генерации. Уговорами это не лечится: я пробовал длину поля,
        порядок значений, лимит токенов, отдельное поле для вывода и прямую
        строку про работающий сервис. Вывод каждый раз становился лучше, а
        действие не менялось.

        Разделение снимает саму возможность такого противоречия:

          вопрос 1: хватает найденного или нужны данные из сервиса? —
                    выбор из ДВУХ значений, без инструментов и параметров;
          вопрос 2: каким инструментом? — задаётся ТОЛЬКО если первый ответ
                    «нужны данные», и в нём УЖЕ НЕТ варианта «ХВАТИТ».

        Второе и есть суть. Сказав «нужны данные», модель больше не может
        увернуться: отказа в списке нет. А риска «позовёт лишнего» нет
        потому, что до второго вопроса дело доходит только после её же
        решения, что найденного мало.

        Цена — лишний вызов модели на тех вопросах, где она говорит «нужны
        данные». Там, где хватает, второго вызова нет вовсе.
        """
        wanted = live_tool(question, has_open_table=bool(open_tables))
        live = _has_live(tools) and wanted is not None and not live_done
        # ПОДСКАЗКА ПРО СЕРВИС — ТОЛЬКО НА ЖИВЫХ ВОПРОСАХ.
        #
        # Висела она на всех, и это стоило десяти обычных вопросов. Замер:
        # «какой порог внимания по выработке» и «к какой длине приводится DLS»
        # уходили в `live_fleet`, таблица встывала в контекст первой, и нужный
        # чанк съезжал с первого места на второе — `chunk_top1` 0.807 -> 0.725.
        # В прогоне без этой строки таких вызовов не было вовсе.
        #
        # Строка писалась, чтобы РАЗБЛОКИРОВАТЬ живые вопросы. На вопросах о
        # правилах она работает подталкиванием в сервис, то есть ровно
        # наоборот. Теперь её показывают тогда, когда она по делу.
        state = _state(question, found, open_tables, tools=tools, live=live)
        if live:
            state = (
                f"{state}\n\nРЕШЕНИЕ УЖЕ ПРИНЯТО: этому вопросу нужны сегодняшние "
                f"данные из сервиса, и подходящий источник — {wanted}.{_named_pipe(question)}\n"
                f"Осталось вызвать его и заполнить параметры. Если считаешь, что "
                f"источник другой, выбери другой — список полный."
            )
        request = ChatRequest(
            system=AGENT_PROMPT,
            user=state,
            temperature=self._s.temperature,
            max_tokens=self._s.agent_max_tokens,
            seed=self._s.seed,
            model=model,
            # Отказ убираем ТОЛЬКО когда решение уже принято кодом. Так модель
            # не может увернуться от выбора источника — именно этим она и
            # занималась шесть прогонов, дописав перед тем верный вывод.
            json_schema=decision_schema(tools, allow_enough=not live),
            history=history,
            think=False,
        )
        call, said = await self._run(request, native=False)
        if call is not None:
            return call, said
        return _call_from_json(said, tools), said


    async def _run(self, request: ChatRequest, *, native: bool) -> tuple[ToolCall | None, str]:
        """Один вызов модели. Ошибку провайдера наверх НЕ поднимаем.

        Агент — надстройка: если он не смог решить, мы отвечаем по тому, что
        уже нашли, то есть работаем как цепочка. Уронить ответ из-за того,
        что не удался необязательный шаг, — это отдать пользователю ошибку
        вместо нормального ответа.
        """
        text: list[str] = []
        try:
            async for chunk in self._providers.stream_chat(request):
                if native and chunk.tool_calls:
                    return chunk.tool_calls[0], ""
                if chunk.text:
                    text.append(chunk.text)
        except (ProviderError, ProviderUnavailable):
            return None, ""
        # Родной механизм возвращает текст — это строка в журнал, и обрезать
        # её незачем жалеть. В схеме текст — это САМ БЛАНК РЕШЕНИЯ: обрезка
        # здесь ломает JSON и превращает вызов инструмента в «модель
        # отказалась». Рубить то, что потом разбираешь, нельзя.
        limit = 400 if native else 2000
        return None, "".join(text).strip()[:limit]


def _is_decision(said: str) -> bool:
    """Модель явно сказала «хватит», а не просто ответила на вопрос.

    Отличать обязательно: «ХВАТИТ» означает, что модель поняла задачу и
    приняла решение. Связный текст ответа означает, что она задачу не
    поняла или не умеет вызывать инструменты — и тогда надо не верить ей на
    слово, а спросить иначе.
    """
    head = said.strip().upper()[:40]
    return head.startswith("ХВАТИТ") or head.startswith("ENOUGH")


def _blank_reason(said: str, tools: list[dict]) -> str:
    """ПОЧЕМУ из бланка не вышло вызова. Приписка к названию способа.

    Без неё в отчёте стояло одно слово «схема» на четыре совершенно разные
    причины, и каждая чинится в другом месте:

      (обрыв)         бланк не дописан — мало токенов;
      (хватит)        модель приняла решение не звать — это промпт;
      (без действия)  бланк дописан, а поле action пустое или с выдумкой —
                      это схема и строгий режим у провайдера;
      (не бланк)      пришёл свободный текст вместо JSON — провайдер схему
                      не применил.

    Я уже один прогон потратил на догадки о том, какая из них была: отчёт
    показывал «ничего не звал», я прочитал это как обрыв, поднял лимит
    токенов — и обрыв не подтвердился. Догадки стоят прогона, приписка —
    десяти строк.
    """
    head = said.lstrip()
    if not head.startswith("{"):
        return " (не бланк)"
    try:
        data = json.loads(head)
    except (json.JSONDecodeError, TypeError):
        return " (обрыв)"
    if not isinstance(data, dict):
        return " (не бланк)"

    action = str(data.get("action") or "").strip()
    if _is_decision(action):
        return " (хватит)"
    names = {spec["function"]["name"] for spec in tools}
    if action and action not in names:
        return f" (выдумал действие: {action!r})"
    return " (без действия)"


def _call_from_json(said: str, tools: list[dict]) -> ToolCall | None:
    """Разбор решения, пришедшего бланком.

    Имя действия проверяется по списку доступных инструментов, а не
    берётся как есть: модель придумывает названия регулярно, а мы по этому
    имени вызываем код.

    АРГУМЕНТЫ ОТБИРАЮТСЯ ПО СХЕМЕ ВЫБРАННОГО ИНСТРУМЕНТА. Бланк решения —
    один плоский объект на все инструменты сразу: в нём есть и `query`, и
    `doc_id`, и `min_damage`. Модель заполняет лишнее по инерции, и раньше
    всё заполненное уезжало в вызов целиком. В логе это выглядело так:

        дочитал раздел «IM-APP…», «Синхронизация с сервером», «0.8»

    Откуда «0.8» у чтения раздела — непонятно никому, включая автора.
    Исполнение от этого не ломалось (инструмент берёт только свои поля),
    но журнал врал, а журналу верят: именно по нему разбирают, что агент
    делал. Отбор по схеме инструмента чинит это в одном месте.
    """
    try:
        data = json.loads(said)
    except (json.JSONDecodeError, TypeError):
        return None
    if not isinstance(data, dict):
        return None

    action = str(data.get("action") or "").strip()
    schemas = {spec["function"]["name"]: spec["function"] for spec in tools}
    if action not in schemas:
        return None

    allowed = (schemas[action].get("parameters") or {}).get("properties") or {}
    arguments = {
        name: data[name]
        for name in allowed
        if name in data and data[name] not in ("", None)
    }
    return ToolCall(name=action, arguments=arguments)


def _state(
    question: str,
    found: list[Hit],
    open_tables: list[OpenTable] | None = None,
    *,
    tools: list[dict] | None = None,
    live: bool = False,
) -> str:
    """Что модель видит перед решением.

    Только выжимки, не полные тексты. Полные тексты стоили бы токенов на
    КАЖДОМ шаге — история отправляется целиком, — а решение «хватит или
    нет» принимается по заголовкам и первым строкам.

    ПОРЯДОК ЗДЕСЬ ТОТ ЖЕ, ЧТО ПЕРЕД СБОРКОЙ КОНТЕКСТА, и это была ошибка,
    пока его тут не было. Выжимка показывает первые шесть фрагментов, а
    то, что модель нашла сама, дописывалось в КОНЕЦ списка — за двадцатый
    номер. Модель сходила в сервис, получила ответ и на следующем шаге
    видела состояние, в котором её находки нет: в списке по-прежнему одни
    определения из вики. Дальше она честно шла искать ещё.

    То есть инструмент работал, а состояние об этом умалчивало. Порядок
    «лучший результат поиска, потом запрошенное моделью» ставит находки
    туда, где их видно.
    """
    head = (
        f"Вопрос: {question}\n\nПока не найдено ничего."
        if not found
        else f"Вопрос: {question}\n\n{preview(_ordered(found), 'Уже найдено:')}"
    )
    parts = [head]
    # Строка про сервис появляется, только когда сервис доступен И вопрос
    # действительно про сегодняшние данные. Второе условие добавлено по
    # замеру: без него она подталкивала модель в сервис на вопросах о
    # правилах, и десять обычных вопросов потеряли первое место в контексте.
    if live and _has_live(tools or []):
        parts.append(LIVE_AVAILABLE)
    tables = open_tables_block(open_tables or [])
    if tables:
        parts.append(tables)
    return "\n\n".join(parts)


def _named_pipe(question: str) -> str:
    """Идентификатор трубы прямо в подсказке, если он назван в вопросе.

    Модель его теряла: на «какая выработка у PP-0035» она дважды звала
    паспорт трубы и ни разу не передала саму трубу. Проверка отбивала вызов
    как паспорт без трубы, таблица не приходила, и ответ выходил такой —
    «данных конкретно по трубе PP-0035 не указано». Имя стояло и в вопросе,
    и в её же ответе, а в аргументах вызова его не было.

    Правило маршрутизации этот идентификатор И ТАК извлекает: по нему оно и
    выбрало `live_pipe`. Просить модель найти его заново — делать дважды уже
    сделанную работу, причём вторым разом менее надёжно.
    """
    named = pipe_id(question)
    if not named:
        return ""
    return f" Идентификатор трубы из вопроса — {named}, передай его как pipe_id."


def _with_pipe_id(call: ToolCall, question: str) -> ToolCall:
    """Дописывает в вызов паспорта трубу из вопроса, если модель её потеряла.

    ЧТО БЫЛО. Замер на 144 вопросах, оба вопроса про конкретную трубу:

        a005 «какая выработка у PP-0035» -> позвала live_pipe, таблиц 0
        a006 «что с трубой PP-0007»      -> позвала live_pipe, таблиц 0

    Инструмент выбран ВЕРНО (`tools_ok` 1.000), а таблица не пришла ни разу.
    Проверено вживую против стенда: `live.pipe("PP-0035")` отдаёт паспорт
    одной строкой, `live.pipe("PP-0007")` — честный отказ E-1042. Клиент
    работает. Значит вызов до клиента не дошёл: его отбила проверка
    «паспорт без идентификатора трубы» в `tools.py`, потому что в аргументах
    трубы не было.

    ПОЧЕМУ НЕ ПОДСКАЗКОЙ. Она уже стоит. В состоянии модели прямым текстом
    написано: «Идентификатор трубы из вопроса — PP-0035, передай его как
    pipe_id». Это седьмой случай за два дня, когда правильная инструкция в
    промпте не превращается в правильный аргумент, и первые шесть учили
    одному и тому же: решение, проверяемое кодом, в код и переносится.

    ПОЧЕМУ ЭТО НЕ ДОГАДКА ЗА МОДЕЛЬ. Мы не выбираем ей инструмент и не
    придумываем аргумент. Она сама выбрала паспорт трубы; труба названа в
    вопросе пользователя, и то же самое правило маршрутизации ПО НЕЙ этот
    паспорт и выбрало. Мы лишь не даём потерять по дороге значение, которое
    уже извлечено и уже использовано.

    ГРАНИЦА. Своё значение модели в приоритете: назвала другую трубу —
    оставляем её. Вопрос мог быть про две трубы, и молча подменить выбор
    значило бы спрятать ошибку вместо того, чтобы дать её увидеть в замере.
    Из вопроса берём только тогда, когда своего обозначения нет вовсе.

    Заодно ЧИСТИМ: «труба PP-0035» и «PP-0035.» — это обозначение с мусором,
    и проверка в `tools.py` их отбивает, хотя клиент справился бы. Одним и
    тем же разбором и находим, и приводим к виду.
    """
    if call.name != "live_pipe":
        return call
    raw = str(call.arguments.get("pipe_id") or "")
    fixed = route.pipe_id(raw) or pipe_id(question)
    if not fixed or fixed == raw:
        return call
    return ToolCall(name=call.name, arguments={**call.arguments, "pipe_id": fixed})


def _has_live(tools: list[dict]) -> bool:
    """Доступен ли модели сервис живых данных ПРЯМО СЕЙЧАС.

    Спрашиваем у списка инструментов, а не у флага прав: список уже собран
    по правам этого человека и по тому, настроен ли сервис. Два источника
    правды здесь означали бы, что однажды они разойдутся, — и состояние
    скажет модели про сервис, которого ей не дали.
    """
    from .rag.tools import LIVE_TOOL_NAMES

    return any(spec["function"]["name"] in LIVE_TOOL_NAMES for spec in tools)


def _without_known(fresh: list[Hit], known: list[Hit]) -> list[Hit]:
    seen = {hit.chunk.chunk_id for hit in known}
    return [hit for hit in fresh if hit.chunk.chunk_id not in seen]


def _ordered(hits: list[Hit]) -> list[Hit]:
    """Порядок фрагментов перед сборкой контекста.

    Правило «лучший фрагмент идёт первым» остаётся: модели хуже используют
    середину длинного контекста, и лучший результат поиска не должен туда
    провалиться.

    Дальше идут фрагменты, которые модель запросила сама. Они стоят выше
    остального поиска сознательно: явная просьба — более сильный сигнал,
    чем место в списке похожести. У них при этом нулевой балл слияния, и
    сортировка по баллу утопила бы их в самый низ, где бюджет контекста их
    просто отрежет — то есть инструмент работал бы, а результата не было
    бы, и объяснить это было бы нечем.
    """
    if not hits:
        return []
    by_score = sorted(hits, key=lambda hit: hit.fused_score, reverse=True)
    # Живые данные — В САМОЕ НАЧАЛО, вперёд лучшего результата поиска.
    #
    # Раньше они шли после него, и на длинном контексте это стоило ответов:
    # модель получала первым куском раздел контракта про поле
    # miner_damage_fraction, а готовый ответ сервиса лежал ниже — и в итоге
    # объясняла, КАК посчитать топ-10, вместо того чтобы его показать.
    #
    # Обоснование не в том, что живые данные «важнее». В том, что они
    # добыты по явному решению агента ИМЕННО ПОД ЭТОТ вопрос, а результат
    # поиска — по похожести слов. Явное намерение — более сильный сигнал,
    # чем близость векторов, и место в контексте должно это отражать.
    live = [hit for hit in hits if hit.chunk.chunk_id < 0]
    searched = [hit for hit in by_score if not hit.origin]
    requested = [hit for hit in hits if hit.origin and hit.chunk.chunk_id >= 0]
    return [*live, *searched[:1], *requested, *searched[1:]]

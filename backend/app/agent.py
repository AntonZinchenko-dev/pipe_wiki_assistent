_DOING = {
    "search_wiki": "ищу в вики ещё раз",
    "read_section": "дочитываю раздел",
    "live_pipe": "иду в базу за паспортом трубы",
    "live_fleet": "иду в базу за данными парка",
    "live_inspections": "иду в базу за инспекциями",
    "live_wells": "иду в базу за скважинами",
}


def _what_now(call: ToolCall) -> str:
    what = _DOING.get(call.name, f"вызываю {call.name}")
    pipe = str(call.arguments.get("pipe_id") or "").strip()
    return f"{what} {pipe}".strip() if pipe else what


@dataclass(slots=True)
class AgentStep:
    """Один шаг: что попросила модель и что из этого вышло."""

    number: int
    tool: str
    arguments: dict
    result: str
    added: int
    ok: bool


@dataclass(slots=True)
class AgentOutcome:
    hits: list[Hit]
    steps: list[AgentStep] = field(default_factory=list)
    # Потолок шагов исчерпан: цикл кончился не потому, что модель сказала
    # «хватит», а потому, что кончились шаги. Признак отдельный, потому что
    # означает «ответ собран из возможно неполного», и в отчёте это надо
    # видеть сразу, а не высчитывать по числу шагов.
    hit_limit: bool = False
    used_tools: bool = False
    # Чем принято решение: «инструменты», «схема» или «не спрашивали».
    #
    # Раньше здесь стояло только `used_tools`, а в комментарии — что
    # «модель отказалась» и «модель не умеет инструменты» снаружи
    # неразличимы и притворяться не надо. Это была ошибка. Различить их
    # дёшево, а без различия агент, который молчит, выглядит одинаково при
    # двух совершенно разных причинах — и чинишь не то. Так и вышло: пять
    # запросов подряд без единого вызова, и по отчёту нельзя было понять,
    # решала модель или не умела.
    mechanism: str = "не спрашивали"
    # Что модель ответила вместо вызова. Пусто, если вызвала.
    #
    # Это и есть недостающая улика: «ХВАТИТ» означает решение, а связный
    # текст ответа на вопрос — что модель не поняла задачу или не умеет
    # инструменты и просто ответила.
    declined_with: str = ""
    # Таблицы, добытые инструментами за все шаги. Уходят в браузер
    # отдельными событиями, минуя модель.
    datasets: list = field(default_factory=list)
    # Шаги кончились, когда след был ЖИВОЙ: последний вызов принёс новые
    # фрагменты, значит следующий мог принести ещё.
    #
    # Это не то же самое, что `hit_limit`. Предел исчерпан и тогда, когда
    # модель последним шагом сходила впустую, — а такой обрыв ничего не
    # стоил, и пугать им пользователя незачем. Ровно это и было в логе:
    # «кончились разрешённые шаги» стояло под полным, правильным ответом,
    # потому что второй шаг не принёс ничего. Предупреждение, которое
    # срабатывает не по делу, через неделю перестают читать вовсе — и
    # тогда оно не сработает и по делу.
    trail_cut: bool = False


class Agent:
    def __init__(
        self,
        *,
        settings: Settings,
        toolbox: Toolbox,
        providers,
    ) -> None:
        self._s = settings
        self._toolbox = toolbox
        self._providers = providers
        # Сколько раз пара «провайдер + модель» промолчала в ответ на
        # показанные инструменты.
        #
        # РАНЬШЕ ЗДЕСЬ БЫЛО МНОЖЕСТВО, И ОДНОГО ПРОМАХА ХВАТАЛО НАВСЕГДА.
        # Это неверно: болтливый ответ вместо вызова бывает и у модели,
        # которая вызовы умеет, — достаточно неудачной формулировки
        # вопроса. Одно наблюдение объявлялось свойством модели, и дальше
        # весь процесс жил со схемой, хотя родной механизм работал.
        #
        # Порог в два промаха стоит один лишний вызов на модель, которая
        # правда не умеет, — и возвращает родной механизм всем, кто просто
        # оступился. Обратная ошибка дороже: она тихая и на весь процесс.
        self._native_misses: dict[tuple[str, str], int] = {}

    # Столько промахов подряд считаем свойством модели, а не случайностью.
    NATIVE_MISS_LIMIT = 2

    async def gather(
        self,
        question: str,
        first: SearchResult,
        *,
        trace: Trace,
        provider: str = "",
        model: str = "",
        live_allowed: bool = False,
        open_tables: list[OpenTable] | None = None,
    ) -> AgentOutcome:
        """Итог работы агента. Тонкая обёртка над `stream` для тех, кому
        промежуточные шаги не нужны."""
        outcome = AgentOutcome(hits=list(first.hits))
        async for item in self.stream(
            question, first, trace=trace, provider=provider, model=model,
            live_allowed=live_allowed, open_tables=open_tables,
        ):
            if isinstance(item, AgentOutcome):
                outcome = item
        return outcome

    async def stream(
        self,
        question: str,
        first: SearchResult,
        *,
        trace: Trace,
        provider: str = "",
        model: str = "",
        live_allowed: bool = False,
        open_tables: list[OpenTable] | None = None,
    ):
        """Добирает фрагменты, сообщая по дороге, чем занят.

        ГЕНЕРАТОР, А НЕ ФУНКЦИЯ, и это не стилистика. Агент работает
        секунды: решает, идёт в сервис, решает снова. Всё это время
        человек смотрит в пустой экран и не знает, думает система или
        зависла. Промежуточные сообщения — единственное лекарство, и
        отдать их можно только по мере появления.

        Последним элементом идёт `AgentOutcome`, до него — `AgentProgress`.

        На вход идёт результат ПЕРВОГО поиска — он уже сделан цепочкой, и
        повторять его было бы просто тратой.
        """
        found: list[Hit] = list(first.hits)
        steps: list[AgentStep] = []
        datasets: list = []
        history: list[dict] = []
        done: set[tuple[str, str]] = set()
        # Метки страниц, которые вернул БРАУЗЕР: только их разрешено листать.
        allowed_pages = {
            table.next_cursor for table in (open_tables or []) if table.next_cursor
        }
        hit_limit = False
        mechanism = "не спрашивали"
        declined_with = ""

        for number in range(1, self._s.agent_max_steps + 1):
            call, how, said = await self._decide(
                question, found, history,
                provider=provider, model=model, live_allowed=live_allowed,
                open_tables=open_tables,
            )
            mechanism = how
            if call is None:
                declined_with = said
                break

            key = (call.name, repr(sorted(call.arguments.items())))
            if key in done:
                # Тот же вызов второй раз. Продолжать бессмысленно: ответ
                # будет тот же самый, а шаг и токены потрачены. Модели
                # застревают на этом регулярно — особенно когда первый
                # результат им не понравился.
                steps.append(
                    AgentStep(number, call.name, call.arguments, "повтор того же вызова", 0, False)
                )
                break
            done.add(key)

            # ЛИСТАЕТ ЧЕЛОВЕК, А НЕ АГЕНТ.
            #
            # Метку следующей страницы агент получает двумя путями: её
            # вернул браузер вместе с вопросом (значит человек смотрит на
            # эту таблицу и попросил ещё) — или её выдал инструмент минуту
            # назад, на прошлом шаге этого же вопроса. Первое разрешено,
            # второе нет, и разница не формальная.
            #
            # Из живого прогона: на «дай топ 10 труб» агент брал десять
            # строк, видел в ответе метку и тут же шёл за одиннадцатой-
            # двадцатой. На «как дела?» он притащил строки с 21-й по 38-ю.
            # Никто этого не просил: он просто увидел, что дальше есть ещё.
            #
            # Запретом в промпте это не лечится — мы пробовали, абзац
            # «сам за следующей страницей не ходи» модель игнорирует через
            # раз. Правило простое и проверяемое кодом, значит его место в
            # коде: подкачка страницы — действие человека, а не решение
            # модели.
            page = str(call.arguments.get("cursor") or "").strip()
            if page and page not in allowed_pages:
                steps.append(
                    AgentStep(
                        number, call.name, call.arguments,
                        "эта страница ещё не показана человеку — листать за него не надо",
                        0, False,
                    )
                )
                history.append({
                    "role": "assistant", "content": "",
                    "tool_calls": [
                        {"function": {"name": call.name, "arguments": call.arguments}}
                    ],
                })
                history.append({
                    "role": "tool", "name": call.name,
                    "content": (
                        "Страницу не показал. Следующую страницу запрашивают, только "
                        "когда человек сам попросил её в этом вопросе. Нужные строки "
                        "у тебя уже есть — отвечай."
                    ),
                })
                continue

            # Говорим ДО вызова, а не после: сообщение «иду в сервис»,
            # приходящее вместе с результатом, не сообщает ничего.
            yield AgentProgress(_what_now(call))

            with trace.span("agent_tool", tool=call.name) as span:
                outcome = await self._toolbox.run(
                    call.name, call.arguments, live_allowed=live_allowed
                )
                fresh = _without_known(outcome.hits, found)
                found.extend(fresh)
                if outcome.dataset is not None:
                    datasets.append(outcome.dataset)
                span.attributes.update(added=len(fresh), ok=outcome.ok)

            steps.append(
                AgentStep(
                    number=number,
                    tool=call.name,
                    arguments=call.arguments,
                    result=outcome.text[:400],
                    added=len(fresh),
                    ok=outcome.ok,
                )
            )

            # Диалог продолжаем полностью: и чем просили, и что получили.
            # Без ответа инструмента модель на следующем шаге не знает, что
            # уже спрашивала, и просит то же самое другими словами.
            history.append({
                "role": "assistant",
                "content": "",
                "tool_calls": [{"function": {"name": call.name, "arguments": call.arguments}}],
            })
            history.append({"role": "tool", "name": call.name, "content": outcome.text})
        else:
            hit_limit = self._s.agent_max_steps > 0

        yield AgentOutcome(
            hits=_ordered(found),
            steps=steps,
            datasets=datasets,
            hit_limit=hit_limit,
            # След оборвали, только если последний шаг ЧТО-ТО принёс.
            # Упёрлись в предел после пустого шага — ничего не потеряли.
            trail_cut=hit_limit and bool(steps) and steps[-1].added > 0,
            used_tools=bool(steps),
            mechanism=mechanism,
            declined_with=declined_with,
        )

    async def _decide(
        self, question, found, history, *, provider: str, model: str, live_allowed: bool,
        open_tables: list[OpenTable] | None = None,
    ) -> tuple[ToolCall | None, str, str]:
        """Решение модели: (вызов или None, каким механизмом, что сказала).

        Два механизма, и второй не запасной парашют, а рабочий путь для
        моделей, которые не умеют вызывать функции. Таких больше, чем
        кажется: на облачной `GigaChat-3-Lightning` за пять запросов подряд
        не пришло ни одного вызова, включая прямую просьбу пользователя
        сходить в сервис. Тот же бланк ответа по схеме на той же модели
        работает — им отдаётся весь основной ответ системы.

        Способ определяется ОДИН РАЗ на пару «провайдер + модель» и
        запоминается. Выяснять это заново на каждом шаге значило бы платить
        лишним вызовом за уже известное.
        """
        tools = self._toolbox.specs(live_allowed=live_allowed)
        key = (provider or self._providers.chain[0], model)
        mode = self._s.agent_decision
        gave_up = self._native_misses.get(key, 0) >= self.NATIVE_MISS_LIMIT

        if mode != "schema" and not gave_up:
            call, said = await self._ask_native(question, found, history, provider, model, tools, open_tables)
            if call is not None:
                # Вызов пришёл — значит прошлые промахи были случайностью.
                # Счётчик обнуляем, иначе редкие осечки накопятся и
                # отключат работающий механизм на ровном месте.
                self._native_misses.pop(key, None)
                return call, "инструменты", ""
            if _is_decision(said):
                # Модель ответила «ХВАТИТ» — она поняла задачу и приняла
                # решение. Это не промах механизма: счётчик не трогаем и
                # на схему не переходим.
                return None, "инструменты", said
            if mode == "tools":
                return None, "инструменты", said
            # Ни вызова, ни внятного отказа: модель ответила текстом.
            # Засчитываем промах и пробуем схему — на этом шаге.
            self._native_misses[key] = self._native_misses.get(key, 0) + 1

        call, said = await self._ask_schema(question, found, history, provider, model, tools, open_tables)
        return call, "схема", said

    async def _ask_native(self, question, found, history, provider, model, tools, open_tables):
        """Решение через вызов функции — родной механизм провайдера."""
        request = ChatRequest(
            system=AGENT_PROMPT_NATIVE,
            user=_state(question, found, open_tables),
            temperature=self._s.temperature,
            max_tokens=self._s.agent_max_tokens,
            model=model,
            # Инструменты показываем по правам ЭТОГО человека. Показать
            # недоступный означало бы: модель попробует, получит отказ,
            # попробует ещё раз — и потратит шаги на то, чего всё равно
            # нельзя. Отсутствующий инструмент честнее запрещённого.
            tools=tools,
            history=history,
            think=False,
        )
        return await self._run(request, native=True)

    async def _ask_schema(self, question, found, history, provider, model, tools, open_tables):
        """Решение через бланк ответа — работает там, где нет вызова функций."""
        request = ChatRequest(
            system=AGENT_PROMPT,
            user=_state(question, found, open_tables),
            temperature=self._s.temperature,
            max_tokens=self._s.agent_max_tokens,
            model=model,
            json_schema=decision_schema(tools),
            history=history,
            think=False,
        )
        call, said = await self._run(request, native=False)
        if call is not None:
            return call, said
        return _call_from_json(said, tools), said

    async def _run(self, request: ChatRequest, *, native: bool) -> tuple[ToolCall | None, str]:
        """Один вызов модели. Ошибку провайдера наверх НЕ поднимаем.

        Агент — надстройка: если он не смог решить, мы отвечаем по тому, что
        уже нашли, то есть работаем как цепочка. Уронить ответ из-за того,
        что не удался необязательный шаг, — это отдать пользователю ошибку
        вместо нормального ответа.
        """
        text: list[str] = []
        try:
            async for chunk in self._providers.stream_chat(request):
                if native and chunk.tool_calls:
                    return chunk.tool_calls[0], ""
                if chunk.text:
                    text.append(chunk.text)
        except (ProviderError, ProviderUnavailable):
            return None, ""
        return None, "".join(text).strip()[:400]


def _is_decision(said: str) -> bool:
    """Модель явно сказала «хватит», а не просто ответила на вопрос.

    Отличать обязательно: «ХВАТИТ» означает, что модель поняла задачу и
    приняла решение. Связный текст ответа означает, что она задачу не
    поняла или не умеет вызывать инструменты — и тогда надо не верить ей на
    слово, а спросить иначе.
    """
    head = said.strip().upper()[:40]
    return head.startswith("ХВАТИТ") or head.startswith("ENOUGH")


def _call_from_json(said: str, tools: list[dict]) -> ToolCall | None:
    """Разбор решения, пришедшего бланком.

    Имя действия проверяется по списку доступных инструментов, а не
    берётся как есть: модель придумывает названия регулярно, а мы по этому
    имени вызываем код.

    АРГУМЕНТЫ ОТБИРАЮТСЯ ПО СХЕМЕ ВЫБРАННОГО ИНСТРУМЕНТА. Бланк решения —
    один плоский объект на все инструменты сразу: в нём есть и `query`, и
    `doc_id`, и `min_damage`. Модель заполняет лишнее по инерции, и раньше
    всё заполненное уезжало в вызов целиком. В логе это выглядело так:

        дочитал раздел «IM-APP…», «Синхронизация с сервером», «0.8»

    Откуда «0.8» у чтения раздела — непонятно никому, включая автора.
    Исполнение от этого не ломалось (инструмент берёт только свои поля),
    но журнал врал, а журналу верят: именно по нему разбирают, что агент
    делал. Отбор по схеме инструмента чинит это в одном месте.
    """
    import json

    try:
        data = json.loads(said)
    except (json.JSONDecodeError, TypeError):
        return None
    if not isinstance(data, dict):
        return None

    action = str(data.get("action") or "").strip()
    schemas = {spec["function"]["name"]: spec["function"] for spec in tools}
    if action not in schemas:
        return None

    allowed = (schemas[action].get("parameters") or {}).get("properties") or {}
    arguments = {
        name: data[name]
        for name in allowed
        if name in data and data[name] not in ("", None)
    }
    return ToolCall(name=action, arguments=arguments)


def _state(question: str, found: list[Hit], open_tables: list[OpenTable] | None = None) -> str:
    """Что модель видит перед решением.

    Только выжимки, не полные тексты. Полные тексты стоили бы токенов на
    КАЖДОМ шаге — история отправляется целиком, — а решение «хватит или
    нет» принимается по заголовкам и первым строкам.

    ПОРЯДОК ЗДЕСЬ ТОТ ЖЕ, ЧТО ПЕРЕД СБОРКОЙ КОНТЕКСТА, и это была ошибка,
    пока его тут не было. Выжимка показывает первые шесть фрагментов, а
    то, что модель нашла сама, дописывалось в КОНЕЦ списка — за двадцатый
    номер. Модель сходила в сервис, получила ответ и на следующем шаге
    видела состояние, в котором её находки нет: в списке по-прежнему одни
    определения из вики. Дальше она честно шла искать ещё.

    То есть инструмент работал, а состояние об этом умалчивало. Порядок
    «лучший результат поиска, потом запрошенное моделью» ставит находки
    туда, где их видно.
    """
    head = (
        f"Вопрос: {question}\n\nПока не найдено ничего."
        if not found
        else f"Вопрос: {question}\n\n{preview(_ordered(found), 'Уже найдено:')}"
    )
    tables = open_tables_block(open_tables or [])
    return f"{head}\n\n{tables}" if tables else head


def _without_known(fresh: list[Hit], known: list[Hit]) -> list[Hit]:
    seen = {hit.chunk.chunk_id for hit in known}
    return [hit for hit in fresh if hit.chunk.chunk_id not in seen]


def _ordered(hits: list[Hit]) -> list[Hit]:
    """Порядок фрагментов перед сборкой контекста.

    Правило «лучший фрагмент идёт первым» остаётся: модели хуже используют
    середину длинного контекста, и лучший результат поиска не должен туда
    провалиться.

    Дальше идут фрагменты, которые модель запросила сама. Они стоят выше
    остального поиска сознательно: явная просьба — более сильный сигнал,
    чем место в списке похожести. У них при этом нулевой балл слияния, и
    сортировка по баллу утопила бы их в самый низ, где бюджет контекста их
    просто отрежет — то есть инструмент работал бы, а результата не было
    бы, и объяснить это было бы нечем.
    """
    if not hits:
        return []
    by_score = sorted(hits, key=lambda hit: hit.fused_score, reverse=True)
    # Живые данные — В САМОЕ НАЧАЛО, вперёд лучшего результата поиска.
    #
    # Раньше они шли после него, и на длинном контексте это стоило ответов:
    # модель получала первым куском раздел контракта про поле
    # miner_damage_fraction, а готовый ответ сервиса лежал ниже — и в итоге
    # объясняла, КАК посчитать топ-10, вместо того чтобы его показать.
    #
    # Обоснование не в том, что живые данные «важнее». В том, что они
    # добыты по явному решению агента ИМЕННО ПОД ЭТОТ вопрос, а результат
    # поиска — по похожести слов. Явное намерение — более сильный сигнал,
    # чем близость векторов, и место в контексте должно это отражать.
    live = [hit for hit in hits if hit.chunk.chunk_id < 0]
    searched = [hit for hit in by_score if not hit.origin]
    requested = [hit for hit in hits if hit.origin and hit.chunk.chunk_id >= 0]
    return [*live, *searched[:1], *requested, *searched[1:]]

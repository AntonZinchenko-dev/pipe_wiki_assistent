def decision_schema(tools: list[dict]) -> dict:
    """Бланк решения для моделей, которые не умеют вызывать функции.

    Запасной путь, и нужен он не для красоты. Вызов функций поддерживают не
    все модели: у нас на облачной `GigaChat-3-Lightning` за пять запросов не
    пришло ни одного вызова, включая прямую просьбу пользователя сходить в
    сервис. А структурированный ответ по схеме на той же модели работает —
    им отдаётся весь основной ответ. Значит агент может принимать решение
    тем же механизмом, которым система уже пользуется.

    Поле `why` идёт ПЕРВЫМ, а `action` после. Это то же правило, что в схеме
    ответа: генерация авторегрессивная, и ярлык, выданный первым, тянет за
    собой обоснование под себя. Схема, начинавшаяся со `status`, стоила нам
    60 отказов из 67 отвечаемых вопросов.
    """
    names = [spec["function"]["name"] for spec in tools]
    return {
        "type": "object",
        "properties": {
            "why": {"type": "string"},
            "action": {"type": "string", "enum": ["ХВАТИТ", *names]},
            "query": {"type": "string"},
            "doc_id": {"type": "string"},
            "heading": {"type": "string"},
            "pipe_id": {"type": "string"},
            "min_damage": {"type": "number"},
            "top_n": {"type": "integer"},
            "cursor": {"type": "string"},
        },
        "required": ["why", "action"],
    }



"""Ответ, который отрицает таблицу, стоящую у человека перед глазами.

ЧТО ПРОИСХОДИТ. Агент сходил в сервис, таблица уехала в браузер, человек её
видит. Отвечающая модель получает выжимку: «Найдено записей: 38. Показано
пользователю: 5», колонки и две строки для примера — первую и последнюю.
И пишет:

    «Во фрагментах нет информации о топ-5 труб по выработке ресурса.
     В таблице T18D0 показаны только три трубы: PP-0035, PP-0007 и PP-0013.»

Обе фразы — про нашу кухню, а не про дело. Человеку не нужно знать, сколько
строк показали модели: перед ним полная таблица, и в ней есть ответ.

ПОЧЕМУ НЕ ПРОМПТОМ. Правила про таблицы это УЖЕ запрещают, прямым текстом и
с тремя примерами «так не надо», один из которых почти дословно совпадает с
тем, что модель написала. За сегодня я шесть раз пытался поправить поведение
модели формулировками — и шесть раз получал лучшее объяснение вместо
лучшего действия. Повторять седьмой раз, имея под рукой детерминированную
починку, было бы упрямством.

ПОЧЕМУ ПОЧИНКА, А НЕ ОТКАЗ. Это ровно тот приём, которым мы уже чиним
ссылки и статус: модель ошиблась в оформлении, а не по сути, и выбросить
весь ответ значило бы наказать человека за нашу проблему. Выбрасываем не
ответ, а вредные предложения.

ГРАНИЦА. Чинится форма, а не смысл. Ответ про не тот предмет здесь не
ловится подстрокой и ловиться не должен: это ошибка понимания.

ПОПРАВКА К ГРАНИЦЕ, сделанная замером. Раньше здесь стояло, что случай
«на какой скважине хуже всего» -> «самая изношенная труба парка PP-0035»
чинить нельзя вовсе. Замер показал, что это было сказано слишком широко.

Тот ответ провалился ДВАЖДЫ, и провалы разной природы. Первый — предмет не
тот, скважину спросили, про трубу ответили: это понимание, и его мы правда
не чиним. Второй — обозначение PP-0035 не встречается НИ В ОДНОМ фрагменте
и ни в вопросе, то есть придумано; это не понимание, а факт, и он
проверяется сравнением строк — тем же, которым мы уже ловим выдуманные
трубы в списках.

Разница в том, есть ли куда отступить. Без таблицы отступать некуда, и
выброшенное предложение оставило бы человека без ответа. С таблицей
отступать есть: перед ним стоят СКВАЖИНЫ, отсортированные по выработке, и
первая строка — ответ на его вопрос. Тогда «Данные в таблице выше» лучше,
чем выдуманная труба с правдоподобным процентом.

Замер при этом остаётся полным: выброшенные обозначения не исчезают, они
переезжают в отдельное поле и по-прежнему роняют `live_clean`. Мы перестаём
ПОКАЗЫВАТЬ дефект человеку, но не перестаём его считать — иначе починка
превратилась бы в сокрытие, чего исходная граница и боялась.
"""

from __future__ import annotations

import re

# ОТРИЦАНИЕ ДАННЫХ. Те же обороты, что ловит метрика `table_answered`:
# список взят из живых прогонов, а не выдуман.
_DENIES = re.compile(
    r"(во фрагмент\w+ нет"
    r"|нет (?:информации|сведений|данных)"
    r"|не указан\w*"
    r"|данны\w+ (?:отсутству|нет))",
    re.I,
)

# РАССКАЗ ПРО НАШУ КУХНЮ. Сколько строк показали модели — служебная деталь.
# Человек видит таблицу целиком, и «показаны только три трубы» звучит как
# отказ отвечать над полными данными.
# ПЕРЕЧЕНЬ ОБОРОТОВ ЗАМЕНЁН НА ПРИЗНАК. Причина — свежий провал.
#
# Список формулировок пропустил вот это, на вопросе «следующие 5», когда
# таблица с ними пришла и стояла у человека перед глазами:
#
#     «Во ФРАГМЕНТЕ приведена только одна строка таблицы: Труба PP-0035...
#      Следующие пять труб не показаны и не перечислены.»
#
# Дописать сюда ещё один оборот значило бы играть в догонялки: формулировок
# у модели бесконечно, и каждая новая приходит отдельным прогоном.
#
# Признак вместо списка: слово «фрагмент» — наше служебное. Человек его не
# знает, в интерфейсе оно не показывается (там «источники»), и в корпусе его
# нет. Предложение про фрагмент — это предложение про нашу кухню по
# определению, а не по формулировке.
#
# То же со «строками таблицы» и «перечислены»: сколько строк уехало в
# выжимку модели — служебная деталь, человек видит таблицу целиком.
#
# Проверка работает ТОЛЬКО при пришедшей таблице (см. `repair`), поэтому
# честный отказ по документам «во фрагментах нет данных» не задевается.
_KITCHEN = re.compile(
    r"(\bфрагмент\w*"
    r"|строк[аиуе]\w* таблиц\w+"
    r"|не (?:показан\w*|перечислен\w*|привед\w+)"
    r"|показан[аы]? только"
    r"|показана только перв\w+"
    r"|остальны\w+ (?:строки|записи) не показан"
    r"|(?:я )?(?:вижу|могу показать) только"
    r"|не вижу (?:остальны|други))",
    re.I,
)

# Ответ, когда добавить к таблице нечего. Ровно та формулировка, которую
# правила про таблицы называют полноценным ответом.
ENOUGH = "Данные в таблице выше."

# Разделение на предложения. Грубое и намеренно такое: аккуратное потребует
# словаря сокращений, а цена ошибки здесь — одно лишнее или недостающее
# предложение в ответе, который мы и так переписываем.
_SENTENCE = re.compile(r"(?<=[.!?])\s+")

_REF = re.compile(r"\[(\d+(?:\s*,\s*\d+)*)\]")


def _refs(text: str) -> set[int]:
    numbers: set[int] = set()
    for group in _REF.findall(text):
        for part in group.split(","):
            part = part.strip()
            if part.isdigit():
                numbers.add(int(part))
    return numbers


def repair(answer: str, *, tables: int, enough: str = ENOUGH) -> tuple[str, int]:
    """Убирает из ответа отрицание таблицы. Возвращает (текст, сколько убрано).

    Без таблиц не трогаем ничего: отрицание в ответе по документам — это
    честный отказ, и подменять его было бы враньём в другую сторону.

    `enough` — чем отвечать, когда от ответа не осталось ничего. По умолчанию
    «Данные в таблице выше»; вызывающий вправе передать что-то содержательнее,
    собранное из той же таблицы. Решение о подмене принимается там, потому что
    здесь неизвестно, о чём был вопрос.
    """
    if not tables or not answer.strip():
        return answer, 0

    sentences = _SENTENCE.split(answer.strip())
    kept = [s for s in sentences if not (_DENIES.search(s) or _KITCHEN.search(s))]
    removed = len(sentences) - len(kept)
    if not removed:
        return answer, 0
    if not kept:
        return enough, removed
    return " ".join(kept), removed


def drop_invented(
    answer: str, *, invented: list[str], tables: int, enough: str = ENOUGH
) -> tuple[str, list[str]]:
    """Убирает предложения с придуманными обозначениями. Возвращает (текст, что убрано).

    «Придуманное» здесь — не догадка: список приходит от проверки, которая
    сравнивает обозначения из ответа с текстом ВСЕХ фрагментов и вопроса.
    Нет нигде — значит его не нашли, а составили.

    Без таблиц не трогаем ничего, и это главное условие. Тогда выброшенное
    предложение не заменить ничем, и человек остался бы без ответа вместо
    ответа с пометкой — то есть мы наказали бы его за нашу проблему сильнее,
    чем сама проблема.

    Сравнение без учёта регистра: «pp-0035» в ответе и «PP-0035» во фрагменте
    — одно и то же обозначение, и различать их означало бы ловить выдумку там,
    где её нет.
    """
    if not tables or not invented or not answer.strip():
        return answer, []

    wanted = [name for name in invented if name.strip()]
    sentences = _SENTENCE.split(answer.strip())
    kept: list[str] = []
    dropped: list[str] = []
    for sentence in sentences:
        low = sentence.lower()
        here = [name for name in wanted if name.lower() in low]
        if here:
            dropped.extend(here)
            continue
        kept.append(sentence)
    if not dropped:
        return answer, []
    # Порядок устойчивый: список уходит в журнал и в прогон, и прыгающий
    # порядок мешает сравнивать запуски.
    unique = sorted(set(dropped))
    if not kept:
        return enough, unique
    return " ".join(kept), unique


def surviving_refs(answer: str) -> set[int]:
    """Номера фрагментов, оставшиеся в тексте после починки.

    Нужны, чтобы выбросить осиротевшие ссылки: цитата на фрагмент, номера
    которого в тексте больше нет, — это ссылка в никуда. Проверка цитат у
    нас строгая, и оставить такую значило бы своими руками создать то, что
    она ловит.
    """
    return _refs(answer)

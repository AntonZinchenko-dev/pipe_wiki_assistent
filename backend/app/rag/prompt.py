#
# Но между «править на живом» и «выкладывать релиз ради отката» есть третий
# вариант, и он здесь: версии живут рядом, а какая из них работает —
# настройка. Откат становится сменой значения и перезапуском, без сборки,
# без релиза и без правки кода.
#
# ГЛАВНОЕ ПРАВИЛО: МЕНЯТЬ ПРОМПТ ЗНАЧИТ ДОБАВЛЯТЬ ВЕРСИЮ, А НЕ ПРАВИТЬ
# СУЩЕСТВУЮЩУЮ.
#
# Если отредактировать текст версии 1.0 на месте, откатываться станет не к
# чему: старого текста больше нет нигде, кроме истории git, а из истории git
# прод не поднимешь одной переменной. Правило сторожится тестом: у каждой
# версии записан отпечаток её содержимого, и правка текста на месте роняет
# проверку. Это не формальность — это единственное, что отличает настоящий
# реестр версий от папки, в которой лежит одна версия.


@dataclass(frozen=True, slots=True)
class PromptSpec:
    """Одна версия промпта: текст, бланк ответа и почему она такая."""

    name: str
    system: str
    schema: dict
    note: str
    # Отпечаток содержимого на момент заморозки. Сторожит правку на месте.
    frozen_at: str = ""

    @property
    def digest(self) -> str:
        return hashlib.sha256((self.system + str(self.schema)).encode()).hexdigest()[:8]

    @property
    def version(self) -> str:
        """Имя плюс отпечаток содержимого.

        Имя нужно человеку, отпечаток — журналу: по нему видно, что текст
        под тем же именем не подменили. Одного имени мало ровно потому, что
        имена переиспользуют.
        """
        return f"{self.name}+{self.digest}"



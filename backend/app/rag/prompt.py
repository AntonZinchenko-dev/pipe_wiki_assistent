# из 67 отвечаемых вопросов при том, что нужный абзац лежал в контексте (см.
# ШАГ-2-ВЫВОДЫ). Поэтому ярлык идёт ПОСЛЕ содержания: сначала ответ, потом
# пометка о том, что получилось.

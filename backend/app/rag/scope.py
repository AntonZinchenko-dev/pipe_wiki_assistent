"""Вопрос вообще про нашу вики? Решается словарём корпуса, а не моделью.

ЗАЧЕМ. Из живой переписки и прогонов:

    «как дела?»   -> «Текущий статус: сервис работает, табло заполнились
                      в 08:05...»
    «что»         -> «Труба не списывается по расчёту усталости...»
    «чо пао чем»  -> развёрнутый рассказ про постмортемы

Система уверенно отвечает на реплики, в которых нет вопроса. Это хуже
неверного ответа: неверный ответ человек может заметить, а этот выглядит
как работа.

ПОЧЕМУ НЕ ПОРОГОМ БЛИЗОСТИ. Пробовали, данные против. У «как дела?»
косинус 0.457, у «что» — 0.409, а у настоящих отвечаемых вопросов нижняя
граница 0.425. Диапазоны перекрываются: порог, который отсечёт мусор,
отрежет и честные вопросы. Косинус тут не разделяет, и калиброванный порог
0.45 это уже учитывает.

ПОЧЕМУ НЕ МОДЕЛЬЮ. Она и есть тот, кто ошибается: статус `need_clarification`
у нас существует, и на «чо пао чем» модель его не поставила. Просить её
решать надёжнее — это то, что за день не сработало шесть раз подряд.

ЧТО РАЗДЕЛЯЕТ. Слова. У вопроса про вики хотя бы одно своё слово
встречается в корпусе; у «как дела?» — ни одного, слова «дела» в наших
шестнадцати документах нет вовсе. Проверка считается по словарю индекса,
поэтому она не отстанет от корпуса: добавят документ про отпуска — вопросы
про отпуска сами перестанут отсекаться.

ЗАМЕР ОФЛАЙН НА ВСЕХ 134 ВОПРОСАХ НАБОРА:

    поймано неотвечаемых: 3   (q120 «как дела?», q121 «что», a012)
    ложных срабатываний:  0

Плюс на заведомом мусоре, которого в наборе нет: «чо пао чем», «сосал?».

ПЕРЕКОС В СТОРОНУ ОТВЕТА. Отказать на честном вопросе дороже, чем ответить
на мусорный: первое человек запомнит как «эта штука не работает». Поэтому
вопрос с идентификатором («что с трубой PP-0007») не отсекается никогда —
обозначение само по себе ссылка на наш предмет, даже если остальные слова
мимо словаря.
"""

from __future__ import annotations

import re

# Длина основы. Пять букв выбраны замером, а не на глаз: на четырёх
# «как дела?» проскакивает (основы слипаются и случайно находятся в
# корпусе), на пяти ловится, и ложных срабатываний по-прежнему ноль.
STEM = 5

# Слова короче этого — предлоги и союзы. Тот же порог, что в разборе
# истории: заводить словарь стоп-слов ради одного правила невыгодно, а
# поддерживать его пришлось бы вечно.
MIN_WORD = 3

_WORDS = re.compile(r"[A-Za-zА-Яа-яЁё0-9_]+")
_IDENTIFIER = re.compile(r"\b[A-ZА-Я]{1,5}-\d[\d.]{0,14}(?:-\d{1,4})*\b")


def stems(text: str) -> set[str]:
    """Основы слов длиннее трёх букв. Грубо и намеренно грубо.

    Настоящая лемматизация потребовала бы словаря русского языка ради
    одной проверки. Обрезка по первым буквам склеивает падежи («трубы»,
    «трубе», «трубой») — а больше от неё здесь ничего и не нужно.
    """
    return {word[:STEM] for word in _WORDS.findall(text.lower()) if len(word) > MIN_WORD}


def vocabulary(texts: list[str]) -> set[str]:
    """Словарь корпуса: основы всех слов индекса."""
    found: set[str] = set()
    for text in texts:
        found |= stems(text)
    return found


def nothing_to_search(question: str, corpus: set[str]) -> bool:
    """Вопрос не о нашей вики: искать нечего, и модель звать незачем.

    Пустой словарь означает «индекс не построен», и тогда проверка
    отключается сама: отвечать «это не про вики» на пустом индексе значит
    валить нашу же недонастройку на пользователя.
    """
    if not corpus or _IDENTIFIER.search(question):
        return False
    own = stems(question)
    if not own:
        # Своих слов нет вовсе: «что», «чо пао чем». Искать нечего буквально.
        return bool(_WORDS.search(question))
    return not (own & corpus)



"""Результат инструмента как ДАННЫЕ, а не как текст для пересказа.

ЧТО БЫЛО НЕ ТАК

Инструмент возвращал строку. Строка ехала в контекст, модель её читала и
переписывала в ответ своими словами. Выглядело это разумно ровно до того
дня, когда ответом стал список.

Из живых прогонов, все три — разные модели, одна и та же болезнь:

    PP-0001, выработка 7 %      (в сервисе 77.0)
    PP-0029, выработка 72.0 %   (такой трубы в парке нет)
    «Топ-5: … Данные для пятой трубы недоступны»  (были все пять)

Это не глупость моделей. Это неизбежное следствие постановки задачи:
модель просили ПЕРЕПИСАТЬ таблицу. Переписывание десяти строк с числами —
механическая работа, в которой генеративная модель ошибается по
построению, и никакой промпт этого не отменяет.

ЧТО СТАЛО

Данные к пользователю идут НАПРЯМУЮ: сервер отдаёт их отдельным событием,
браузер рисует таблицу сам. Модель их не переписывает — она их вообще не
получает целиком.

Модель получает ВЫЖИМКУ: сколько нашлось, сколько показано, как называются
колонки, первая и последняя строка для связного текста. Её работа — не
перепечатать таблицу, а сказать, что из этой таблицы следует по правилам
из документов. Вот это генеративная модель делает хорошо.

ТРИ СЛЕДСТВИЯ, И КАЖДОЕ САМО ПО СЕБЕ ОКУПАЕТ ПЕРЕДЕЛКУ

1. Таблица больше не может быть неверной. Её никто не генерирует —
   значит класс ошибок «перепутал цифру» исчез целиком, а не уменьшился.
2. Токены. Сорок строк парка стоили около полутора тысяч токенов в
   контексте плюс столько же на выходе. Теперь — три десятка токенов
   выжимки, а пользователь видит БОЛЬШЕ, чем раньше: показать сорок строк
   в интерфейсе ничего не стоит.
3. Пользователю видно, что скрыто. `total_found` и `truncated` говорят
   «нашлось 40, показано 5» — раньше это терялось в пересказе, и «топ-5»
   читалось как «в парке пять труб».

ОШИБКА — ТОЖЕ РЕЗУЛЬТАТ, А НЕ ИСКЛЮЧЕНИЕ

У неё та же оболочка: код, сообщение, можно ли повторять, через сколько и
что делать человеку. Модель по этому пишет нормальный ответ («по PP-0007
расчёт устарел, повторите через минуту»), а не «произошла ошибка».
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass, field

# Сколько строк показываем ЧЕЛОВЕКУ. Это ограничение интерфейса и сети, а
# не контекста: в контекст строки больше не попадают вовсе.
MAX_ROWS_FOR_VIEW = 200

# Сколько строк видит МОДЕЛЬ. Одна — первая.
#
# Не ноль, потому что без единого примера ответ получается обезличенным:
# «нашлось 40 труб» вместо «самая изношенная PP-0035, 97.7 %».
#
# И НЕ ДВЕ, хотя сначала было две. Первая и последняя строка вместе
# читаются как начало и конец последовательности, а последовательность
# хочется продолжить. На странице из 29 строк модель получила первую и
# последнюю — и дописала середину из головы: PP-0092, PP-0088, PP-0067,
# PP-0072. Таких труб в парке нет.
#
# Один пример — это пример. Два примера — это образец для подражания.
SAMPLE_ROWS = 1

# ЧТО ТАКОЕ ОДНА СТРОКА. По виду таблицы, а не по догадке.
#
# Зачем это отдельной строкой в выжимке, если есть заголовок и колонки.
# Затем, что заголовок и колонки говорят, ЧТО В ТАБЛИЦЕ, и не говорят, ЧТО
# ЕСТЬ ОДНА ЗАПИСЬ. На таблице скважин модель ответила про трубу: колонка
# «Труб в скважине» рядом с «Худшая труба, выработка» описывает трубы, и по
# описанию колонок предмет строки не восстановить.
#
# Это ИНФОРМАЦИЯ, которой у модели не было, а не просьба не путать. Разница
# существенная: за два дня шесть попыток изменить поведение запретом в
# промпте не дали ничего, а единственная удача была там, где модели дали
# недостающий факт — идентификатор трубы в подсказке. Выжимка для того и
# существует, чтобы описывать таблицу; здесь у неё был пробел.
ROW_MEANS = {
    "wells.fleet": "Одна строка — одна СКВАЖИНА, не труба.",
    "pipes.fleet": "Одна строка — одна труба.",
    "pipes.inspections": "Одна строка — одна труба.",
    "pipe.passport": "Вся таблица — одна труба.",
}


@dataclass(frozen=True, slots=True)
class Column:
    """Описание колонки. `key` — ключ в строке, `title` — заголовок в таблице."""

    key: str
    title: str
    unit: str = ""
    # `number` выравнивается вправо и форматируется, `text` — нет.
    kind: str = "text"


@dataclass(frozen=True, slots=True)
class ToolError:
    """Отказ инструмента в разобранном виде.

    `retriable` и `retry_after_s` — не украшение: это разница между
    «подождите минуту» и «этой трубы нет, повтор не поможет». Модель без
    них пишет одинаковое «произошла ошибка» в обоих случаях, и человек
    идёт пробовать снова там, где пробовать бессмысленно.
    """

    code: str
    message: str
    retriable: bool = False
    retry_after_s: int | None = None
    hint: str = ""


@dataclass(slots=True)
class Dataset:
    """Таблица, добытая инструментом: данные для экрана, выжимка для модели."""

    kind: str
    title: str
    columns: list[Column] = field(default_factory=list)
    rows: list[dict] = field(default_factory=list)
    # Сколько НАШЛОСЬ всего — не сколько показано. Разница и есть главное,
    # что теряется при пересказе.
    total_found: int = 0
    # Сколько записей вообще просмотрено, чтобы отобрать показанные.
    scanned: int = 0
    # С какой по счёту записи начинается показанное.
    #
    # ДОБАВЛЕНО ПО ПРОМАХУ, и промах показательный. Оболочка честно
    # сообщала «показано 5 из 39» — и не давала никакого способа получить
    # остальные 34. На просьбу «следующие 5» модели оставалось одно:
    # запросить первые десять и назвать словами строки с шестой по
    # десятую. То есть ровно то переписывание таблицы, ради избавления от
    # которого всё и затевалось.
    #
    # Урок общий: оболочка, которая объявляет о существовании скрытых
    # данных, обязана давать способ их достать. Иначе она не описывает
    # ограничение, а провоцирует его обход.
    offset: int = 0
    truncated: bool = False
    hint: str = ""
    taken_at: str = ""
    error: ToolError | None = None
    # Строки, по которым данных получить не удалось. Молчать о них нельзя:
    # «две трубы за порогом» и «две за порогом, по одной расчёт устарел» —
    # разные ответы, и второй честный.
    skipped: list[str] = field(default_factory=list)
    # Метка следующей страницы. Пусто — дальше ничего нет.
    #
    # МОДЕЛЬ НЕ СЧИТАЕТ НИЧЕГО, и это главное. Пока страница задавалась
    # смещением, на «следующие 5» после первой пятёрки модель передала
    # offset=1 — и получила строки со второй по шестую. Она не ошиблась в
    # арифметике, она по-другому поняла слово «смещение»: как «номер
    # начальной строки», а не «сколько пропустить».
    #
    # Спорить с таким бесполезно: любое название параметра кто-нибудь
    # поймёт иначе. Метку модель не толкует — она передаёт её обратно как
    # есть, и ошибиться в этом нечем.
    next_cursor: str = ""

    @property
    def handle(self) -> str:
        """Короткий и УСТОЙЧИВЫЙ номер таблицы.

        Считается от содержимого, а не от счётчика: два одинаковых вызова
        в одном ответе получают один номер, и в журнале прогона номера не
        прыгают от запуска к запуску. Прыгающий идентификатор сделал бы
        два одинаковых прогона несравнимыми на ровном месте.
        """
        material = json.dumps(
            [self.kind, self.title, self.total_found, self.rows[:1]],
            ensure_ascii=False, sort_keys=True, default=str,
        )
        return "T" + hashlib.sha1(material.encode()).hexdigest()[:4].upper()

    def to_dict(self) -> dict:
        """Полный вид — для интерфейса. Сюда уходят все строки."""
        return {
            "handle": self.handle,
            "kind": self.kind,
            "title": self.title,
            "columns": [asdict(column) for column in self.columns],
            "rows": self.rows[:MAX_ROWS_FOR_VIEW],
            "total_found": self.total_found,
            "scanned": self.scanned,
            "offset": self.offset,
            "truncated": self.truncated or len(self.rows) > MAX_ROWS_FOR_VIEW,
            "hint": self.hint,
            "taken_at": self.taken_at,
            "skipped": self.skipped,
            "next_cursor": self.next_cursor,
            "error": asdict(self.error) if self.error else None,
        }

    def digest(self) -> str:
        """Выжимка — для модели. Строк здесь нет, есть их описание.

        Текст написан так, чтобы на него можно было СОСЛАТЬСЯ: проверка
        цитат работает с ним как с обычным фрагментом документа, и
        утверждение «нашлось 40 труб» остаётся подтверждаемым.

        Запрет переписывать таблицу стоит прямо здесь, потому что это наша
        разметка вокруг данных, а не текст из документа. Модели, читающей
        фрагмент, надо сказать не только что в нём, но и что с ним делать.
        """
        if self.error:
            return self._error_digest()

        first = self.offset + 1
        last = self.offset + len(self.rows)
        where = (
            f"Показаны строки с {first}-й по {last}-ю"
            if self.offset
            else f"Показано пользователю: {len(self.rows)}"
        )
        lines = [
            f"Таблица {self.handle}: {self.title}.",
            f"Найдено записей: {self.total_found}. {where}."
            + (f" Просмотрено: {self.scanned}." if self.scanned else ""),
        ]
        if self.truncated:
            hidden = self.total_found - last
            if hidden > 0:
                lines.append(f"Ниже по списку есть ещё {hidden} записей, они не показаны.")
        if self.columns:
            lines.append("Колонки: " + ", ".join(column.title for column in self.columns) + ".")
        means = ROW_MEANS.get(self.kind, "")
        if means:
            lines.append(means)

        for label, row in self._sample():
            lines.append(f"{label}: {self._row_text(row)}.")

        if self.skipped:
            lines.append("Не удалось получить данные по: " + ", ".join(self.skipped) + ".")

        # ПОДСКАЗКИ ЗДЕСЬ НЕТ, и это не забывчивость.
        #
        # Подсказка «попросите следующие 5» написана ЧЕЛОВЕКУ и стоит под
        # таблицей, где он её видит. Попав во фрагмент, она прочиталась
        # дважды не тем: агент воспринял её как указание себе и сходил за
        # второй страницей, которую никто не просил, а отвечающая модель
        # пересказала её пользователю — «остальные четыре строки не
        # показаны, их можно получить по запросу „следующие 5“».
        #
        # Текст, написанный для одного получателя, нельзя класть туда, где
        # его прочитают трое.
        return "\n".join(lines)

    def agent_note(self) -> str:
        """То же для АГЕНТА, плюс метка следующей страницы.

        Агенту она нужна (он решает, звать ли инструмент снова),
        отвечающей модели — нет. Разделение не формальное: всё, что
        попадает во фрагмент, модель считает материалом для цитаты.
        """
        note = self.digest()
        if self.offset:
            # Агенту это знать надо: иначе он решит, что показал начало.
            note += (
                f"\nЭто не начало списка: первые {self.offset} записей остались выше."
            )
        if self.hint:
            note += f"\n{self.hint}"
        # МЕТКИ СЛЕДУЮЩЕЙ СТРАНИЦЫ ЗДЕСЬ НЕТ, и это не потеря.
        #
        # Она тут была, и агент вёл себя ровно так, как его попросили:
        # видел метку и шёл за следующей страницей. На «дай топ 10 труб» он
        # приносил двадцать строк, на «как дела?» — восемнадцать.
        #
        # Метка нужна ему только тогда, когда следующую страницу попросил
        # человек, и в этом случае она приходит другим путём: браузер
        # возвращает её вместе с вопросом, и она стоит в блоке «уже
        # показанные таблицы». Инструмент, только что отдавший страницу,
        # приглашать за следующей не должен — он не знает, просили ли её.
        return note

    def _sample(self) -> list[tuple[str, dict]]:
        if not self.rows:
            return []
        if len(self.rows) == 1:
            return [("Единственная строка", self.rows[0])]
        head = "Первая показанная строка" if self.offset else "Первая строка"
        picked = [(head, self.rows[0])]
        if SAMPLE_ROWS > 1:
            picked.append(("Последняя показанная строка", self.rows[-1]))
        return picked[:SAMPLE_ROWS]

    def leading_row(self) -> str:
        """Верхняя показанная строка словами. Пусто — строк нет.

        Нужна откату: когда предложение модели выброшено за выдуманное
        обозначение, «Данные в таблице выше» безопасно и бесполезно — человек
        и сам видит, что таблица выше. А ответ у нас на руках: у
        отсортированной выборки верхняя строка и есть крайнее значение.

        Здесь только рендер. РЕШЕНИЕ, годится ли верхняя строка ответом,
        принимается выше: на «дай топ 5» она не ответ, и подменять ею было бы
        новым дефектом вместо починки старого.
        """
        if not self.rows:
            return ""
        return self._row_text(self.rows[0])

    def _row_text(self, row: dict) -> str:
        parts = []
        for column in self.columns:
            value = row.get(column.key)
            if value is None or value == "":
                continue
            unit = f" {column.unit}" if column.unit else ""
            parts.append(f"{column.title} {value}{unit}")
        return ", ".join(parts)

    def _error_digest(self) -> str:
        error = self.error
        assert error is not None
        lines = [f"Запрос «{self.title}» не удался. Код {error.code}: {error.message}"]
        if error.retriable:
            when = (
                f" не раньше чем через {error.retry_after_s} с"
                if error.retry_after_s
                else ""
            )
            lines.append(f"Отказ временный, запрос можно повторить{when}.")
        else:
            lines.append("Отказ постоянный, повторять запрос бессмысленно.")
        if error.hint:
            lines.append(error.hint)
        lines.append(
            "Скажи об этом человеку прямо: что именно не получилось, почему и что "
            "делать дальше. Не выдумывай значения вместо недостающих."
        )
        return "\n".join(lines)


# Как говорить о таблицах. Блок сообщения, а НЕ фрагмент документа.
#
# Сначала эти правила лежали внутри фрагмента таблицы, вместе с данными.
# Результат вышел закономерный: модель пересказала их пользователю.
#
#   «В таблице T98D4, которая уже показана пользователю на экране целиком,
#    отображены топ-5 труб. Остальные строки не показаны — их можно
#    увидеть только если запросить „следующие 5“.»
#
# И сослалась на них как на источник, процитировав мою собственную
# служебную строку как содержание документа.
#
# Всё, что лежит во фрагменте, модель считает материалом для цитирования —
# так мы её и учили. Значит инструкции во фрагменте лежать не могут: их
# место в сообщении, рядом с вопросом.
TABLE_RULES = """<о таблицах>
Фрагменты «живые данные сервиса» — это выжимки таблиц, которые человек УЖЕ \
видит на экране целиком. ТАБЛИЦА И ЕСТЬ ОТВЕТ.

Твоя работа — не пересказать её, а добавить то, чего в ней нет: правило из \
документов, порог, вывод. Одна-две фразы.

ЕСЛИ ДОБАВИТЬ НЕЧЕГО — так и напиши одной строкой: «Данные в таблице выше.» \
Это полноценный ответ, а не неудача. Пустое место в конце ответа заполнять \
не надо, и вот чем его заполнять НЕЛЬЗЯ:

— выдуманными записями. Ни одной строки, кроме первой, ты не видишь. \
Название, номер, дата, статус, которых нет во фрагментах, — это выдумка, \
даже если они выглядят правдоподобно;
— выдуманными сервисами и эндпоинтами. Если в документах нет такой системы, \
её не существует;
— советом обратиться в другую систему, в поддержку или «запросить \
дополнительные данные». Человек уже получил данные, они перед ним;
— рассказом о том, чего ты не видишь и почему. Сколько строк тебе показано — \
наша кухня, пользователю это знать незачем, и звучит это как отказ отвечать \
над полной таблицей.

Так НАДО:
«Самая изношенная труба парка — PP-0035, выработано 97.7 % ресурса. Это выше \
инженерного порога 80 % [3], но списывают по осмотру, а не по расчёту [4].»

Так НАДО, когда правила по теме в документах нет:
«Данные в таблице выше.»

Так НЕ НАДО:
«В таблице T98D4 показаны топ-5 труб. Первая строка: Труба PP-0035, Выработка \
97.7 %, Циклов 1990578. Остальные строки не показаны — их можно получить по \
запросу «следующие 5».»

Так НЕ НАДО:
«Я могу показать только первую строку таблицы. Для получения информации о \
следующих пяти скважинах обратитесь к системе напрямую.»

Так НЕ НАДО:
«Обращаюсь к сервису WELLD. Скважина WELL-00123456789, статус Drilled and \
completed, начало бурения 2026-01-15.»
</о таблицах>"""


@dataclass
class OpenTable:
    """Таблица, которая УЖЕ на экране у человека, с меткой следующей страницы.

    Нужна затем, что таблицы живут в браузере, а сервер диалогов не помнит.
    Из живого прогона: человек получил строки 1–5 и написал «следующие 5».
    Метка `fleet|0.0000|5|5` лежала в браузере, до агента не доехала — и он,
    не зная, где остановился, запросил первые десять, а следом одиннадцатую
    по двадцатую. Человек увидел те же пять строк ещё раз и ни одной новой.

    Это обычный курсор, и держит его тот, кто листает, — клиент. Сервер
    остаётся без памяти о диалогах, а «следующие пять» перестаёт быть
    догадкой.
    """

    handle: str
    title: str
    offset: int
    shown: int
    total_found: int
    next_cursor: str


def open_tables_block(tables: list[OpenTable]) -> str:
    """Строка состояния для АГЕНТА: что уже показано и чем листать дальше.

    Отвечающей модели этот текст не нужен и вреден — она пересказала бы его
    человеку. Та же причина, по которой подсказка ушла из `digest()`.
    """
    if not tables:
        return ""
    lines = ["Уже показанные человеку таблицы (он их видит, заново не запрашивай):"]
    for table in tables:
        first = table.offset + 1
        last = table.offset + table.shown
        line = f"— {table.handle} «{table.title}»: строки {first}–{last} из {table.total_found}."
        if table.next_cursor:
            line += (
                f" Следующая страница — тот же инструмент с "
                f"cursor={table.next_cursor!r}, строку не меняй и не вычисляй."
            )
        else:
            line += " Дальше строк нет."
        lines.append(line)
    return "\n".join(lines)

@dataclass(slots=True)
class CitationCheck:
    fragment: int
    # `quote` — текст, ВЫРЕЗАННЫЙ НАМИ из фрагмента. Именно он уходит на
    # экран, поэтому он дословный по построению.
    quote: str
    ok: bool
    reason: str = ""
    # `handle` — то, что указала модель. Хранится для разбора: когда опора не
    # нашлась, надо видеть, что именно модель пыталась показать.
    handle: str = ""


@dataclass(slots=True)
class AnswerEnvelope:
    """То, что уходит на фронт как итог. Всё, что интерфейсу нужно знать."""

    status: AnswerStatus
    answer: str
    citations: list[CitationCheck] = field(default_factory=list)
    clarifying_question: str = ""
    schema_valid: bool = True
    schema_error: str = ""
    # Сколько ссылок снято с ОТКАЗА. Не ноль — значит модель сказала «сведений
    # нет» и тут же сослалась на фрагмент. Поле нужно затем, что снятое с
    # экрана не должно исчезнуть из измерений: дефект лечится промптом, и,
    # перестав его считать, мы перестанем видеть, помог ли промпт.
    citations_dropped: int = 0
    # Идентификаторы, названные в ответе, но отсутствующие в источниках.
    #
    # Самый дешёвый детектор выдумки из всех, что у нас есть, и он ловит
    # ровно тот класс вранья, который проверка цитат поймать не может.
    unknown_refs: list[str] = field(default_factory=list)
    # Идентификаторы, у которых числа в ответе разошлись с источником.
    #
    # Отдельно от `unknown_refs`, потому что это другая беда и другой
    # разговор с человеком: там «такой трубы нет», здесь «труба есть, а
    # цифра не та». Вторая тише и опаснее.
    mismatched_refs: list[str] = field(default_factory=list)

    @property
    def citations_failed(self) -> int:
        return sum(1 for citation in self.citations if not citation.ok)

    @property
    def citations_repaired(self) -> int:
        """Сколько ссылок прошло ПОСЛЕ починки сервером.

        Число обязано быть на виду. Мы починили три вида указаний: оборванное
        слово, склейку двух настоящих мест и перепутанный номер фрагмента. Все
        три — дефекты МОДЕЛИ, и лечатся они промптом. Если считать их просто
        успехом, счётчик дефекта исчезнет, а дефект останется: мы будем
        уверены, что модель указывает места хорошо, потому что сами за ней
        подчищаем.
        """
        return sum(1 for citation in self.citations if citation.ok and citation.reason)

    def to_dict(self) -> dict:
        return {
            "status": self.status.value,
            "answer": self.answer,
            "clarifying_question": self.clarifying_question,
            "schema_valid": self.schema_valid,
            "schema_error": self.schema_error,
            "citations": [
                {
                    "fragment": citation.fragment,
                    "quote": citation.quote,
                    "ok": citation.ok,
                    "reason": citation.reason,
                    "handle": citation.handle,
                }
                for citation in self.citations
            ],
            "citations_failed": self.citations_failed,
            "citations_dropped": self.citations_dropped,
            "citations_repaired": self.citations_repaired,
            "unknown_refs": self.unknown_refs,
            "mismatched_refs": self.mismatched_refs,
        }


def _fold(char: str) -> str:
    """Приводит один символ к виду для сравнения. Пустая строка — выбросить.

    Здесь собрано ВСЁ приведение: регистр, «ё», артефакты вёрстки. Функция
    одна, потому что нормализатора должно быть ровно столько же.

    До этой правки их было два: один приводил строку целиком (для поиска),
    второй — посимвольно с картой позиций (для вырезания). Я добавил
    обработку обратных кавычек только в первый, и честная опора «Роль
    data-admin выдаётся» перестала находиться в тексте «Роль `data-admin`
    выдаётся»: игла нормализована, стог нет. Две функции, обязанные давать
    одинаковый результат, обязаны быть одной функцией.
    """
    if char in _DROP_CHARS:
        return ""
    return char.lower().replace("ё", "е")[:1] or char


def _normalize_with_map(text: str) -> tuple[str, list[int]]:
    """Приведение с картой позиций обратно в исходный текст.

    Зачем карта. Найти опору надо в приведённом тексте (иначе перенос строки
    посреди фразы всё ломает), а вырезать цитату — из ИСХОДНОГО, потому что
    именно он попадёт человеку на экран. Без карты позиций одно с другим не
    связать: приведение меняет длину строки.

    Выброшенные символы в карту просто не попадают, и позиции остаются
    согласованными: список ведётся только по оставленным символам.

    ГЛАВНОЕ ПРАВИЛО ЗДЕСЬ: содержание — это буквы и цифры. Всё остальное —
    пробелы, переносы, кавычки, тире, двоеточия, вертикальные черты разметки
    таблиц — вёрстка, и при сопоставлении сводится к одному пробелу.

    Правило появилось не из любви к порядку, а из прогона. Модель читает
    строку markdown-таблицы
        | S1 | Боевой контур недоступен, либо данные недостоверны |
    и указывает место так: «S1: Боевой контур недоступен, либо данные
    недостоверны» — заменив разделитель ячеек двоеточием, то есть прочитав
    таблицу так, как читает её человек. Указание верное, место единственное,
    а посимвольное сравнение его не находило: оно сравнивало вертикальную
    черту с двоеточием.

    Аналогия: +7 (343) 123-45-67 и 73431234567 — это один телефон, и записная
    книжка, которая их различает, не защищает от ошибки, а сама ею является.
    Скобки и дефисы в номере — оформление.
    """
    characters: list[str] = []
    positions: list[int] = []
    previous_space = True

    for index, char in enumerate(text):
        if char in _DROP_CHARS:
            continue

        if not char.isalnum():
            # Пробел, перенос, знак препинания, черта таблицы — одно и то же:
            # разделитель. Подряд идущие сводятся к одному.
            if previous_space:
                continue
            characters.append(" ")
            positions.append(index)
            previous_space = True
            continue

        folded = _fold(char)
        if not folded:
            continue
        characters.append(folded)
        positions.append(index)
        previous_space = False

    while characters and characters[-1] == " ":
        characters.pop()
        positions.pop()

    return "".join(characters), positions


def _normalize_for_match(text: str) -> str:
    """То же приведение без карты. Реализовано ЧЕРЕЗ то же самое, не рядом."""
    return _normalize_with_map(text)[0]


# Граница цитаты: конец предложения, конец строки таблицы или перенос.
_SPAN_END = re.compile(r"[.!?;]\s|\n|\s\|")

# Сколько букв и цифр должно быть в цитате, чтобы её имело смысл показывать.
# Двенадцать — это примерно два коротких слова: «S1 | Боевой» уже что-то
# говорит, «S1» не говорит ничего.
MIN_QUOTE_CONTENT = 12


def _match_positions(normalized: str, needle: str) -> list[int]:
    """Все вхождения опоры, НАЧИНАЮЩИЕСЯ с начала слова. Одно место — один ответ.

    Функция одна на все три применения — подсчёт, вырезание одного места,
    вырезание всех, — по той же причине, по которой нормализатор сведён в
    один: три копии «найти вхождения», обязанные совпадать, расходятся при
    первой же правке. Один раз я на этом уже попался.

    Про начало слова. Поиск по подстроке ловит опору внутри другого слова, и
    это ломает как раз короткие, но точные указания. В тексте «шаги S10 и S1»
    опора `S1` встречается формально дважды — второй раз внутри `S10`, — и
    честное однозначное указание получало отказ «встречается несколько раз».
    Совпадение считается только там, где опора начинается со слова: либо в
    начале фрагмента, либо после символа, который словом не является.

    Конец опоры не проверяем сознательно: опора `Код E-1042` заканчивается
    ровно на границе, а `срок` законно указывает на слово «сроки» — это не
    другое место, а то же самое.
    """
    if not needle:
        return []
    first = needle[0]
    check_boundary = first.isalnum()
    positions: list[int] = []
    position = normalized.find(needle)
    while position >= 0:
        if (
            not check_boundary
            or position == 0
            or not normalized[position - 1].isalnum()
        ):
            positions.append(position)
        position = normalized.find(needle, position + 1)
    return positions


def handle_occurrences(body: str, handle: str) -> int:
    """Сколько раз указанное место встречается во фрагменте.

    Отдельная функция, чтобы причина отказа была честной: «опоры нет» и «опора
    встречается дважды» — разные неисправности. Первая говорит о модели,
    вторая о том, что она указала слишком коротко, и лечатся они по-разному.
    """
    return len(_match_positions(_normalize_with_map(body)[0], _normalize_for_match(handle)))


def extract_span(body: str, handle: str, *, max_chars: int = 320) -> str | None:
    """Вырезает из фрагмента настоящий текст, начиная с указанного места.

    Это и есть суть приёма. Модель не переписывает цитату — она показывает, ГДЕ
    смотреть: номер фрагмента и первые несколько слов. Текст мы достаём из
    документа сами, и потому он дословный по построению: испортить его нечем.

    Так уходит целый класс брака. У нас 15 цитат из 77 ответов не проходили
    дословную проверку — модель «поправляла» пунктуацию, склеивала два места,
    меняла падеж. Все эти ошибки существовали только потому, что мы просили
    воспроизвести текст, который у нас уже лежит в базе.
    """
    needle = _normalize_for_match(handle)
    if not needle:
        return None

    normalized, positions = _normalize_with_map(body)
    found = _match_positions(normalized, needle)
    if not found:
        return None

    # НЕОДНОЗНАЧНАЯ опора — это отказ, а не повод угадывать.
    #
    # Раньше брали первое вхождение. На таблице вида
    #   | Порог усталости | 0.62 | предупреждение |
    #   | Порог усталости | 0.81 | авария |
    # модель указывала на вторую строку, а мы выдавали первую — и выдавали её
    # как дословную цитату из документа, то есть с полным доверием. Это хуже
    # прежнего вранья модели: там текст был подозрительным, здесь он
    # безупречен и неверен.
    if len(found) > 1:
        # Неоднозначную опору разбирает resolve_citations: там видно, дают ли
        # вхождения одинаковый текст. Здесь просто отказываемся угадывать.
        return None

    return _cut_span(body, positions[found[0]], needle, max_chars=max_chars)


def _content_len(text: str) -> int:
    """Длина СОДЕРЖАНИЯ: только буквы и цифры, без знаков и разделителей.

    Нужна затем, что сравнивать цитату с опорой по обычной длине — значит
    считать содержанием знаки препинания. Цитата «5.» на два символа длиннее
    опоры «5» и ровно так же пуста; цитата «S1 |» длиннее «S1» на разделитель
    ячейки, которого в документе и не читают.
    """
    return sum(1 for char in text if char.isalnum())


def _cut_span(body: str, start: int, needle: str, *, max_chars: int = 320) -> str:
    """Вырезает текст от указанной позиции до ближайшей границы смысла.

    Режем по ПЕРВОЙ границе после опоры, а не по последней в окне. Последняя
    давала цитату на несколько предложений и склеивала соседние строки таблицы
    в один абзац — человек читал два разных значения как одно утверждение.

    Но «первая граница» в чистом виде тоже даёт брак, и я увидел его только на
    настоящих данных. Опора `S1` в строке таблицы
        | S1 | Боевой контур недоступен | немедленно |
    стоит прямо перед разделителем ячеек, и первая же граница — сразу за
    опорой. Цитата получалась «S1». То же с опорой `5` в нумерованном списке:
    цитата «5.». Формально всё верно: текст дословный, место найдено. А
    человеку показано НИЧЕГО — и показано с зелёной отметкой «подтверждено».

    Поэтому границу проходим дальше, пока цитата не наберёт хоть какого-то
    содержания. Порог здесь АБСОЛЮТНЫЙ, и это важно: первая версия правила
    требовала, чтобы цитата была содержательнее ОПОРЫ, и растягивала цитату
    там, где растягивать нечего. Модель указала на целое предложение — значит
    цитата законно равна этому предложению, и приклеивать к ней следующее
    незачем. Пусто не «когда цитата равна опоре», а «когда в цитате почти
    ничего нет».

    И жёсткая граница: перенос строки не пересекаем никогда. Иначе на таблице,
    где в строке после опоры не осталось содержания, цитата перескочила бы в
    СОСЕДНЮЮ строку — и человек прочитал бы два разных значения как одно
    утверждение. Ровно та ошибка, из-за которой мы вообще перестали резать по
    последней границе в окне.
    """
    window = body[start : start + max_chars]

    position = len(needle)
    while True:
        match = _SPAN_END.search(window, position)
        if match is None:
            if len(body) > start + max_chars:
                cut = window.rfind(" ")
                if cut > len(needle):
                    window = window[:cut] + "…"
            break
        candidate = window[: match.start() + 1]
        crosses_line = "\n" in match.group()
        if (
            crosses_line
            or _content_len(candidate) >= MIN_QUOTE_CONTENT
            or match.end() >= len(window)
        ):
            window = candidate
            break
        # За этой границей ничего, кроме опоры, не оказалось — ищем следующую.
        position = match.end()

    return " ".join(window.split()).strip(" |")


def _handle_in_header(handle: str, fragment: Fragment) -> bool:
    header = " ".join(
        [
            str(fragment.number), fragment.doc_id, fragment.doc_title,
            fragment.heading_path, fragment.doc_version, fragment.doc_updated,
        ]
    )
    return _normalize_for_match(handle) in _normalize_for_match(header)


def _span_adds_text(span: str, handle: str) -> bool:
    """Несёт ли вырезанная цитата что-нибудь СВЕРХ самой опоры.

    Нужна ровно затем, что послабление для повтора формулировки оказалось
    дырой. Проверка «все вхождения дают один и тот же текст» задумывалась про
    честный повтор в документе, но она срабатывала и там, где вхождения
    отличаются как раз тем, что мы обрезали. Таблица
        | Степень | 0.62 | предупреждение |
        | Степень | 0.81 | авария |
    на опоре «Степень» даёт два раза одну и ту же цитату «Степень» — потому
    что граница цитаты стоит сразу за словом, — и мы выдавали её как
    подтверждённую. То есть подтверждали пустое указание: где именно смотреть,
    из цитаты «Степень» человек не узнаёт, а бейдж говорит ему, что ссылка
    проверена. Это та же ловушка, что и с угадыванием первого вхождения:
    безупречный с виду текст, за которым нет никакого факта.

    Условие простое: цитата обязана быть длиннее опоры. Совпадение «один в
    один» значит, что вся информативность указания — в самом указании, а его
    мы и не смогли разрешить однозначно.
    """
    return _content_len(_normalize_for_match(span)) > _content_len(_normalize_for_match(handle))


def extract_all_spans(body: str, handle: str) -> list[str]:
    """Все варианты цитаты для неоднозначной опоры.

    Нужна, чтобы отличить безобидный повтор формулировки от настоящей
    неоднозначности: если все вхождения дают один и тот же текст, выбирать
    не из чего.
    """
    needle = _normalize_for_match(handle)
    if not needle:
        return []
    normalized, positions = _normalize_with_map(body)
    spans: list[str] = []
    for position in _match_positions(normalized, needle):
        piece = _cut_span(body, positions[position], needle)
        if piece:
            spans.append(piece)
    return spans


def _pick_by_line_start(body: str, handle: str) -> str:
    """Из нескольких вхождений опоры выбирает то, что НАЧИНАЕТ строку.

    Замером показано, что это главный оставшийся вид неудачной ссылки: из
    восьми шесть — опора в одно слово, «E-2210», «SVY-409», «Степень»,
    «Команда». Все они живут в таблицах кодов и регламентов, где одно и то
    же слово стоит и в строке таблицы, и в тексте рядом.

    Различает их положение, а не длина. Код в начале строки — это ОПРЕДЕЛЕНИЕ
    кода: «E-2210 | Некорректный диапазон шагов». Тот же код посреди
    предложения — ссылка на него: «повторять E-2210 бессмысленно». Человек,
    проверяющий цитату, хочет попасть в первое.

    Выбираем, только когда таких вхождений ОДНО. Два начала строки означают,
    что различить их положением нельзя, и тогда работает следующий признак —
    совпадение со словами ответа.
    """
    needle = _normalize_for_match(handle)
    if not needle:
        return ""

    # В ОДНОСТРОЧНОМ ФРАГМЕНТЕ ПРАВИЛО НЕ РАБОТАЕТ, и это не оговорка.
    #
    # «Начинает строку» — признак СТРУКТУРЫ: строки таблицы, пункта списка.
    # Там, где строка одна, начало строки означает лишь «стоит первым в
    # абзаце», и выбор по нему — подбрасывание монеты с видом обоснования.
    # На фрагменте «Кэш на чтении и кэш на записи настраиваются раздельно»
    # правило уверенно выбрало бы первое «кэш» — притом что различить их
    # нечем, и честный ответ здесь «неизвестно, о каком месте речь».
    if "\n" not in body:
        return ""

    normalized, positions = _normalize_with_map(body)

    starting: list[str] = []
    for position in _match_positions(normalized, needle):
        original = positions[position]
        before = body[:original].rstrip(" \t|")
        if before and not before.endswith("\n"):
            continue
        piece = _cut_span(body, original, needle)
        if piece:
            starting.append(piece)

    return starting[0] if len(starting) == 1 else ""


def _resolve_by_prefix(
    body: str, handle: str, *, min_chars: int = 10
) -> tuple[str, str] | None:
    """Спасает ОБОРВАННУЮ опору: ищет самое длинное её начало, что есть в тексте.

    Настоящий случай из прогона. Вопрос про срок роли data-admin — критичный,
    поимённо проверяемый. Модель ответила верно и указала место как
    «Роль data-admin выдав». Слово оборвано посреди себя: в документе стоит
    «Роль `data-admin` выдаётся». Ссылка не нашлась, и в отчёте это выглядело
    как промах модели, хотя указание было правильным на двадцать символов из
    двадцати одного.

    Аналогия. Человек говорит: «страница 14, абзац начинается словами „Роль
    data-admin выдав…“» — и запинается на последнем слове. Библиотекарь,
    который на этом основании отказывается принести страницу, формально прав
    и практически бесполезен: сказанного уже достаточно, чтобы найти место
    ровно одно.

    Почему это не угадывание. Мы НЕ достраиваем опору до того, что, по нашему
    мнению, модель имела в виду, — мы только УКОРАЧИВАЕМ её до той части,
    которая в документе есть дословно. И оставляем главное условие: укороченная
    часть обязана встречаться во фрагменте один раз. Если после обрезки место
    перестало быть единственным, мы отказываемся, как и раньше.

    Предел снизу существует затем, что обрезать можно до бессмыслицы: начало
    «Рол» найдётся в половине документа. Десять символов — та граница, за
    которой указание перестаёт указывать.

    И второе условие, без которого вся затея опасна. Прощаем только ОБРЫВ
    СЛОВА: отброшенный хвост обязан быть остатком одного слова, без пробелов
    внутри. Разницу видно на двух примерах:

      «Роль data-admin выдав»                  → отброшено «в»
      «Отключение кэша разрешено дежурному»    → отброшено «азрешено дежурному»

    Первое — запнувшийся человек, и место он указал. Второе — выдумка: начало
    «Отключение кэша» в документе есть, а дальше модель сочинила утверждение,
    прямо противоположное написанному («в продакшене запрещено»). Без этого
    условия починка выдавала бы такой выдумке подтверждённую цитату — и
    цитата была бы дословной, настоящей и опровергающей тот самый ответ,
    рядом с которым стоит. Это худшее, что может сделать проверка: заверить
    ложь документом.

    Правило простое: мы прощаем НЕДОПИСАННОЕ слово и никогда не прощаем
    ДРУГИЕ слова.

    Возвращает вырезанную цитату и то начало опоры, по которому она нашлась, —
    второе нужно, чтобы в отчёте было видно, ЧТО именно мы укоротили.
    """
    needle = _normalize_for_match(handle)
    if len(needle) <= min_chars:
        return None

    normalized, positions = _normalize_with_map(body)

    # Начала длиннее — точнее, поэтому идём от самого длинного. Свойство
    # монотонности здесь работает на нас: если начало длины n во фрагменте
    # есть, то и все более короткие есть, а значит первое же найденное сверху
    # и есть самое точное.
    for length in range(len(needle) - 1, min_chars - 1, -1):
        found = _match_positions(normalized, needle[:length])
        if not found:
            continue
        if len(found) > 1:
            # Самое точное из возможных начал уже неоднозначно — дальше
            # укорачивать бессмысленно, вхождений станет только больше.
            return None
        tail = needle[length:].strip()
        if len(tail.split()) > 1 or needle[length] == " ":
            # Отброшено больше, чем остаток одного слова. Здесь развилка, и
            # различие между её ветками — это различие между починкой и
            # выдумкой.
            #
            # Если отброшенный хвост в этом же фрагменте ЕСТЬ — модель склеила
            # два настоящих места документа в одну опору. Так она и делает на
            # таблицах и на соседних предложениях: берёт заголовок столбца и
            # значение из строки, или первую половину одного предложения и
            # вторую половину другого. Весь текст подлинный, неверна только
            # склейка. Тогда цитату честно взять по ПЕРВОМУ месту — тому, на
            # которое опора и указывает своим началом.
            #
            # Если хвоста в фрагменте НЕТ — это выдумка: «Отключение кэша
            # разрешено дежурному» при написанном «в продакшене запрещено».
            # Тут починка выдала бы подтверждённую цитату, опровергающую тот
            # самый ответ, рядом с которым стоит.
            #
            # Аналогия: человек по памяти сшил цитату из двух абзацев — оба в
            # книге есть, и по первому его вполне можно найти. А человек,
            # дописавший к настоящему началу свой вывод, цитирует не книгу.
            if not tail or tail not in normalized:
                return None
            glued = True
        else:
            glued = False
        start = positions[found[0]]
        end = positions[found[0] + length - 1] + 1
        span = _cut_span(body, start, needle[:length])

        if glued and not span.rstrip().endswith((".", "!", "?", ";")):
            # СКЛЕЙКУ ПРИНИМАЕМ ТОЛЬКО ПО ЦЕЛОМУ ПРЕДЛОЖЕНИЮ.
            #
            # Без этого условия моя же починка выдала брак на первой проверке.
            # Опора «Порог внимания / 1 % / 5 %» склеена из заголовка столбца и
            # значений строки. Начало «Порог внимания» в тексте есть, хвост
            # тоже есть — условие склейки выполнено, — и цитатой становилась
            # СТРОКА ЗАГОЛОВКОВ: «Порог внимания | Порог аварии». Ни одного
            # числа, ради которых ссылка и приложена, в ней нет. Подтверждение
            # без факта — это хуже отказа: отказ виден, а пустое подтверждение
            # выглядит как доказательство.
            #
            # Целое предложение — признак того, что первая часть склейки
            # самодостаточна: по ней можно прочитать утверждение. Обрывок
            # ячейки таблицы этому условию не удовлетворяет, и правильно.
            return None

        return span, body[start:end]
    return None


def _words_scattered(body: str, handle: str) -> bool:
    """Все слова опоры во фрагменте есть, но не подряд.

    Это отдельный, хорошо узнаваемый способ ошибиться, и сопоставлением он не
    лечится. Модель читает таблицу
        | Метрика     | Порог внимания | Порог аварии |
        | доля срезов | 1 %            | 5 %          |
    и указывает место как «Порог внимания / 1 % / 5 %» — склеивает ЗАГОЛОВОК
    столбца со значениями из другой строки. Такого куска текста в документе не
    существует: модель собрала его сама, притом правильно поняв таблицу.

    Вырезать по такому указанию нечего. Но и называть это «опоры нет» — врать
    о причине: слова-то все на месте. Отдельное имя нужно затем, что лечится
    это промптом («не склеивай ячейки»), а не проверкой.
    """
    # Порог в два символа, а не в три: «3D» — полноценное слово в строке
    # таблицы, и отбросив его, мы теряем ровно тот случай, ради которого
    # функция написана («Слой / 3D» — заголовок столбца плюс ячейка).
    words = [word for word in _normalize_for_match(handle).split() if len(word) >= 2]
    if len(words) < 2:
        return False
    present = set(_normalize_for_match(body).split())
    return all(word in present for word in words)


# Подпись, которую модель ставит перед опорой вместо того, чтобы просто её
# дать: «Точная неизмененная цитата (от 5 до 10 слов): …», «Цитата: …».
_HANDLE_LABEL = re.compile(
    r"^[^:]{0,80}?(?:цитат\w*|quote|опор\w*|фрагмент\w*)[^:]{0,40}:\s*",
    re.IGNORECASE,
)


def _clean_handle(handle: str) -> str:
    """Снимает с опоры подпись, которую модель приписала от себя.

    В замере три неудачные ссылки из девяти выглядели так:
    «Точная неизмененная цитата (от 5 до 10 слов): Обычный релиз…». Опора
    настоящая, текст в документе есть — но искали мы его вместе с подписью,
    и, разумеется, не находили.

    Чинится это в двух местах сразу: в схеме у поля появилось описание
    (поле без подписи модель подписывает себе сама), а здесь — уборка за
    теми моделями, которые всё равно подпишут. Второе без первого лечило бы
    следствие, первое без второго — оставляло бы нас без страховки.
    """
    handle = handle.strip()
    cleaned = _HANDLE_LABEL.sub("", handle, count=1).strip()
    # Пустой результат означает, что подписью была вся строка: опоры в ней
    # нет вовсе, и лучше честно не найти, чем искать по остатку.
    return cleaned or handle


def _pick_by_claim(spans: list[str], claim: str) -> str:
    """Из нескольких вхождений опоры выбирает то, о котором написан ответ.

    Короткая опора вроде «E-1042» встречается в документе трижды: в списке
    кодов, в таблице причин и в примере запроса. Все три — «то самое место»
    с точки зрения поиска и разные с точки зрения смысла, поэтому проверка
    честно отвечала «какое имелось в виду, неизвестно» и снимала ссылку.

    Но неизвестно это было только проверке. Модель уже сказала, ЧТО она
    утверждает, — и вхождение, из которого это утверждение взято, отличается
    от остальных тем, что его слова стоят в ответе. Совпадение считаем по
    словам длиннее трёх букв: короткие («в», «для», «не») есть везде и только
    зашумляют счёт.

    Выбираем, лишь когда победитель ОДИН. Ничья означает, что вхождения
    действительно неразличимы, и тогда прежний отказ остаётся верным: лучше
    снять ссылку, чем показать человеку цитату, выбранную подбрасыванием
    монеты.
    """
    if not claim.strip():
        return ""

    claim_words = {word for word in re.findall(r"\w+", claim.lower()) if len(word) > 3}
    if not claim_words:
        return ""

    scores = [
        len({word for word in re.findall(r"\w+", span.lower()) if len(word) > 3} & claim_words)
        for span in spans
    ]
    best = max(scores)
    if best == 0 or scores.count(best) > 1:
        return ""
    return spans[scores.index(best)]


def resolve_citations(
    citations: list[dict],
    fragments: list[Fragment],
    *,
    min_handle_chars: int = 1,
    claim: str = "",
) -> list[CitationCheck]:
    """Находит указанное моделью место в фрагменте и вырезает цитату сама.

    Модель присылает номер фрагмента и `starts_with` — первые несколько слов
    того места, откуда взято утверждение. Мы ищем эти слова в фрагменте и
    достаём оттуда настоящий текст.

    Проверка осталась той же по духу и стала честнее по форме: опора либо есть
    во фрагменте, либо нет. Ошибка «сослался на [2], а взял из [3]» ловится
    по-прежнему и отмечается отдельно — лечится она иначе.

    Раньше мы просили модель воспроизвести цитату дословно и проверяли
    воспроизведение. Это требование не к достоверности, а к памяти: модель
    правила пунктуацию, склеивала два места, меняла падеж — и честный ответ
    получал отметку о вранье. Просить показать границы дешевле и надёжнее.
    """
    by_number = {fragment.number: fragment for fragment in fragments}
    checks: list[CitationCheck] = []

    for raw in citations:
        if not isinstance(raw, dict):
            # Проверка `isinstance(citations_raw, list)` касалась только
            # контейнера, и строка внутри массива роняла разбор целиком:
            # пользователь, уже прочитавший весь ответ в потоке, получал
            # сверху «внутренняя ошибка сервера», а событий answer и done не
            # приходило вовсе. Гарантия провайдера — это его гарантия, и
            # проверять надо каждый уровень, а не первый.
            checks.append(CitationCheck(0, "", False, "ссылка не в виде объекта", str(raw)[:80]))
            continue
        handle = _clean_handle(str(raw.get("starts_with") or raw.get("quote") or ""))
        try:
            number = int(raw.get("fragment"))
        except (TypeError, ValueError):
            checks.append(CitationCheck(0, "", False, "не указан номер фрагмента", handle))
            continue

        fragment = by_number.get(number)
        if fragment is None:
            checks.append(
                CitationCheck(number, "", False, f"фрагмента [{number}] не было в контексте", handle)
            )
            continue
        # Здесь остался порог только на ПУСТУЮ опору.
        #
        # Сначала было 12 символов, потом 3 — и трёх хватило, чтобы отбросить
        # `S1` в списке степеней инцидента и `5` в нумерованном списке, то
        # есть оба раза указание, которое ни с чем не спутать. Причина при
        # этом печаталась «опора пустая», хотя опора была, — отчёт врал о
        # собственном отказе, и это хуже самого отказа: по такому отчёту
        # чинишь не то.
        #
        # Любой порог длины здесь — это попытка мерить однозначность линейкой.
        # Однозначность мерится числом вхождений, и она уже измеряется ниже.
        if len(handle) < min_handle_chars:
            checks.append(CitationCheck(number, "", False, "опора пустая", handle))
            continue

        span = extract_span(fragment.body, handle)
        if span:
            checks.append(CitationCheck(number, span, True, "", handle))
            continue

        # Опора встречается несколько раз — но иногда это не мешает.
        #
        # Если все вхождения дают ОДИН И ТОТ ЖЕ вырезанный текст, выбирать
        # между ними не нужно: цитата получится одинаковая. Отказывать здесь
        # значило бы наказывать за повтор формулировки в документе.
        spans = extract_all_spans(fragment.body, handle)
        # Одинаковость вхождений считаем по ПРИВЕДЁННОМУ тексту, а не по
        # исходному. «Срок — не более 14 дней» и «срок — не более 14 дней» —
        # это одна и та же цитата, различающаяся регистром первой буквы;
        # сравнение как есть объявляло такой повтор неоднозначностью. Ровно та
        # же ошибка, что и с нормализацией опоры: сравнивать надо то, что мы
        # считаем равным, а не то, как это напечатано.
        same_text = len({_normalize_for_match(span) for span in spans}) == 1
        if len(spans) > 1 and same_text and _span_adds_text(spans[0], handle):
            checks.append(CitationCheck(number, spans[0], True, "", handle))
            continue
        if len(spans) > 1:
            # Сначала положение, потом смысл. Порядок не случаен: положение
            # — свойство документа и не зависит от того, что написала
            # модель, а совпадение со словами ответа зависит. Признак, не
            # зависящий от проверяемого, надёжнее.
            chosen = _pick_by_line_start(fragment.body, handle) or _pick_by_claim(
                spans, claim
            )
            if chosen:
                checks.append(
                    CitationCheck(
                        number, chosen, True,
                        "опора встречается несколько раз; выбрано место, "
                        "где она начинает строку или совпадает с текстом ответа",
                        handle,
                    )
                )
                continue
            checks.append(
                CitationCheck(
                    number, "", False,
                    "опора встречается во фрагменте несколько раз и в разных местах — "
                    "какое имелось в виду, неизвестно",
                    handle,
                )
            )
            continue

        # Опора не нашлась целиком — возможно, она просто оборвана.
        if not spans:
            repaired = _resolve_by_prefix(fragment.body, handle)
            if repaired is not None:
                span, used = repaired
                checks.append(
                    CitationCheck(
                        number, span, True,
                        f"опора укорочена до совпадающей части: «{used}»",
                        handle,
                    )
                )
                continue

        # Опора взята из ШАПКИ фрагмента, а не из текста.
        #
        # Шапку мы печатаем сами: номер, документ, раздел, редакция. Ссылаться
        # на неё бессмысленно — это наша разметка, а не содержание документа.
        # Отдельная причина нужна затем, что лечится это промптом, а не
        # проверкой, и без имени дефект выглядел как «модель промахнулась».
        if _handle_in_header(handle, fragment):
            checks.append(
                CitationCheck(
                    number, "", False,
                    "опора указана по шапке фрагмента, а не по его тексту",
                    handle,
                )
            )
            continue

        # Не нашлось здесь — смотрим, нет ли этого места в ДРУГОМ фрагменте.
        elsewhere = next(
            (
                other.number
                for other in fragments
                if other.number != number and extract_span(other.body, handle)
            ),
            None,
        )
        if elsewhere:
            # НОМЕР ПЕРЕПУТАН, А ОПОРА НАСТОЯЩАЯ — это починка, а не отказ.
            #
            # Модель указала на [1], а текст лежит дословно в [3]. Раньше мы
            # такую ссылку выбрасывали, и это была потеря на ровном месте:
            # весь смысл приёма «показывай место, а не переписывай текст» в
            # том, что МЫ проверяем, где текст лежит. Мы это проверили и знаем
            # ответ — значит можем исправить номер сами.
            #
            # Выдумкой это стать не может по построению: цитата вырезается из
            # того фрагмента, где текст действительно есть, и он был в
            # контексте модели. Мы не додумываем, а переставляем указатель на
            # найденное место.
            #
            # Аналогия: сослались на страницу 40, текст оказался на 42-й.
            # Библиотекарь, который на этом основании отказывается выдать
            # книгу, формально прав и бесполезен.
            #
            # Причина сохраняется в тексте ссылки: дефект остаётся виден, но
            # человек получает подтверждение вместо «не подтверждена».
            other = by_number[elsewhere]
            span = extract_span(other.body, handle) or (
                extract_all_spans(other.body, handle) or [""]
            )[0]
            if span:
                checks.append(
                    CitationCheck(
                        elsewhere, span, True,
                        f"номер исправлен: модель указала [{number}], "
                        f"текст лежит в [{elsewhere}]",
                        handle,
                    )
                )
                continue
            reason = f"опоры нет в [{number}], но есть в [{elsewhere}]"
        elif _words_scattered(fragment.body, handle):
            reason = "опора склеена из разных мест фрагмента: слова есть, но не подряд"
        else:
            reason = "опоры нет в указанном фрагменте"
        checks.append(CitationCheck(number, "", False, reason, handle))

    return checks



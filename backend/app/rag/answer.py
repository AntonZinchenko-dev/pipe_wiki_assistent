"""Структурированный ответ: потоковый разбор схемы и проверка цитат.

Здесь решается противоречие, которое обычно решают неправильно.

Ответ модели должен быть СТРУКТУРОЙ (статус, текст, цитаты с номерами
фрагментов), а не свободным текстом: иначе интерфейсу приходится угадывать
эвристиками, отказ это или ответ, и всё рассыпается при первой смене
формулировки. Но структура — это JSON, а стримить пользователю сырой JSON
нельзя: он увидит `{"status": "answered", "answer": "Кэш ...`.

Обычно из этого выходят двумя плохими путями: либо отказываются от схемы и
парсят текст регулярками, либо делают два вызова модели (сначала структуру,
потом текст) и платят дважды.

Правильный путь — один вызов со схемой плюс инкрементальный разбор потока на
сервере: мы вытаскиваем из растущего JSON только поле `answer` и отдаём
наружу уже чистый текст, а полную структуру валидируем, когда поток закончился.
Заодно это ровно тот случай из раздела 5, где границы сетевых кусков не
совпадают с границами данных: escape-последовательность `\\u0410` спокойно
приезжает разрезанной пополам, и разбор «по куску за раз» на этом ломается.

И вторая половина файла — дословная проверка цитат. Самый дешёвый детектор
вранья из существующих: не нужен ни судья-модель, ни дополнительные вызовы
(раздел 4).
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass, field
from enum import Enum

from .context import Fragment

_KEY_PATTERN = re.compile(r'"answer"\s*:\s*"')
_WS = re.compile(r"\s+")

# Артефакты вёрстки, которые расходятся между документом и его пересказом.
#
# Обратные кавычки вокруг `data-admin`, разные виды тире и кавычек — это
# оформление, а не слова. Модель, указывающая на место в тексте, пишет «Роль
# data-admin выдаётся», а в тексте стоит «Роль `data-admin` выдаётся» — и
# честная опора не находилась. Слова при этом не подменяются, поэтому
# подмену слова проверка по-прежнему видит.
# Символы, которые исчезают совсем: они стоят ВНУТРИ слова. Мягкий перенос и
# обратная кавычка вокруг `data-admin` — оформление, и превратить их в пробел
# нельзя, иначе слово разорвётся на два.
#
# Все остальные знаки — кавычки, тире, двоеточия, вертикальные черты таблиц —
# отдельной таблицей больше не перечисляются: они стали РАЗДЕЛИТЕЛЯМИ в
# `_normalize_with_map`. Перечислять их по одному значило играть в догонялки
# с типографикой: каждый новый знак в документе означал бы новую строку в
# словаре и новый непойманный случай до неё.
_DROP_CHARS = frozenset("`\u00ad")
_ESCAPES = {'"': '"', "\\": "\\", "/": "/", "b": "\b", "f": "\f", "n": "\n", "r": "\r", "t": "\t"}


class AnswerStatus(str, Enum):
    ANSWERED = "answered"
    NOT_FOUND = "not_found"
    NEED_CLARIFICATION = "need_clarification"
    # Служебные статусы: их модель выдать не может, их выставляет сервер.
    ERROR = "error"
    NO_CONTEXT = "no_context"  # поиск не дал ничего выше порога


# Статусы, которые модель вправе выставить сама. Остальные — служебные.
MODEL_STATUSES = (
    AnswerStatus.ANSWERED,
    AnswerStatus.NOT_FOUND,
    AnswerStatus.NEED_CLARIFICATION,
)


class StreamingAnswerParser:
    """Достаёт поле `answer` из потока JSON по мере поступления.

    Никакой готовой библиотеки здесь не нужно: нам не требуется разбирать JSON
    целиком на каждом куске (это O(n²) и бессмысленно), нужно только одно
    строковое поле. Состояний три: ищем ключ, читаем строку, закончили.
    """

    __slots__ = ("_raw", "_pos", "_inside", "_done", "_pending")

    def __init__(self) -> None:
        self._raw: str = ""
        self._pos: int = 0        # позиция разбора внутри _raw
        self._inside: bool = False
        self._done: bool = False
        self._pending: str = ""   # незавершённая escape-последовательность

    @property
    def raw(self) -> str:
        return self._raw

    @property
    def finished(self) -> bool:
        return self._done

    def feed(self, chunk: str) -> str:
        """Добавляет кусок потока, возвращает уже раскодированный прирост текста."""
        self._raw += chunk
        if self._done:
            return ""

        if not self._inside:
            match = _KEY_PATTERN.search(self._raw, self._pos)
            if match is None:
                # Ключ ещё не приехал целиком. Отступаем назад на длину
                # возможного «хвоста» ключа, чтобы не пропустить его, если он
                # разрезан между кусками.
                self._pos = max(self._pos, len(self._raw) - 16)
                return ""
            self._inside = True
            self._pos = match.end()

        out: list[str] = []
        i = self._pos
        raw = self._raw

        while i < len(raw):
            char = raw[i]

            if self._pending:
                # Досбираем escape-последовательность, начатую в прошлом куске.
                self._pending += char
                i += 1
                decoded, consumed = _try_unescape(self._pending)
                if decoded is None and consumed == 0:
                    if len(self._pending) > 6:  # мусор, не escape
                        out.append(self._pending)
                        self._pending = ""
                    continue
                out.append(decoded or "")
                self._pending = ""
                continue

            if char == "\\":
                self._pending = "\\"
                i += 1
                continue

            if char == '"':
                # Некавычкованная кавычка = конец строки поля.
                self._done = True
                self._inside = False
                i += 1
                break

            out.append(char)
            i += 1

        self._pos = i
        return "".join(out)


def _try_unescape(pending: str) -> tuple[str | None, int]:
    """Пробует раскодировать escape. Возвращает (текст, сколько символов взято).

    (None, 0) означает «данных пока мало, ждём следующий символ» — именно этот
    случай и ломает наивный разбор чанк-за-чанком.
    """
    if len(pending) < 2:
        return None, 0
    code = pending[1]
    if code in _ESCAPES:
        return _ESCAPES[code], 2
    if code == "u":
        if len(pending) < 6:
            return None, 0
        try:
            return chr(int(pending[2:6], 16)), 6
        except ValueError:
            return pending, len(pending)
    return pending, len(pending)



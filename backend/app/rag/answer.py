# Ссылка в тексте: [1], а также [1, 2] и [1; 2] одной скобкой.
#
# Модели регулярно объединяют несколько источников в одну скобку — это
# нормальная типографика сносок, и запретить её промптом до конца не
# выходит. Пока сюда попадал только одиночный номер, ответ со ссылкой
# «[1, 2]» считался ответом БЕЗ ссылок, и починка честно переписывала
# статус на «в документации нет ответа» — над текстом, который отвечал и
# ссылался. Проверка, которая врёт о собственном предмете, хуже
# отсутствующей: по её отчёту чинят не то место.
_TEXT_REF = re.compile(r"\[(\d{1,2}(?:\s*[,;]\s*\d{1,2})*)\]")

# Идентификатор предметной области: PP-0035, W-122, E-1042, РЛ-4.2.3.
#
# Шаблон нарочно общий, а не список известных префиксов. Список пришлось бы
# пополнять на каждый новый вид сущности, и до пополнения новый вид не
# проверялся бы вовсе — молча.
# Обозначение вида PP-0035, E-1042, РЛ-4.2.3, W-122.
#
# Хвост длинный НАРОЧНО. Было семь знаков, и выдуманное
# «WELL-00123456789» в живом прогоне проехало мимо: после седьмой цифры
# стояла восьмая, границы слова не получалось, совпадения не было.
# Детектор молчал ровно на том случае, ради которого он заведён, —
# правдоподобный идентификатор, которого нет нигде.
_IDENTIFIER = re.compile(r"\b[A-ZА-Я]{1,5}-\d[\d.]{0,14}\b")


def unknown_identifiers(answer: str, fragments: list[Fragment], question: str = "") -> list[str]:
    """Идентификаторы из ответа, которых нет ни в источниках, ни в вопросе.

    ЗАЧЕМ ЭТО НУЖНО, ЕСЛИ ЕСТЬ ПРОВЕРКА ЦИТАТ. Проверка цитат сверяет
    ЧЕТЫРЕ опоры — столько разрешает схема. Для ответа на один вопрос
    этого хватает с запасом. Для ответа СПИСКОМ не хватает вовсе: в
    «топ-10 изношенных труб» десять строк фактов, и шесть из них
    подтвердить нечем.

    Ровно там всё и сломалось. На живом прогоне модель выдала топ-10, в
    котором значились PP-0029 и PP-0024 с правдоподобными процентами.
    Таких труб в ответе сервиса не было: одну модель придумала, у другой
    переставила цифры в номере. Проверка цитат отметила одну опору из
    четырёх, остальные шесть строк прошли как есть — и на экране это
    выглядело как обычный точный ответ про состояние бурильного
    инструмента.

    Проверка здесь тупая и потому надёжная: идентификатор либо встречается
    в тексте фрагментов, либо его придумали. Ни модели, ни сети, ни
    настроек — сравнение строк.

    Вопрос тоже считается источником: человек вправе спросить «а что с
    PP-0007», и ответ «по PP-0007 данных нет» назовёт идентификатор,
    которого во фрагментах и правда нет. Это не выдумка, а эхо вопроса.
    """
    known = " ".join([*(fragment.body for fragment in fragments), question])
    present = set(_IDENTIFIER.findall(known)) | set(_PATH.findall(known))
    named = set(_IDENTIFIER.findall(answer or "")) | set(_PATH.findall(answer or ""))
    # Порядок устойчивый: список уходит в интерфейс и в журнал, и прыгающий
    # от запуска к запуску порядок мешает сравнивать прогоны.
    return sorted(named - present)


# Путь эндпоинта: /api/v1/pipes. Тоже идентификатор, только другой формы.
#
# Добавлен по живому промаху: на вопрос про топ-10 модель посоветовала
# «запросить данные через /api/v1/tubes и отсортировать по
# miner_damage_fraction». Такого эндпоинта нет — в контракте он называется
# /pipes. Совет выглядел компетентно и вёл в никуда, а выдуманным в нём
# было единственное слово.
_PATH = re.compile(r"/[a-z][a-z0-9_-]*(?:/[a-z0-9_{}-]+)+")


# Разделители разрядов, которые модель ставит, а сервис — нет.
_THOUSANDS = re.compile(r"(?<=\d)[\u00a0\u202f ,](?=\d{3}\b)")
_DECIMAL_COMMA = re.compile(r"(?<=\d),(?=\d{1,2}\b)")
_NUMBER = re.compile(r"\d+(?:\.\d+)?")


# Насколько далеко от идентификатора числа ещё считаются «его».
#
# ПОТОЛОК ДОБАВЛЕН ПО ВТОРОЙ ЛОЖНОЙ ТРЕВОГЕ ПОДРЯД, и обе одной природы:
# окно последнего идентификатора тянулось до конца текста и подбирало
# числа из чужих предложений.
#
#   «…сечение 6.95 м) [1].»        — единица из номера ссылки
#   «Для PP-0037 … вывести первые 5 рейсов» — пятёрка из соседней фразы
#
# Строка данных короткая: «Труба PP-0035: выработка 97.7%, циклов
# 1990578, критическое сечение 4.79 м, скважина W-122.» — около девяноста
# знаков, и дальше по строке идёт уже номер скважины, который окно
# закрывает сам.
IDENTIFIER_WINDOW_CHARS = 90

# Конец предложения: точка со следующим за ней пробелом и заглавной.
#
# Граница по смыслу надёжнее границы по длине: числа трубы стоят в ЕЁ
# предложении, а «вывести первые 5 рейсов» — уже в следующем. Точка
# внутри числа («97.7%») сюда не попадает: после неё нет пробела.
_SENTENCE_END = re.compile(r"(?<=[.!?])\s+(?=[А-ЯЁA-Z])")


def _numbers_by_identifier(text: str) -> dict[str, set[float]]:
    """Числа, стоящие ПРИ каждом идентификаторе.

    Окно — от идентификатора до следующего идентификатора, конца строки,
    конца предложения или девяноста знаков, что раньше. Это не универсальное правило
    разбора текста, а точное описание того, как сервис и модель пишут
    такие строки: всё, что относится к трубе, стоит сразу за её номером.

    Границу приходится ставить жёстко, потому что цена ошибок разная.
    Пропущенная подмена — одна неверная строка в ответе. Ложная тревога —
    красная плашка на верном ответе, после которой человек перестаёт
    верить проверке вообще, и настоящую подмену тоже спишет на придирки.
    """
    normalized = _DECIMAL_COMMA.sub(".", _THOUSANDS.sub("", text or ""))
    marks = list(_IDENTIFIER.finditer(normalized))
    found: dict[str, set[float]] = {}
    for index, mark in enumerate(marks):
        start = mark.end()
        end = marks[index + 1].start() if index + 1 < len(marks) else len(normalized)
        end = min(end, start + IDENTIFIER_WINDOW_CHARS)
        window = normalized[start:end]
        # Перевод строки тоже граница: строки таблицы кончаются им.
        window = window.split("\n", 1)[0]
        # И конец предложения: дальше речь уже не об этой трубе.
        window = _SENTENCE_END.split(window, 1)[0]
        numbers = {float(value) for value in _NUMBER.findall(window)}
        found.setdefault(mark.group(0), set()).update(numbers)
    return found


def mismatched_numbers(answer: str, fragments: list[Fragment]) -> list[str]:
    """Идентификаторы, у которых числа в ответе расходятся с источником.

    ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ ДЕТЕКТОРА, и без неё первая ловит половину
    случаев. Проверка имён поймала выдуманную трубу PP-0029. Но в
    следующем же прогоне модель написала «PP-0001, выработка 7 %» —
    номер настоящий, а в ответе сервиса у этой трубы 77.0 %. Имя
    проверено, число выдумано, на экране всё чисто.

    Для инженера по инструменту разница между 7 и 77 процентами ресурса —
    это разница между «работаем» и «снимаем с колонны». Ошибка в одной
    цифре здесь дороже целой выдуманной строки: выдуманную заметят, а
    искажённую — нет.

    Сверяются только числа ПРИ идентификаторе и только для тех, у кого в
    источнике числа вообще есть. Сравнивать весь ответ пословно нельзя:
    «топ-5», «10 труб», «в среднем» — это счёт и речь, а не данные, и
    сторож, срабатывающий на них, станет шумом за один день.
    """
    source = _numbers_by_identifier(
        " ".join(fragment.body for fragment in fragments)
    )
    # НОМЕРА ССЫЛОК ВЫРЕЗАЕМ, и это не мелочь — на них сторож соврал.
    #
    # Ответ кончался так: «…PP-0018 (75.2%, циклов 1215552, сечение
    # 6.95 м) [1].» Окно последнего идентификатора идёт до конца текста, и
    # в него попадала единица из «[1]». В источнике у PP-0018 такого числа
    # нет — и совершенно верная строка получила красную плашку.
    #
    # Ложная тревога здесь дороже пропуска: сторож, поймавший невиновного
    # на глазах у пользователя, теряет доверие целиком, и настоящую
    # подмену потом тоже спишут на его придирки.
    said = _numbers_by_identifier(_TEXT_REF.sub(" ", answer or ""))

    bad: list[str] = []
    for identifier, numbers in said.items():
        known = source.get(identifier)
        if not known or not numbers:
            continue
        if numbers - known:
            bad.append(identifier)
    return sorted(bad)


def _text_refs(text: str) -> set[int]:
    """Номера фрагментов, проставленные в тексте ответа: [1], [2], [1, 2].

    Нужны ровно для одного: отличить «ответ без источника» от «источник
    назван, но не в том поле». Первое — повод не верить ответу, второе —
    повод не верить нашей проверке.
    """
    return {
        int(number)
        for group in _TEXT_REF.findall(text or "")
        for number in re.split(r"[,;]", group)
    }


def _is_question(text: str) -> bool:
    """Задан ли в тексте вопрос.

    Проверка нарочно грубая — по вопросительному знаку — и большего тут не
    надо. Она решает ровно одну задачу: отличить «уточните, что именно вам
    нужно?» от «максимальный размер не указан, но рекомендуется разбивать
    свыше 400 строк». Первое — вопрос с пустым полем, второе — ответ с
    неверным ярлыком.

    Умнее делать не стоит: разбор намерения по тексту — это ещё одна
    эвристика, которая однажды ошибётся молча. Вопросительный знак либо
    есть, либо нет.
    """
    return "?" in text


def finalize(
    raw_json: str, fragments: list[Fragment], *, streamed_text: str, question: str = ""
) -> AnswerEnvelope:
    """Разбирает и валидирует полный ответ модели.

    Схему валидируем на своей стороне, даже если провайдер обещал строгий
    режим: его гарантия — это его гарантия, а не наша. Если JSON не разобрался,
    не падаем: у нас уже есть текст, который человек видел в потоке, и лучше
    отдать его с честной пометкой, чем показать ошибку поверх прочитанного
    ответа (раздел 5).
    """
    try:
        payload = json.loads(raw_json)
        if not isinstance(payload, dict):
            raise ValueError("на верхнем уровне ожидался объект")
    except (json.JSONDecodeError, ValueError) as error:
        # Текст, который человек уже прочитал, отдаём: стирать прочитанное
        # хуже, чем показать обрыв. Но статусом `answered` это не помечаем.
        #
        # Раньше помечали — и на этом попались второй раз тем же способом.
        # Модель упёрлась в лимит токенов, JSON не закрылся, разбор провалился,
        # а строка ушла наружу как «ответил»: и в интерфейс, и в метрику. Ярлык
        # «ответил» означает «структура получена и проверена». Здесь она не
        # получена, значит ярлык — ложь, даже если текст полезен.
        # ПУСТОЙ ОТВЕТ И ИСПОРЧЕННЫЙ — РАЗНЫЕ ДИАГНОЗЫ.
        #
        # «JSONDecodeError: Expecting value: line 1 column 1 (char 0)»
        # формально верно и практически бесполезно: char 0 означает, что
        # разбирать было НЕЧЕГО — модель не отдала ни байта. Это не порча
        # структуры, это молчание, и чинится оно совсем другим.
        #
        # Живой случай: думающая модель истратила весь лимит токенов на
        # размышления и до ответа не дошла. Человек увидел «структура не
        # разобрана» и пошёл искать ошибку в разборе, которой там нет.
        if not raw_json.strip():
            return AnswerEnvelope(
                status=AnswerStatus.ERROR,
                answer=streamed_text.strip() or "Модель не начала ответ.",
                schema_valid=False,
                schema_error=(
                    "модель не отдала ни одного байта ответа. Обычная причина "
                    "у думающих моделей — весь лимит токенов ушёл на "
                    "размышления: поднимите PW_MAX_ANSWER_TOKENS или возьмите "
                    "модель без размышлений"
                ),
            )

        return AnswerEnvelope(
            status=AnswerStatus.ERROR,
            answer=streamed_text.strip() or "Ответ пришёл в неразобранном виде.",
            schema_valid=False,
            schema_error=f"структура не разобрана: {error.__class__.__name__}: {error}",
        )

    raw_status = str(payload.get("status", "")).strip()
    # Служебные статусы моделью не принимаются. `no_context` означает «поиск
    # не дал ничего выше порога» — это факт про НАШ поиск, и выставляет его
    # сервер. Приняв его от модели, мы смешали бы в метрике «порог отсёк» с
    # «модель отказалась», а это два разных диагноза и два разных ремонта.
    if raw_status not in {status.value for status in MODEL_STATUSES}:
        status = AnswerStatus.ANSWERED if payload.get("answer") else AnswerStatus.ERROR
    else:
        status = AnswerStatus(raw_status)

    answer = str(payload.get("answer", "")).strip() or streamed_text.strip()
    citations_raw = payload.get("citations")
    citations = resolve_citations(
        citations_raw if isinstance(citations_raw, list) else [],
        fragments,
        claim=answer,
    )

    # Ответ без единой цитаты при статусе «ответил» — не ответ.
    #
    # Правило промпта гласит: каждое утверждение подкрепляется ссылкой на
    # фрагмент. Значит «ответил, но сослаться не на что» — это ровно два
    # случая, и оба плохие: либо модель написала отказ и перепутала ярлык,
    # либо сочинила утверждение из ничего. Первый случай мы поймали в
    # измерениях: модель написала «сведений во фрагментах нет» и пометила это
    # `answered`.
    #
    # Раньше мы это только помечали. Помечать недостаточно: интерфейс покажет
    # человеку уверенный ответ, а метрика зачтёт его как ответ. Поэтому
    # статус исправляется на стороне сервера, а исходный сохраняется в
    # schema_error — чтобы в трейсе было видно, что это наша правка, а не
    # решение модели.
    #
    # Это общий приём: то, что можно проверить у себя, не оставляют на совесть
    # модели. Ярлык, противоречащий содержанию, — проверяемое условие.
    clarifying_question = str(payload.get("clarifying_question", "")).strip()

    schema_error = ""

    # Уточнение без уточняющего вопроса — не уточнение.
    #
    # Из прогона: на вопрос про максимальный размер пул-реквеста модель
    # ответила по существу — «явно не указан, но рекомендуется разбивать
    # свыше 400 изменённых строк», — и пометила это `need_clarification`, не
    # спросив ничего. Метрика статуса честно засчитала промах, а дефект был не
    # в ответе, а в ярлыке.
    #
    # Это тот же приём, что и «ответил без единой цитаты»: ярлык, который
    # противоречит содержанию, — проверяемое условие, и проверять его надо у
    # себя, а не оставлять на совесть модели. Ярлык `need_clarification`
    # обещает вопрос в `clarifying_question`; нет вопроса — обещание не
    # выполнено, и ярлык заменяется на тот, который содержанию соответствует.
    if status is AnswerStatus.NEED_CLARIFICATION and not clarifying_question:
        # СНАЧАЛА смотрим, не задан ли вопрос прямо в тексте ответа.
        #
        # Это второй случай, и он вскрылся на живой переписке. Модель
        # написала в `answer`: «Извините, но я не могу понять запрос.
        # Уточните, какие именно данные вам нужны», — а поле
        # `clarifying_question` оставила пустым. Правка честно сработала
        # по букве и заменила ярлык на «ответил», потому что ссылки были.
        #
        # На экране получилось «ответ найден» над текстом «уточните
        # запрос». Это хуже, чем неверный ярлык от модели: неверный ярлык
        # — её ошибка, а этот мы поставили сами и своими руками сделали
        # интерфейс лжецом.
        #
        # Поле пустое — это про ФОРМУ, а не про содержание. Если вопрос
        # задан, его надо перенести туда, где ему место, и ярлык оставить.
        if _is_question(answer):
            schema_error = "уточняющий вопрос был в тексте ответа — перенесён в поле"
            clarifying_question = answer.strip()
        else:
            schema_error = "статус «нужно уточнение» без уточняющего вопроса — исправлен"
            status = AnswerStatus.ANSWERED if citations else AnswerStatus.NOT_FOUND

    if status is AnswerStatus.ANSWERED and not citations:
        # СНАЧАЛА смотрим, не проставлены ли ссылки прямо в тексте.
        #
        # Эта правка второй раз подряд оказалась опаснее ошибки, от которой
        # защищала. Из живой переписки: модель дала безупречный ответ —
        # пять труб с выработкой, циклами и сечениями, — поставила в конце
        # [2], но массив citations оставила пустым. Правка честно по букве
        # заменила ярлык на «в документации нет ответа». Над правильным,
        # полным, подтверждённым ответом.
        #
        # Пустой массив — это про ФОРМУ. Он значит «нечего сверять
        # дословно», а не «ответ взят с потолка». Эти два случая надо
        # различать: во втором ответ действительно опасен, в первом опасна
        # только наша правка.
        #
        # Номер сверяется с тем, что реально было в контексте: «[7]» при
        # шести фрагментах — выдумка, и вот она как раз повод для отказа.
        referenced = _text_refs(answer) & {fragment.number for fragment in fragments}
        if referenced:
            schema_error = (
                "ссылки указаны только в тексте, без опоры — "
                "дословность не проверена"
            )
        else:
            schema_error = "статус «ответил» без единой цитаты — исправлен на not_found"
            status = AnswerStatus.NOT_FOUND

    # «НЕТ ОТВЕТА» НАД ПОЛНОЙ ТАБЛИЦЕЙ — ЭТО НЕПРАВДА.
    #
    # Из живого прогона: «следующие 5 скважин покажи» — таблица пришла,
    # пять строк на экране, а над ней ярлык «в документации нет ответа» и
    # текст «я могу показать только первую строку, обратитесь к системе
    # напрямую». Человек видит данные и сообщение, что данных нет.
    #
    # Ярлык ставит модель, и здесь она оценивает не результат, а свою
    # осведомлённость: строк она действительно не видит, их видит человек.
    # Мы знаем больше неё — живой фрагмент в контексте означает, что сервис
    # ответил, — и поправить ярлык обязаны мы.
    #
    # Текст ответа при этом НЕ трогаем: он останется неудачным, и это
    # видно. Чинить надо ровно то, что сломано, а сломан здесь ярлык.
    if status in {AnswerStatus.NOT_FOUND, AnswerStatus.NO_CONTEXT} and any(
        fragment.live for fragment in fragments
    ):
        status = AnswerStatus.ANSWERED
        schema_error = schema_error or (
            "статус «нет ответа» при живых данных сервиса — исправлен на answered"
        )

    # При ОТКАЗЕ снимаем только НЕПОДТВЕРДИВШИЕСЯ ссылки.
    #
    # Сначала я снимал их все, рассуждая так: ссылка подтверждает утверждение,
    # у отказа утверждения нет, значит проверять нечего. Логика верная, а
    # посылка неверна, и следующий же прогон это показал.
    #
    # Вопрос q020 («складываются ли повреждения сечений трубы») — критичный.
    # Модель написала правильный ответ: «не складываются, состояние трубы
    # определяется её самым нагруженным сечением», приложила две ссылки,
    # которые обе НАШЛИСЬ в документе, — и поставила ярлык not_found. Я снял
    # обе ссылки и тем самым уничтожил подтверждение верного ответа, поверив
    # самому ненадёжному полю из трёх.
    #
    # Ненадёжность `status` — не догадка, а измеренный факт: из-за неё мы
    # переставляли поля схемы, потому что ярлык, выданный раньше содержания,
    # ломал 60 ответов из 67. Строить на таком поле РАЗРУШАЮЩЕЕ действие —
    # значит наступить на те же грабли с другой стороны.
    #
    # Правило теперь опирается на проверяемое. Ссылка, которая нашлась в
    # документе, — факт, и она остаётся при любом ярлыке. Ссылка, которая не
    # нашлась, при отказе бесполезна: это набивка поля, и её мы убираем с
    # экрана, сохранив число в `citations_dropped`.
    citations_dropped = 0
    if status in {AnswerStatus.NOT_FOUND, AnswerStatus.NO_CONTEXT}:
        kept = [citation for citation in citations if citation.ok]
        citations_dropped = len(citations) - len(kept)
        citations = kept

    return AnswerEnvelope(
        status=status,
        answer=answer,
        citations=citations,
        clarifying_question=clarifying_question,
        schema_valid=not schema_error,
        schema_error=schema_error,
        citations_dropped=citations_dropped,
        unknown_refs=unknown_identifiers(answer, fragments, question),
        mismatched_refs=mismatched_numbers(answer, fragments),
    )

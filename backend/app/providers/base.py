"""Единый интерфейс провайдера модели.

Смысл слоя ровно один: остальной код не должен знать, кто отвечает — локальная
модель через Ollama или облачная. Тогда переключение на резерв при отказе это
конфигурация, а не рефакторинг (раздел 2 чек-листа).

Здесь только типы и протоколы. Ни одной строчки, знающей про конкретного
провайдера.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import AsyncIterator, Protocol, runtime_checkable


class FinishReason(str, Enum):
    """Почему генерация закончилась.

    Обрабатывать надо все причины: ответ, обрезанный по лимиту токенов, без
    отдельной обработки выглядит для пользователя как нормально законченный
    (раздел 5).
    """

    STOP = "stop"            # модель закончила сама
    LENGTH = "length"        # упёрлись в лимит токенов
    CANCELLED = "cancelled"  # пользователь нажал «Стоп»
    ERROR = "error"          # оборвалось с ошибкой
    TIMEOUT = "timeout"      # провайдер замолчал дольше допустимого


@dataclass(slots=True)
class Usage:
    """Расход по запросу.

    prompt_tokens и completion_tokens приходят от провайдера — это точные
    числа. Наша собственная оценка токенов (в rag/context) нужна только для
    планирования бюджета ДО запроса и всегда приблизительна; смешивать их
    нельзя.
    """

    prompt_tokens: int = 0
    completion_tokens: int = 0
    cost_rub: float = 0.0  # для локальной модели ноль, но поле есть всегда

    @property
    def total_tokens(self) -> int:
        return self.prompt_tokens + self.completion_tokens


@dataclass(slots=True)
class ToolCall:
    """Просьба модели выполнить инструмент.

    `arguments` — уже разобранный объект, а не строка. Разные провайдеры
    присылают аргументы по-разному: кто объектом, кто строкой с JSON внутри.
    Приводить их к одному виду обязан адаптер провайдера — ровно по той же
    причине, по которой он приводит к одному виду схему ответа. Иначе про
    различия придётся знать вызывающему коду, и слой провайдеров перестанет
    что-либо скрывать.
    """

    name: str
    arguments: dict


@dataclass(slots=True)
class ChatChunk:
    """Кусок потока. Либо текст, либо финал с причиной завершения."""

    text: str = ""
    # «Размышления» модели — отдельный канал, а не часть ответа.
    #
    # Модели с рассуждением отдают его в своём поле, и провайдер не смешивает
    # его с ответом. Если это поле не читать, размышления просто исчезают — и
    # когда модель израсходовала на них весь лимит токенов, наружу приходит
    # ПУСТОЙ ответ без единого признака того, куда делись токены. Именно так
    # наш судья и замолчал: 67 «вердиктов не разобрано» при пустой строке.
    #
    # Поле отдельное, а не приклеенное к text, сознательно: размышления нельзя
    # показывать пользователю и нельзя проверять как ответ, но их обязательно
    # надо видеть в диагностике.
    thinking: str = ""
    done: bool = False
    finish_reason: FinishReason | None = None
    usage: Usage | None = None
    # Инструменты, которые модель просит выполнить. Пусто почти всегда.
    tool_calls: list[ToolCall] = field(default_factory=list)


@dataclass(slots=True)
class ChatRequest:
    system: str
    user: str
    temperature: float = 0.0
    max_tokens: int = 700
    # Какой моделью отвечать. Пусто — той, что настроена у провайдера.
    #
    # Поле здесь, а не в настройках, потому что выбор модели стал решением
    # ОДНОГО запроса: человек в интерфейсе может спросить одно и то же у
    # локальной и у облачной и сравнить. Настройки при этом общие на всё
    # приложение, и менять их из обработчика запроса нельзя — второй
    # пользователь получил бы чужой выбор.
    model: str = ""
    # Сколько провайдеру держать модель в памяти после ответа. None — как
    # настроено у него по умолчанию, 0 — выгрузить сразу.
    #
    # Нужно это не для красоты. На машине с одной видеокартой две модели
    # одновременно не помещаются: попытка поднять судью рядом с отвечающей
    # уронила llama-server с ошибкой CUDA. Явное управление временем жизни
    # модели — то, чем это лечится со стороны клиента.
    keep_alive: str | int | None = None
    # JSON Schema. Форма ответа задаётся схемой на стороне API провайдера, а не
    # вежливой просьбой в промпте: просьба даёт несколько процентов брака, и
    # каждый процент — исключение при разборе ответа в проде (раздел 5).
    json_schema: dict | None = None
    # Включать ли «размышления» у моделей, которые их умеют. None — не трогать
    # настройку провайдера, False — выключить.
    #
    # Судье размышления не нужны: у него есть поле reason, где он пишет причину
    # словами, и этого достаточно. А цена включённых размышлений — весь лимит
    # токенов, потраченный до того, как начнётся ответ.
    think: bool | None = None
    # ЗЕРНО СЛУЧАЙНОСТИ. None — не трогать, провайдер берёт своё.
    #
    # Нужно для прогонов: на одном и том же зерне локальная модель отвечает
    # одинаково, и разброс между прогонами перестаёт маскировать разницу
    # между правками. Без него мы платим за ту же уверенность пятью
    # прогонами вместо одного.
    #
    # Температура 0 этого НЕ заменяет. Ноль означает «всегда самый
    # вероятный токен», но порядок арифметики при параллельном счёте на
    # видеокарте немного плавает, и ответы выходят почти одинаковыми, а не
    # побитово. Поэтому проверки у нас сравнивают по смыслу, а не строками,
    # — и зерно нужно ровно затем, чтобы сузить это «почти».
    #
    # Отправляет его только локальный провайдер: у Сбера параметр не
    # подтверждён по документации, а посылать непроверенное поле в прогон,
    # которым принимают решения, — это менять измеряемую систему втихую.
    seed: int | None = None
    # Строки, на которых генерация обрывается. Пусто — не ограничивать.
    stop: list[str] = field(default_factory=list)
    # Инструменты, которые модель имеет право вызвать. Пусто — обычный
    # запрос без инструментов, и тогда поле в тело запроса не попадает
    # вовсе: модель, которой показали пустой список инструментов, иногда
    # начинает извиняться, что не может ничего вызвать.
    tools: list[dict] = field(default_factory=list)
    # Уже состоявшийся обмен: что модель просила и что ей ответили. Без
    # этого второй шаг агента не знает о первом и просит то же самое по
    # кругу, пока не упрётся в ограничение шагов.
    history: list[dict] = field(default_factory=list)


class ProviderError(RuntimeError):
    """Ошибка провайдера с разметкой: можно ли повторять и когда.

    Различение retryable/не-retryable делается здесь, а не в вызывающем коде,
    потому что знание о том, что 400 повтором не лечится, принадлежит слою
    провайдера (раздел 2).
    """

    def __init__(
        self,
        message: str,
        *,
        retryable: bool,
        status: int | None = None,
        retry_after_s: float | None = None,
        provider: str = "",
    ) -> None:
        super().__init__(message)
        self.retryable = retryable
        self.status = status
        self.retry_after_s = retry_after_s
        self.provider = provider


class ProviderUnavailable(ProviderError):
    """Провайдер недоступен целиком: сеть, предохранитель, отключён в конфиге."""

    def __init__(self, message: str, *, provider: str = "") -> None:
        super().__init__(message, retryable=True, provider=provider)



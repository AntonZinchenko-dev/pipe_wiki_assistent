    # ошибкой: модель, у которой инструмент не работает, начинает пробовать
    # его снова и снова и тратит на это шаги.
    #
    # Токена у стенда нет, но поле есть: без него переезд на боевой контур
    # означал бы правку кода, а не настройки. Токен живёт только здесь, на

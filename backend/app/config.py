    # вместо вызова, один раз переходит на бланк ответа — и запоминает это
    # для пары «провайдер + модель». Нужно потому, что вызов функций
    # поддерживают не все модели: на облачной Lightning за пять запросов
    # подряд не пришло ни одного вызова, а бланк ответа на ней работает.
    #
    # `tools` и `schema` — принудительно, для замеров: два механизма это
    # две системы, и сравнивать их надо явно, а не гадать, какой сработал.
    agent_decision: str = "auto"


    token_safety_margin: int = 500

    # Поиск
    search_top_k: int = 24
    context_max_fragments: int = 8
    similarity_floor: float = 0.45

    # Константа слияния и вес ключевого списка. Выбраны ПЕРЕБОРОМ, не на глаз:
    # scripts/eval.py sweep считает 42 варианта за время одного прогона,
    # потому что достать списки стоит вызова модели, а слить — ничего.
    #
    # Было k = 60 и вес 1.0 — то есть значения из статьи про списки длиной в

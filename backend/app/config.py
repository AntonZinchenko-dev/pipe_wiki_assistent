    alert_error_rate_warn: float = 0.01   # РЛ-9.2: порог внимания 1 %
    alert_error_rate_crit: float = 0.05   # РЛ-9.2: порог аварии 5 %
    alert_budget_warn: float = 0.80       # РЛ-9.2: 80 % дневного бюджета
    alert_budget_crit: float = 1.20       # РЛ-9.2: 120 % дневного бюджета

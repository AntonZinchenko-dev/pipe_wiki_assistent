    auth_mode: str = "off"
    auth_user_header: str = "X-Remote-User"
    auth_roles_header: str = "X-Remote-Roles"
    auth_default_user: str = "локальный пользователь"
    # Роли по умолчанию в режиме `off`. Здесь стоит не пусто, а рабочий
    # набор: установка без настроенного входа должна вести себя
    # предсказуемо, а не «как будто прав нет вообще».
    auth_default_roles: str = "dev,data-reader"
    # Ограничения по проектам: `SURVEYD:data-reader,FATIGUE-API:ops`.
    #
    # Пусто — ограничений нет, и это сознательно. Список ЗАПРЕЩЁННОГО, а не
    # разрешённого: разрешённый пришлось бы держать полным, и новый проект
    # в вики оказался бы невидим для всех — обновление документации молча

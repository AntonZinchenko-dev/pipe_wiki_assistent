"""Отпечаток кода, влияющего на ответ.

Зачем это отдельный файл.

Прогон измерений сохраняет конфигурацию: модель, порог, top_k, бюджет,
версию промпта. Смысл в том, чтобы через месяц можно было сказать, чем два
прогона различались, и приписать разницу метрик чему-то конкретному.

Но конфигурация не включала КОД. И мы на этом попались буквально сразу:
изменили серверную страховку в `answer.py`, сделали новый прогон, и
`compare` напечатал «конфигурации совпадают — это замер разброса». Формально
инструмент был прав: ни одно поле конфига не поменялось. Фактически он
соврал, потому что поменялось поведение системы.

Вывод общий: воспроизводимость по конфигу, в который не входит код, —
иллюзия. Конфиг должен отвечать на вопрос «та же это система или другая», а
система — это код плюс настройки, а не только настройки.

Отпечаток считается от содержимого файлов, определяющих ответ: пайплайн,
провайдеры, RAG. Тесты, скрипты и фронтенд сюда не входят — они на ответ не
влияют, и включать их значит получать ложные различия на каждую правку
теста.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

APP_DIR = Path(__file__).resolve().parent

# Порядок важен только для повторяемости хэша, поэтому пути сортируются.
TRACKED_GLOBS = ("*.py", "rag/*.py", "providers/*.py")

# Файлы, которые меняются от запуска к запуску или не влияют на ответ.
IGNORED_NAMES = {"version.py"}


def tracked_files() -> list[Path]:
    paths: set[Path] = set()
    for pattern in TRACKED_GLOBS:
        for path in APP_DIR.glob(pattern):
            if path.name in IGNORED_NAMES or "__pycache__" in path.parts:
                continue
            paths.add(path)
    return sorted(paths)


def code_version() -> str:
    """Короткий хэш кода, влияющего на ответ.

    Считается от относительных путей и содержимого: переименование файла —
    тоже изменение системы, и его надо видеть.
    """
    digest = hashlib.sha256()
    for path in tracked_files():
        digest.update(str(path.relative_to(APP_DIR)).encode())
        digest.update(b"\0")
        digest.update(path.read_bytes())
        digest.update(b"\0")
    return digest.hexdigest()[:12]

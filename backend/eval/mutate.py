"""Порча ответов: проверка ЧУВСТВИТЕЛЬНОСТИ приборов вместо согласия.

Зачем это понадобилось. Каппа Коэна измеряет согласие двух разметчиков сверх
случайного — и для этого ей нужны оба класса в разумной пропорции. У нас их
нет и не будет: система отвечает верно примерно в 95 % случаев, и случайная
выборка из сорока ответов даёт 36 верных против 2 неверных. На таком перекосе
каппа не определена практически, а формально считается и выдаёт 0.2 — цифру,
которую легко принять за «приборы плохи», хотя означает она «мерить нечем».

Сортировка «сначала подозрительные» должна была это исправить и не исправила:
подозрительные оказались в основном верными. Само по себе это хорошая новость
(автоматические флаги почти не врут), но для калибровки это тупик.

Выход — перевернуть задачу. Вместо «согласны ли приборы с человеком на
случайных ответах» спрашиваем «ЛОВЯТ ЛИ приборы ответы, про которые мы ТОЧНО
знаем, что они неверны». Неверные ответы делаем сами из верных: меняем число,
переворачиваем отрицание, заменяем текст отказом, оставляем эхо вопроса.

Аналогия. Пожарный датчик нельзя проверить, сидя в комнате и отмечая, что он
молчит. Его проверяют дымом: поджигают бумажку и смотрят, сработает ли. Дым
нужен свой, известный — иначе проверка зависит от того, случится ли пожар.

Честность метода держится на двух условиях, и оба важны:

1. порча должна быть НАСТОЯЩЕЙ ошибкой, а не придиркой. Изменить «80 %» на
   «8 %» — ошибка. Переставить слова — нет;
2. это НЕ замена измерению на живых ответах. Чувствительность к подделкам
   говорит, что прибор не слеп; она не говорит, как часто он ошибается на
   настоящем потоке. Смешивать эти два вопроса — значит снова себя обманывать.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

_NUMBER = re.compile(r"\d+")
REFUSAL = "Конкретных сведений об этом в документах нет."


@dataclass(slots=True)
class Mutant:
    kind: str
    answer: str
    why: str


def _flip_number(text: str, *, only: set[str] | None = None) -> str | None:
    """Меняет первое число так, чтобы ответ стал неверным, но правдоподобным.

    Правдоподобие здесь — часть проверки. «Порог 8 %» вместо «80 %» выглядит
    как опечатка в живом ответе, и прибор обязан её поймать; заменять на
    «порог сто миллионов» значило бы проверять лёгкий случай.
    """
    match = next(
        (
            found
            for found in _NUMBER.finditer(text)
            if not only or found.group() in only
        ),
        None,
    )
    if match is None:
        return None
    value = match.group()
    changed = value[:-1] if len(value) > 1 else str((int(value) + 3) % 10)
    if not changed or changed == value:
        changed = str(int(value) + 1)
    return text[: match.start()] + changed + text[match.end() :]


def _flip_negation(text: str) -> str | None:
    """Переворачивает отрицание — самая опасная ошибка в справочной системе.

    «Токен новичку не выдаётся» против «выдаётся» — это разница между
    соблюдённым регламентом и инцидентом безопасности, а по форме ответы
    почти одинаковые. Именно здесь прибор обязан быть зорким.
    """
    for pattern, replacement in (
        (r"\bне выдаётся\b", "выдаётся"),
        (r"\bне выдаются\b", "выдаются"),
        (r"\bне выдают\b", "выдают"),
        (r"\bне используется\b", "используется"),
        (r"\bне складываются\b", "складываются"),
        (r"\bзапрещена\b", "разрешена"),
        (r"\bзапрещено\b", "разрешено"),
        (r"\bнельзя\b", "можно"),
        (r"\bне подключена\b", "подключена"),
        (r"\bне считает\b", "считает"),
        (r"\bне выходят\b", "выходят"),
    ):
        changed, count = re.subn(pattern, replacement, text, count=1, flags=re.IGNORECASE)
        if count:
            return changed
    return None


# Ложное утверждение для дописки. Взято из корпуса и ПЕРЕВЁРНУТО: в
# регламенте отключение кэша в продакшене запрещено безусловно.
FALSE_CLAIM = "Кроме того, отключать кэш последних значений в продакшене разрешено."


def mutants_for(
    *, question: str, answer: str, needles: list[str] | None = None
) -> list[Mutant]:
    """Применимые порчи одного ответа. Каждая обязана быть ЗАВЕДОМО неверной.

    «Заведомо» — главное слово. Первая версия этой функции делала ещё и
    обрезку ответа до первого предложения, и на первом же примере обрезанный
    ответ оказался ПОЛНЫМ И ВЕРНЫМ: «Новичкам токены к боевому контуру не
    выдаются» — факт сохранён целиком, отброшено пояснение. Прибор, не
    поднявший тревогу на таком «мутанте», был бы наказан за правильную
    работу, а я записал бы это ему в слепоту.

    Поэтому обрезка убрана, а изменение числа делается только по числу,
    которое ЯВЛЯЕТСЯ фактом — то есть входит в разметку вопроса. Разметка
    здесь используется для ПОСТРОЕНИЯ порчи, а не для её оценки: что мутант
    неверен, мы знаем из способа его изготовления, а ловят его приборы или нет
    — отдельный вопрос, и на него отвечают они сами.
    """
    made: list[Mutant] = []
    needles = needles or []

    made.append(Mutant("отказ", REFUSAL, "ответ заменён отказом при наличии факта"))

    # Эхо: ответ повторяет термин вопроса и не сообщает ничего.
    words = [word for word in re.findall(r"[\w./-]{4,}", question) if not word.isdigit()]
    if words:
        made.append(
            Mutant("эхо", max(words, key=len), "ответ повторяет слово из вопроса")
        )

    # Число портим ТОЛЬКО если оно и есть факт: иначе «РЛ-9.2» превратится в
    # «РЛ-8.2», ответ останется верным по существу, и прибор будет наказан
    # за то, что не поднял ложную тревогу.
    fact_numbers = {number for needle in needles for number in _NUMBER.findall(needle)}
    if fact_numbers:
        flipped = _flip_number(answer, only=fact_numbers)
        if flipped and flipped != answer:
            made.append(Mutant("число", flipped, "изменено число, несущее факт"))

    negated = _flip_negation(answer)
    if negated and negated != answer:
        made.append(Mutant("отрицание", negated, "перевёрнуто отрицание"))

    # ПРИПИСКА — единственная порча, к которой проверка подстрокой слепа ПО
    # ПОСТРОЕНИЮ, и потому главная в этом наборе.
    #
    # Верный ответ остаётся на месте целиком: все ожидаемые подстроки в нём
    # есть, проверка довольна. А рядом дописано утверждение, которого в
    # документах нет и которое прямо противоречит регламенту. Именно так
    # выглядит самая опасная ошибка справочной системы: правильный ответ
    # плюс уверенная отсебятина.
    #
    # Вот на этом виде и решается вопрос, окупает ли судья вызовы. Если он
    # ловит дописку, а подстрока не может — он нужен. Если не ловит и он,
    # платить за него нечем.
    made.append(
        Mutant(
            "приписка",
            f"{answer.strip()} {FALSE_CLAIM}",
            "к верному ответу дописано ложное утверждение",
        )
    )

    return made

"""Судья-модель и её калибровка.

Четыре требования раздела 4, все обязательные.

**Судья отделён от отвечающего.** Отвечает qwen2.5, судит nemotron. Если
судить той же моделью тем же контекстом, она систематически одобряет свои же
ответы — эффект известный, и он завышает метрику, не добавляя знания.

**Решение бинарное.** Не «оценка от 1 до 10»: шкала у модели плывёт между
запусками и между версиями промпта, а «да/нет» устойчиво. Заодно бинарное
решение можно сравнить с человеческой разметкой каппой.

**Температура ноль.** Судья — это измерительный прибор; прибор, дающий разные
показания на одном входе, не прибор.

**Судья калиброван на людях.** Пока каппа Коэна с ручной разметкой не
посчитана, судье нельзя доверять вообще: мягкий судья одобрит всё и покажет
прекрасные метрики. Ниже 0.6 все цифры на этом судье — шум (см. metrics.cohen_kappa
и scripts/eval_kappa.py).

Эталон для судьи — сам корпус, а не написанный от руки образцовый ответ.
Судье подаются фрагменты тех документов, которые в золотом наборе помечены как
содержащие ответ. Так эталон не расходится с документацией при её изменении —
а написанный от руки ответ расходится молча.
"""


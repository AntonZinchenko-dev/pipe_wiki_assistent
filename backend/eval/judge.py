JUDGE_SYSTEM = """\
Ты — строгий проверяющий. Тебе дают вопрос сотрудника, выдержки из
документации и ответ, который выдала справочная система.

Твоя задача: решить, верен ли ответ ПО ОТНОШЕНИЮ К ВЫДЕРЖКАМ.

Ответ считается верным, если он отвечает на заданный вопрос и не противоречит
выдержкам. Ответ считается неверным, если он: противоречит выдержкам;
отвечает не на заданный вопрос; утверждает то, чего в выдержках нет;
уклоняется от ответа, когда ответ в выдержках есть.

Стиль, длина, вежливость и наличие ссылок на номера фрагментов НЕ влияют на
решение. Отсутствие деталей, которых вопрос не требовал, тоже не делает ответ
неверным.

Выдержки пронумерованы: [1], [2] и так далее.

Поля заполняй в этом порядке: fragment, reason, correct.

В поле fragment — НОМЕР той выдержки, на которой основано твоё решение. Один
номер, из тех, что есть в списке. Если ни одна выдержка вопроса не решает,
поставь 0 и скажи об этом в reason.

В поле reason — одна короткая фраза с причиной, и в ней опирайся только на ту
выдержку, номер которой указал.

Решение в поле correct строго бинарное."""

# ПОРЯДОК ПОЛЕЙ: сначала reason, потом correct.
#
# Это не оформление. Провайдер строит из схемы грамматику и требует поля в
# объявленном порядке; генерация авторегрессивная. Значит `correct` первым —
# это приговор до единого шага рассуждения, ровно тот дефект, который стоил
# нам 60 ложных отказов в схеме ответа (ШАГ-2-ВЫВОДЫ, раздел 3). У судьи он
# опаснее: судья — измерительный прибор, и смещённый прибор портит не один
# ответ, а все выводы, которые по нему делаются.
#
# Здесь применён второй приём из того же правила: ярлык нужен, но перед ним
# ставится поле для рассуждения. `reason` в этой схеме — не украшение для
# логов, а место, где судье РАЗРЕШЕНО подумать прежде, чем решать. Поэтому же
# в промпте просят одну короткую фразу: длинное рассуждение здесь не нужно,
# нужен хотя бы один шаг.
JUDGE_SCHEMA: dict = {
    "type": "object",
    "properties": {
        # Сначала ОПОРА — номер выдержки, а не её текст.
        #
        # Первая версия требовала дословную цитату, и это оказалось слишком
        # строго: маленькая модель не воспроизводит длинный отрывок символ в
        # символ, и проверка отвергла 39 вердиктов из 67. Проверка, которая
        # выбрасывает больше половины данных, — не проверка, а шредер: она
        # уничтожает измерение, вместо того чтобы его защищать.
        #
        # Номер решает ту же задачу дешевле. Модель не переписывает текст,
        # который у нас уже есть, — она на него указывает. Ровно так же
        # устроены ссылки в ответах системы, и по той же причине.
        #
        # Что номер ловит: ссылку на выдержку, которой нет. Чего не ловит:
        # неверное прочтение существующей выдержки — это остаётся работой
        # человека, и честнее сказать это прямо, чем делать вид, что проверка
        # всесильна.
        "fragment": {"type": "integer"},
        "reason": {"type": "string"},
        "correct": {"type": "boolean"},
    },
    "required": ["fragment", "reason", "correct"],
}


THINK_BLOCK = re.compile(r"<think>.*?</think>|<thinking>.*?</thinking>", re.S | re.I)


def extract_json_object(text: str) -> str | None:
    """Достаёт первый полный объект JSON из текста вокруг него.

    Зачем терпимость, если у нас строгая схема. Схема ограничивает то, что
    модель пишет В ПОЛЕ ответа, но не обязывает провайдера отдать ровно этот
    объект и ничего больше. Модели с «рассуждением» выводят свои размышления
    до ответа — иногда в блоке <think>, иногда просто текстом, — и тогда
    json.loads по всей строке падает, хотя валидный объект в ней есть.

    Наш судья на этом и сломался: 66 вердиктов из 67 пришли «неразобранными».
    Требовать, чтобы вся строка была JSON, — это требование не к данным, а к
    поведению чужой модели, и оно не выполняется.

    Разбор идёт по балансу скобок с учётом строк и экранирования: наивный
    поиск последней `}` ломается на объекте, внутри строки которого есть
    скобка, а такое встречается в цитатах из документов.
    """
    text = THINK_BLOCK.sub(" ", text)
    start = text.find("{")
    if start < 0:
        return None

    depth = 0
    in_string = False
    escaped = False
    for position in range(start, len(text)):
        char = text[position]
        if in_string:
            if escaped:
                escaped = False
            elif char == "\\":
                escaped = True
            elif char == '"':
                in_string = False
            continue
        if char == '"':
            in_string = True
        elif char == "{":
            depth += 1
        elif char == "}":
            depth -= 1
            if depth == 0:
                return text[start : position + 1]
    return None


@dataclass(slots=True)
class Verdict:
    """Вердикт судьи. `correct = None` означает «судить не удалось».

    Три состояния, а не два, — и это принципиально. Первая версия возвращала
    `correct=False`, когда вердикт не разобрался или сверять было нечем, и в
    комментарии рядом было написано, что так делать нельзя: это смещает
    метрику. Комментарий был прав, код — нет.

    Разница в том, что «судья сказал „неверно“» и «судья не смог сказать» —
    это разные факты. Первое считается в качество. Второе считается в
    неисправность прибора, и если таких случаев много, доверять цифре нельзя
    вообще.
    """

    correct: bool | None
    reason: str
    # Номер выдержки, на которую опёрся судья, и её заголовок. Заголовок
    # хранится не для красоты: разбирать расхождения с человеком, не видя, на
    # что именно смотрел судья, невозможно — мы это уже проходили.
    fragment: int = 0
    fragment_label: str = ""
    raw: str = ""


# Ссылки вида [1], [12] в тексте ответа. Убираются перед показом судье.
_CITATION_MARK = re.compile(r"\s*\[\d+\]")


def language_verdict(answer: str) -> Verdict | None:
    """Вердикт по языку ответа — или None, если по языку претензий нет.

    ЯЗЫК РЕШАЕТСЯ ДО МОДЕЛИ И БЕЗ НЕЁ.

    Годный ответ для вики — верный по смыслу И читаемый тем, кто спрашивал.
    Ответ на китайском, безупречный по содержанию, пользователь русской вики не
    прочтёт, и засчитывать его правильным значит мерить не то, что нужно
    продукту.

    Судья сам этого не ловит: он оценивает содержание и на языке не
    сосредоточен. На прогоне образца он признал верными шесть ответов не на
    русском из одиннадцати — по смыслу верных. То есть `judge_ok` был завышен
    на величину, которой никто не видел.

    Почему проверкой в коде, а не строчкой в промпте судьи. Правило
    детерминированное, считается по буквам и стоит ноль: просить об этом модель
    значит получить те же несколько процентов брака, что и на любой просьбе, и
    платить за них вызовом. То же соображение, что и со схемой ответа: форму
    задают рамкой, а не вежливой просьбой.

    Дублирования метрик здесь нет, есть дерево диагностики: `judge_ok`
    отвечает «годен ли ответ», `language_ok` — «почему не годен».

    Пустой язык (букв в ответе нет вовсе) нарушением НЕ считается и отправляет
    строку дальше к судье: «определять нечего» — это отсутствие измерения, а не
    измерение со значением «плохо».

    Отдельной функцией, а не строчками внутри `verdict`, ровно по одной
    причине: этим же правилом пользуется пересчёт сохранённых прогонов
    (`eval.py recheck`), чтобы пересмотреть вердикты, вынесенные прибором
    прежней версии. Две копии правила разошлись бы — мы это в проекте уже
    проходили четыре раза.
    """
    language = answer_language(answer)
    if language and language != CORPUS_LANGUAGE:
        return Verdict(
            correct=False,
            reason=(
                f"ответ не на языке корпуса ({language}, ожидался "
                f"{CORPUS_LANGUAGE}) — по смыслу не проверялся"
            ),
        )
    return None


class Judge:
    def __init__(
        self,
        *,
        provider,
        model: str,
        store,
        max_excerpt_chars: int = 2400,
        think: bool | None = False,
        max_tokens: int = 700,
        seed: int | None = None,
    ) -> None:
        self._provider = provider
        self._model = model
        self._store = store
        self._max_excerpt_chars = max_excerpt_chars
        self._think = think
        self._max_tokens = max_tokens
        # ЗЕРНО У СУДЬИ ВАЖНЕЕ, ЧЕМ У ОТВЕЧАЮЩЕЙ МОДЕЛИ.
        #
        # Судья — измерительный прибор. Плавающий ответ отвечающей модели
        # портит один ответ; плавающий вердикт судьи портит ВСЕ выводы,
        # которые по нему делаются, и разброс прибора складывается с
        # разбросом измеряемого. Если зерно доступно — прибор надо
        # закреплять первым.
        self._seed = seed
        self._excerpt_cache: dict[str, str] = {}
        self._label_cache: dict[str, list[str]] = {}

    def excerpts_for(self, question: Question) -> str:
        """Выдержки из документов, помеченных как содержащие ответ.

        Берём в первую очередь чанки, в которых есть ожидаемая подстрока: это
        и есть то место документации, про которое спрашивают. Если подстрок
        нет, берём начало документа.
        """
        key = f"{question.id}"
        if key in self._excerpt_cache:
            return self._excerpt_cache[key]

        needles = [" ".join(needle.split()).lower() for needle in question.must_contain]
        picked: list[str] = []

        for doc_id in question.docs:
            detail = self._store.document(doc_id)
            if not detail:
                continue

            # Шапка документа идёт в выдержки отдельной строкой.
            #
            # Половина вопросов «кто отвечает», «какая версия», «действующий
            # ли» отвечается метаданными, а не текстом. Без шапки судья ищет
            # ответ в теле, находит похожую таблицу из соседнего раздела и
            # уверенно ошибается — у нас так и вышло на вопросе о владельце
            # TELEMETRY-GW: в шапке стоит «Группа интеграций», а судья взял
            # строку из таблицы «кому писать» в документе для новичков.
            header = (
                f"[{doc_id}] {detail.get('title', '')} · владелец: "
                f"{detail.get('owner', '—')} · ред. {detail.get('version', '—')} · "
                f"обновлён: {detail.get('updated', '—')} · статус: "
                f"{detail.get('status', '—')}"
            )
            picked.append(("шапка", header))

            chunks = detail.get("chunks", [])
            matching = [
                chunk
                for chunk in chunks
                if any(needle in " ".join(chunk["body"].split()).lower() for needle in needles)
            ]
            # Берём ТОЛЬКО куски с ожидаемой подстрокой, и не больше трёх на
            # документ. Добавлять соседние «на всякий случай» — значит дать
            # судье лишние правдоподобные строки, из которых он выберет не ту.
            # Если подстрока не нашлась нигде, берём начало документа: это
            # видно по вердикту и лечится разметкой, а не догадками.
            for chunk in (matching[:3] or chunks[:1]):
                picked.append((f"{doc_id} · {chunk['heading_path']}", chunk["body"]))

        # Обрезка по бюджету идёт ПОФРАГМЕНТНО, а нумерация считается по тому,
        # что реально уехало судье.
        #
        # Раньше блоки склеивались и общая строка резалась по 2400 символов, а
        # список номеров строился по полному набору. Два следствия, и оба
        # скверные. Первое: у вопроса с двумя-тремя документами хвост выдержек
        # молча исчезал — в том числе тот, где лежал нужный факт, если нужный
        # документ стоял в списке не первым. Судья не мог подтвердить верный
        # ответ и ставил «неверно», а метрика показывала «система ответила
        # неверно» вместо «мы неверно собрали выдержки». Второе: проверка
        # номера пропускала ссылку на выдержку, которую судья физически не
        # видел, — то есть ровно тот «вердикт не глядя», который она ловит.
        labels: list[str] = []
        blocks: list[str] = []
        budget = self._max_excerpt_chars

        for label, body in picked:
            head = f"[{len(labels) + 1}] {label}"
            # Каждому фрагменту — своя доля бюджета, чтобы длинный первый не
            # съел остальные целиком.
            share = max(240, budget // max(1, len(picked) - len(labels)))
            piece = body if len(body) <= share else body[:share].rsplit(" ", 1)[0] + "…"
            cost = len(head) + len(piece) + 2
            if cost > budget and labels:
                break
            budget -= cost
            labels.append(head)
            blocks.append(f"{head}\n{piece}")

        text = "\n\n".join(blocks)
        self._excerpt_cache[key] = text
        self._label_cache[key] = labels
        return text

    def labels_for(self, question: Question) -> list[str]:
        """Заголовки пронумерованных выдержек. Считаются вместе с выдержками."""
        if question.id not in self._label_cache:
            self.excerpts_for(question)
        return self._label_cache.get(question.id, [])

    async def verdict(self, *, question: Question, answer: str) -> Verdict:
        # Язык — первым, до модели и до выдержек: правило детерминированное и
        # от разметки не зависит. См. language_verdict.
        by_language = language_verdict(answer)
        if by_language is not None:
            return by_language

        excerpts = self.excerpts_for(question)
        if not excerpts:
            # Сверять не с чем — это брак разметки или индекса, а не плохой
            # ответ системы. Записывать это в «неверно» значит наказывать
            # систему за нашу собственную ошибку.
            return Verdict(correct=None, reason="нет выдержек для сверки")

        # ССЫЛКИ ИЗ ОТВЕТА УБИРАЕМ. Иначе в одном промпте живут ДВЕ
        # несовместимые нумерации.
        #
        # Ответ системы размечен ссылками на фрагменты её собственного
        # контекста: «...не более 14 дней [4]». Выдержки судье мы нумеруем
        # заново и своим счётом — их две, три, от силы шесть. Судья видит в
        # ответе «[4]», принимает это за номер выдержки и ссылается на
        # выдержку [4], которой не существует.
        #
        # Именно это и случилось: четыре вердикта из 96 отброшены с причиной
        # «судья сослался на выдержку [4], которой нет (их 2)». И все четыре
        # вердикта были ВЕРНЫ, а их обоснования дословно цитировали настоящий
        # текст документа. То есть прибор выбросил четыре правильных
        # измерения из-за нашей же путаницы в нумерации — и выглядело это как
        # неисправность судьи.
        #
        # Аналогия: дать эксперту документ, где абзацы пронумерованы дважды —
        # типографской нумерацией и рукописной на полях, — и требовать ссылок
        # «по номеру абзаца». Эксперт не виноват.
        cleaned = _CITATION_MARK.sub("", answer).strip()

        user = (
            f"<выдержки>\n{excerpts}\n</выдержки>\n\n"
            f"Вопрос сотрудника: {question.question}\n\n"
            f"Ответ системы:\n{cleaned or '(пусто)'}"
        )

        raw, thinking, finish, usage = await self._call(user, think=self._think)

        # Диагностика прикладывается к вердикту, а не пишется в лог.
        #
        # Первая версия отдавала «вердикт не разобран» и пустую строку — и по
        # этому сообщению нельзя было понять ничего. Оказалось, что модель
        # израсходовала весь лимит токенов на размышления, а ответ не начался:
        # видно это только по причине остановки и по числу токенов, которых в
        # сообщении не было.
        diagnosis = f"finish={finish} токенов={usage}"
        if thinking:
            diagnosis += f" размышления({len(thinking)} симв.)={thinking[:200]!r}"

        candidate = extract_json_object(raw)
        if candidate is None and thinking:
            # JSON мог уехать в канал размышлений целиком — бывает, когда
            # провайдер относит к размышлениям всё до первого «ответного»
            # токена. Ищем там тоже, прежде чем сдаваться.
            candidate = extract_json_object(thinking)
        try:
            payload = json.loads(candidate) if candidate else None
            if payload is None:
                raise json.JSONDecodeError("объекта JSON в ответе нет", raw or "", 0)
        except (json.JSONDecodeError, TypeError):
            # Судья, чей ответ не разобрался, не превращается в «неверно»:
            # это смещает метрику в сторону пессимизма и выглядит как падение
            # качества системы, хотя сломался прибор.
            return Verdict(
                correct=None,
                reason="вердикт судьи не разобран"
                if raw.strip()
                else "судья вернул пустой ответ",
                raw=f"{diagnosis} | ответ={raw[:300]!r}",
            )

        if not isinstance(payload, dict) or not isinstance(payload.get("correct"), bool):
            # Схема требовала булево. Пришло что-то другое — значит провайдер
            # схему не применил, и «мягкое» приведение к False здесь такая же
            # ложь, как в предыдущей ветке.
            return Verdict(
                correct=None,
                reason="в вердикте нет поля correct",
                raw=f"{diagnosis} | ответ={raw[:300]!r}",
            )

        labels = self.labels_for(question)
        try:
            fragment = int(payload.get("fragment") or 0)
        except (TypeError, ValueError):
            fragment = -1

        if fragment < 0 or fragment > len(labels):
            # Ссылка на выдержку, которой нет. Это единственное, что номер
            # позволяет поймать механически, — и этого достаточно, чтобы
            # отсеять вердикт, вынесенный не глядя.
            return Verdict(
                correct=None,
                reason=f"судья сослался на выдержку [{payload.get('fragment')}], "
                       f"которой нет (их {len(labels)})",
                fragment=fragment,
                raw=f"{diagnosis} | вердикт был {payload['correct']!r}: "
                    f"{str(payload.get('reason', ''))[:200]}",
            )

        if fragment == 0:
            # «Ни одна выдержка не решает» — это состояние НАШЕЙ сборки
            # выдержек, а не свойство ответа. Поэтому вердикт не принимается
            # ни в какую сторону.
            #
            # Раньше так отбрасывалось только «верно», а «неверно» с нулевой
            # опорой засчитывалось в judge_ok как плохой ответ системы. Эта
            # асимметрия систематически тянула метрику вниз: судья показывал
            # «система ответила неверно на N вопросов», хотя честный вывод —
            # «сверять было нечем на N вопросов». Наказывать систему за то,
            # что мы не дали судье нужный текст, нельзя.
            return Verdict(
                correct=None,
                reason="судья не нашёл в выдержках ничего, на что опереться",
                fragment=0,
                raw=f"{diagnosis} | причина была: {str(payload.get('reason', ''))[:200]}",
            )

        return Verdict(
            correct=payload["correct"],
            reason=str(payload.get("reason", ""))[:300],
            fragment=fragment,
            fragment_label=labels[fragment - 1] if fragment else "(ни одна не решает)",
            raw=raw[:500],
        )

    async def _call(self, user: str, *, think: bool | None):
        """Один вызов судьи. Возвращает (ответ, размышления, причина, токены).

        Переключатель размышлений понимают не все модели: у не-рассуждающей
        провайдер на него ответит 400. Поэтому при такой ошибке вызов
        повторяется БЕЗ переключателя — один раз, только на этот случай.

        Это не общий «повтор при ошибке» (тот живёт в провайдере и разбирает
        коды): это подстройка под возможности конкретной модели, и место ей
        здесь, рядом с знанием о том, зачем переключатель нужен.
        """
        request = ChatRequest(
            system=JUDGE_SYSTEM,
            user=user,
            temperature=0.0,
            max_tokens=self._max_tokens,
            seed=self._seed,
            json_schema=JUDGE_SCHEMA,
            think=think,
        )

        raw = ""
        thinking = ""
        finish = ""
        usage = ""
        try:
            async for chunk in self._provider.chat_stream(request):
                if chunk.text:
                    raw += chunk.text
                if chunk.thinking:
                    thinking += chunk.thinking
                if chunk.done:
                    finish = chunk.finish_reason.value if chunk.finish_reason else ""
                    usage = (
                        f"{chunk.usage.completion_tokens}/{self._max_tokens}"
                        if chunk.usage
                        else ""
                    )
        except ProviderError as error:
            if think is not None and error.status == 400 and "think" in str(error).lower():
                self._think = None
                return await self._call(user, think=None)
            raise

        return raw, thinking, finish, usage


def agreement_table(judge: list[bool], human: list[bool]) -> dict:
    """Таблица согласия: где судья строже человека, а где мягче.

    Средняя каппа не говорит, в какую сторону судья врёт, а это важно: мягкий
    судья завышает метрики (и это опаснее), строгий — занижает.
    """
    both_yes = sum(1 for j, h in zip(judge, human) if j and h)
    both_no = sum(1 for j, h in zip(judge, human) if not j and not h)
    judge_softer = sum(1 for j, h in zip(judge, human) if j and not h)
    judge_stricter = sum(1 for j, h in zip(judge, human) if not j and h)

    return {
        "оба «верно»": both_yes,
        "оба «неверно»": both_no,
        "судья мягче человека": judge_softer,
        "судья строже человека": judge_stricter,
        "совпадений": both_yes + both_no,
        "всего": len(judge),
    }
